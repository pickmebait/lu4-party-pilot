/**
 * Права в разделе целей.
 *
 * Цели общие для пати, и это единственное место, где токен персонажа имеет
 * право что-то завести: раньше хотелку мог завести только мастер, из-за чего
 * завести цель для себя мог лишь тот, кто держит мастер-токен.
 *
 * Проверка смотрит в исходники, потому что права живут в браузерном хранилище,
 * а оно в node не запускается. Зато видно то, что сервер проверить не может:
 * сервер сверяет документ целиком и не знает, кто что нажимал.
 */
import fs from 'fs'

let провалено = 0
const шаг = (ok, что, детали = '') => {
  if (ok) console.log(`  ok    ${что}`)
  else {
    провалено++
    console.log(`  СБОЙ  ${что}${детали ? ` — ${детали}` : ''}`)
  }
}

const цели = fs.readFileSync('src/components/Goals.tsx', 'utf8')
const модель = fs.readFileSync('src/lib/goals.ts', 'utf8')
const хранилище = fs.readFileSync('src/lib/store.ts', 'utf8')
const пикер = fs.readFileSync('src/components/ItemPicker.tsx', 'utf8')
const склад = fs.readFileSync('src/components/Warehouse.tsx', 'utf8')
const app = fs.readFileSync('src/App.tsx', 'utf8')
const сплющено = (текст) => текст.replace(/\s+/g, ' ')

/**
 * Тело функции по имени — до закрывающей скобки на строке.
 *
 * Именно indexOf, а не search: у search нет второго аргумента «с какого места
 * искать», и он нашёл бы первую скобку во всём файле — проверка прошла бы,
 * ничего не проверяя.
 */
const тело = (текст, имя) => {
  const начало = текст.indexOf(`export function ${имя}`)
  if (начало < 0) return ''
  const конец = текст.indexOf('\n}', начало)
  return конец < 0 ? текст.slice(начало) : текст.slice(начало, конец + 2)
}

console.log('\nПрава в разделе целей')

const вести = тело(хранилище, 'можетВестиЦель')
шаг(
  /if \(кто\.role !== 'char'\) return true/.test(вести) &&
    /создатель === кто\.charId/.test(вести),
  'мастер ведёт любую цель, токен персонажа — только свою',
  'правило «создатель или мастер» разъехалось',
)

шаг(
  /создатель === кто\.charId/.test(вести),
  'цель без создателя не достаётся никому из персонажей',
  'иначе токен персонажа смог бы закрыть чужую цель, заведённую до появления поля',
)

const создатьДля = тело(хранилище, 'можетСоздаватьДля')
шаг(
  /if \(кто\.role !== 'char'\) return true/.test(создатьДля) && /charId === кто\.charId/.test(создатьДля),
  'мастер заводит цель для кого угодно, персонаж — только для себя',
)

шаг(
  /\.filter\(\(c\) => master \|\| c\.id === ownCharId\)/.test(цели) &&
    /disabled=\{!master\}/.test(цели),
  'в форме нет чужих персонажей для токена персонажа',
  'выбор «для кого» показывает чужих, а кнопка всё равно заблокирована',
)

шаг(
  /создатель: ownCharId \?\? 'Мастер'/.test(цели),
  'цель запоминает, кто её завёл',
  'без этого поле остаётся пустым и закрыть цель сможет один мастер',
)

шаг(
  /можетСоздаватьДля\(общее\.forCharId\)/.test(цели),
  'кнопка создания спрашивает права, а не только наличие предметов',
)

шаг(
  /disabled=\{!моя \|\| !!цель\.rejected\}/.test(цели),
  'предмет чужой цели нельзя отметить добытым',
)

шаг(
  /\{моя && \(\s*<footer/.test(сплющено(цели)) && /removeGoal\(цель\.id\)/.test(цели),
  'инструменты цели показываются только её создателю',
)

/* -------------------------------------------------------- модель цели */

шаг(
  /export type СтатусЦели = 'активная' \| 'выполнена' \| 'отклонена'/.test(модель),
  'у цели три состояния, а не два',
)

// Выполненность выводится из предметов, а не хранится рядом с ними: хранить
// оба — значит завести два источника правды и однажды получить выполненную
// цель, в которой ничего не добыто.
шаг(
  /export function цельВыполнена[\s\S]*?цель\.items\.every/.test(модель) &&
    !/done: boolean/.test(модель),
  'выполненность цели выводится из всех её предметов',
  'иначе у цели появятся два независимых признака готовности',
)

шаг(
  /rejected: предметы\.some\(\(п\) => !п\.готово\)[\s\S]*?\.rejected === true/.test(модель),
  'выполненная цель не может быть отклонённой',
  'состояние, которого быть не может, сорвёт расчёты',
)

// Пачка предметов — одна запись, а не по записи на предмет.
шаг(
  /items: пачка\.map/.test(цели) && /addGoal\(\{/.test(цели),
  'пачка предметов заводится одной целью',
  'иначе прогресс и список добытых снова разъедутся по записям',
)

шаг(
  /Array\.isArray\(d\.goals\) \? d\.goals : \(d as \{ wishes\?: unknown \}\)\.wishes/.test(
    хранилище,
  ),
  'старые базы читаются, а не выбрасываются',
  'перенос со старой формы обязателен: иначе чужие цели исчезнут при обновлении',
)

шаг(
  /МНОЖЕСТВЕННЫЙ_ПОТОЛОК = 15/.test(пикер) && /export const МНОЖЕСТВЕННЫЙ_ПОТОЛОК/.test(пикер),
  'потолок выбора предметов один на всё приложение',
  'два числа означают, что одно из них перестанет действовать',
)

/* ------------------------------------------- переименования и переезды */

шаг(/\{ key: 'wishes', label: 'Цели' \}/.test(app), 'раздел называется «Цели»')

шаг(
  !/label: 'Хотелки'/.test(app) && !/label: 'Комплекты'/.test(app),
  'старых названий вкладок не осталось',
)

шаг(
  !/tab === 'sets'/.test(app) && !/SetsView/.test(app),
  'раздел комплектов убран, комплекты живут в казне',
)

шаг(/<SetsBlock catalog=\{catalog\} \/>/.test(склад), 'блок комплектов встроен в раздел казны')

console.log('')
console.log(провалено === 0 ? 'ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ' : `ПРОВАЛЕНО: ${провалено}`)
process.exit(провалено === 0 ? 0 : 1)