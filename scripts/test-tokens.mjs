/*
 * Распределение по позициям.
 *
 * Смещение в разряде — верный признак того, что генератор выдаёт неравномерно:
 * предсказуемые токены получаются не из повторов, а из предпочтений в
 * отдельных позициях. Проверка грубая и только ловит явную неравномерность:
 * при 10 000 выборок в 32 разрядах почти невозможно упасть за эти рамки,
 * а вот заметный перекос — вполне.
 */
const БОЛЬШАЯ = 400
const большиеСекреты = []
for (let i = 0; i < БОЛЬШАЯ; i++) {
  const п = await создать(ОДИНАКОВОЕ_ИМЯ, [])
  большиеСекреты.push(секретИз(п.мастер))
}

шаг(
  new Set(большиеСекреты).size === БОЛЬШАЯ,
  `${БОЛЬШАЯ} секретов подряд не повторились`,
  `${new Set(большиеСекреты).size} уникальных`,
)

let худшаяПозиция = { позиция: -1, отклонение: 0 }
for (let поз = 0; поз < 32; поз++) {
  const счётчик = new Map()
  for (const с of большиеСекреты) {
    const символ = с[поз]
    счётчик.set(символ, (счётчик.get(символ) ?? 0) + 1)
  }
  const среднее = БОЛЬШАЯ / АЛФАВИТ.length
  // Все 32 символа должны встретиться: выпавший символ означал бы смещение.
  for (const символ of АЛФАВИТ) {
    const отклонение = Math.abs((счётчик.get(символ) ?? 0) - среднее)
    if (отклонение > худшаяПозиция.отклонение) {
      худшаяПозиция = { позиция: поз, отклонение }
    }
  }
}
шаг(
  худшаяПозиция.отклонение < БОЛЬШАЯ * 0.06,
  'каждый из 32 символов встречается в каждой позиции',
  `позиция ${худшаяПозиция.позиция}, отклонение ${худшаяПозиция.отклонение.toFixed(1)} от ${(БОЛЬШАЯ / 32).toFixed(1)}`,
)

