/** Создаёт пати с заранее заданным названием и набором персонажей. */
async function создать(имяПати, ники) {
  const создан = await call('/api/party', { method: 'POST', body: { name: имяПати } })
  if (создан.status !== 200) throw new Error('создание не вышло: ' + создан.json?.error)
  const мастер = создан.json.token

  const пусто = await call('/api/party/data', { token: мастер })
  const база = {
    version: 8,
    updatedAt: пусто.json.updatedAt,
    updatedBy: 'Мастер',
    chars: ники.map((ник, i) => ({
      id: `c${i}`,
      name: ник,
      cls: 'Knight',
      level: 80,
      affil: 'состав',
      slots: {},
      subs: [],
      subUnlocked: false,
      contacts: {},
      away: {},
      pa: null,
    })),
    warehouse: { stacks: [], log: [] },
    wishes: [],
    sets: [],
    schedule: { prime: {}, offs: [], checklist: [] },
    customNames: {},
  }
  await call('/api/party/data', {
    method: 'PUT',
    token: мастер,
    body: { db: база, baseUpdatedAt: пусто.json.updatedAt },
  })

  const токеныПерсонажей = []
  for (let i = 0; i < ники.length; i++) {
    const выпущен = await call('/api/party/tokens', {
      method: 'POST',
      token: мастер,
      body: { charId: `c${i}` },
    })
    токеныПерсонажей.push(выпущен.json.token)
  }
  const итог = { partyId: создан.json.partyId, мастер, токеныПерсонажей, имяПати }
  всеСозданные.push(итог)
  return итог
}

