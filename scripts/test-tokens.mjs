/**
 * Аудит токенов доступа.
 *
 * Проверяется ровно то, в чём был вопрос: токен не зависит ни от названия
 * пати, ни от ника персонажа, и две одинаковые по именам пати не получают
 * одинаковые токены. Репозиторий подменён словарём в памяти, настоящий GitHub
 * и серверный токен не нужны.
 *
 * Отдельно проверяется и то, из чего токен складывается: длина секрета,
 * алфавит, отсутствие повторов на большой выборке и то, что секрет не выводится
 * из названия. Проверки на «токены разные» мало: токены будут разными и при
 * слабом источнике случайности, если соль случайна, — но человек, назвавший
 * пати, мог бы догадаться о её токене по названию.
 */
