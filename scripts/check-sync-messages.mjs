/**
 * Проверка сообщений о синхронизации.
 *
 * Проверяется ровно то, что человек читает, и поэтому важнее всего второе:
 * в надписи не должно быть ничего, кроме ответа на вопрос «что произошло и
 * что делать». Техника — адрес, код, метки, ответ сервера — обязана быть под
 * значком, иначе надпись снова станет отчётом, который никто не читает.
 *
 * Проверка идёт по словам, а не по коду компонента: переименовать текст
 * можно свободно, а вот протащить в надпись «HTTP 409» нельзя.
 */
import { build } from 'esbuild'
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const ТЕСТ = `
import { СЛОВА, деталиЗапроса, ктоПравил, приОбрыве, приОтказе, приПовторе, приПотерянномОтвете, приУспехе } from '@/lib/syncMessages.ts'

let пройдено = 0
const ошибки: string[] = []
const равно = (подпись, получили, ждём) => {
  пройдено++
  const a = JSON.stringify(получили)
  const b = JSON.stringify(ждём)
  if (a !== b) ошибки.push(подпись + '\\\\n      получили: ' + a + '\\\\n      ждём:     ' + b)
}
const правда = (подпись, условие) => {
  пройдено++
  if (!условие) ошибки.push(подпись)
}
const всеСлова = (объект) =>
  Object.entries(объект).filter(([, значение]) => typeof значение === 'string')

/*
 * Ни одна надпись не должна содержать техники.
 *
 * Список подобран по тому, что действительно всплывало в текстах раньше, и
 * по тому, что легко попадёт снова: коды, адреса, имена полей и слова про
 * устройство обмена. Имя человека в надписи допустимо — оно отвечает на
 * вопрос «чьё это», а вот «от: Ирок, 3 минуты назад» — уже отчёт.
 */
const ЗАПРЕЩЕНО = [
  'HTTP', 'http://', 'https://', '409', '403', '401', '500',
  'код ответа', 'Код ответа', 'метка', 'Метка', 'запрос', 'Запрос',
  'ответ сервера', 'Ответ сервера', 'адрес', 'Адрес',
  'updatedAt', 'updatedBy', 'apiUrl', 'попытк', 'Попытк',
  'ошибка', 'Ошибка', 'exception', 'stack', 'null', 'undefined',
]

for (const [имя, надпись] of всеСлова(СЛОВА)) {
  for (const слово of ЗАПРЕЩЕНО) {
    правда(
      'надпись «' + имя + '» без техники: нет «' + слово + '»',
      !надпись.includes(слово),
    )
  }
}

/*
 * Надпись должна быть короткой.
 *
 * Длинная строка в шапке переносится и занимает три строки, отодвигая всё,
 * что под ней. Порог взят с запасом: самая длинная осмысленная надпись —
 * «В пати есть свежая версия. Твоя правка подставится в неё сама», и она
 * должна уместиться.
 */
for (const [имя, надпись] of всеСлова(СЛОВА)) {
  правда('надпись «' + имя + '» короче 80 знаков (сейчас ' + надпись.length + ')', надпись.length <= 80)
}

/*
 * Главное в неудаче — сказано ли, теряется правка или нет.
 *
 * Обрыв связи правку не теряет: она лежит в браузере и уйдёт сама. Если об
 * этом не сказать, человек решит самое худшее и начнёт переписывать всё.
 *
 * Проверяется смысл, а не конкретные слова: «правка цела» и «правка не
 * потеряна» говорят одно и то же, и переписывать надпись не придётся из-за
 * того, что формулировку поменяли.
 */
правда('обрыв говорит, что правка цела', /цела|не потеряна|не пропала/.test(СЛОВА.нетСвязи))
правда('обрыв обещает повторить сам', /сама|сам|повтор/.test(СЛОВА.нетСвязи))
правда('отказ говорит, что правка не сохранена', СЛОВА.правкаНеСохранена.includes('не сохранена'))
правда('успех назван словом, а не молчанием', СЛОВА.сохранено.length > 0)

/* Успех должен убираться сам, неудача — никогда. */

правда('успех убирается', приУспехе().убратьЧерезМс > 0)
правда('повтор убирается', приПовторе().убратьЧерезМс > 0)
правда('потерянный ответ убирается', приПотерянномОтвете().убратьЧерезМс > 0)
правда('неудача не убирается сама', приОбрыве() === undefined || приОбрыве().убратьЧерезМс === undefined)
правда('отказ не убирается сама', приОтказе('x', 409).убратьЧерезМс === undefined)

/* Подробности обязаны быть на месте, и обязаны содержать технику. */

const подробности = деталиЗапроса({ адрес: 'https://пример', вид: 'запись базы', код: 409, попыток: 2, меткаСервера: 'м1', меткаСвоя: 'м0', текстСервера: 'отказ' })
правда('в подробностях есть адрес', подробности.includes('https://пример'))
правда('в подробностях есть код', подробности.includes('409'))
правда('в подробностях есть попытки', подробности.includes('2'))
правда('в подробностях есть обе метки', подробности.includes('м1') && подробности.includes('м0'))
правда('в подробностях есть ответ сервера', подробности.includes('отказ'))

/* Обрыв отличается от отказа в подробностях, а не только в надписи. */

правда('обрыв объясняет отсутствие ответа', деталиЗапроса({ код: 0 }).includes('обрыв'))
правда('отказ с кодом не выглядит обрывом', деталиЗапроса({ код: 403 }).includes('403'))
правда('без кода честно молчит', деталиЗапроса({}).includes('Код ответа: —'))
правда('успешная запись не выглядит обрывом', !деталиЗапроса({ код: 200 }).includes('обрыв'))

/* Кто правил — тоже подробность, а не надпись. */

правда('кто правил собран', ктоПравил({ updatedBy: 'Ирок', updatedAt: new Date().toISOString() }).includes('Ирок'))
правда('без автора не выдумываем', ктоПравил({ updatedBy: null, updatedAt: new Date().toISOString() }).includes('неизвестно'))
равно('без базы — нет данных', ктоПравил(undefined), 'нет данных')

/* Надпись про чужую правку должна говорить, что будет дальше. */

правда('сказано, что правка ляжет поверх', /ляжет|подставится/.test(СЛОВА.вПаТИИзменилосьПодставится))

export default { пройдено, ошибки }
`

const папка = mkdtempSync(join(tmpdir(), 'сообщения-'))
const вход = join(папка, 'тест.mts')
const выход = join(папка, 'тест.mjs')
writeFileSync(вход, ТЕСТ, 'utf8')

try {
  await build({
    entryPoints: [вход],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    outfile: выход,
    logLevel: 'silent',
    alias: { '@': new URL('../src', import.meta.url).pathname.replace(/^[/\\]([A-Za-z]:)/, '$1') },
  })
  const модуль = await import(pathToFileURL(выход).href)
  const { пройдено, ошибки } = модуль.default
  if (ошибки.length) {
    console.error(`ПРОВАЛЕНО ${ошибки.length} из ${пройдено}:`)
    for (const о of ошибки) console.error('  ✗ ' + о)
    process.exit(1)
  }
  console.log(`ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ (${пройдено})`)
} finally {
  rmSync(папка, { recursive: true, force: true })
}
