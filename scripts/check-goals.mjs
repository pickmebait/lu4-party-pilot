/**
 * Проверка модели целей: разбор базы, прогресс и статусы.
 *
 * Отдельный файл, а не строчка в check-analytics: модель нужна и расчётам, и
 * хранилищу, и именно тут живёт перенос со старой формы. Перенос проверяется
 * отдельно и подробнее всего — выбросить чужую цель при смене формата хуже
 * всего, что может случиться с молчаливым обновлением.
 */
import { build } from 'esbuild'
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const ТЕСТ = `
import {
  normalizeGoals,
  прогрессЦели,
  цельВыполнена,
  статусЦели,
  закрытаВ,
} from '@/lib/goals.ts'

let пройдено = 0
const ошибки: string[] = []
const равно = (подпись, получили, ждём) => {
  пройдено++
  const a = JSON.stringify(получили)
  const b = JSON.stringify(ждём)
  if (a !== b) ошибки.push(подпись + '\\n      получили: ' + a + '\\n      ждём:     ' + b)
}
const правда = (подпись, условие) => {
  пройдено++
  if (!условие) ошибки.push(подпись)
}

/* ------------------------------- перенос со старой формы: цель = предмет */

const старая = normalizeGoals([
  {
    id: 'w1', itemId: 300, count: 2, priority: 1, seeker: 'Вера',
    forCharId: 'c3', note: 'с аукциона', done: false,
  },
  {
    id: 'w2', itemId: 301, mod: 14, count: 1, priority: 2, seeker: 'Бетта',
    done: true, doneAt: '2026-10-11T12:00:00.000Z',
  },
])

равно('старая хотелка не теряется', старая.length, 2)
равно('у неё один предмет', старая[0].items.length, 1)
равно('предмет сохранил id и количество', [старая[0].items[0].itemId, старая[0].items[0].count], [300, 2])
равно('заточка перенеслась', старая[1].items[0].mod, 14)
равно('выполненная хотелка стала добытым предметом', старая[1].items[0].готово, true)
равно('дата выполнения стала датой добытия', старая[1].items[0].готовоAt, '2026-10-11T12:00:00.000Z')
равно('создатель и примечание на месте', [старая[0].создатель, старая[0].note], [undefined, 'с аукциона'])
равно('старая выполненная цель выполнена и по-новому', цельВыполнена(старая[1]), true)

/*
 * Настоящая запись из базы, где живут цели.
 *
 * Взята дословно, а не придумана: перенос старой формы обязан сохранить
 * чужую работу, и проверять это нужно на том, что действительно лежит у
 * людей, а не на удобном примере. Здесь закрытая цель с примечанием и без
 * создателя — значит закроет её только мастер, и это правильно.
 */
const настоящая = normalizeGoals([
  {
    id: 'wmvcnnwoc1cfza6',
    done: true,
    itemId: 548,
    count: 1,
    priority: 2,
    seeker: 'PickMe',
    forCharId: 'cmvbewm5c13gfov',
    note: 'Куплю до 4кк',
    doneAt: '2026-10-17T17:13:33.554Z',
  },
])[0]

равно('настоящая цель не потерялась', !!настоящая, true)
равно('предмет на месте', настоящая.items[0].itemId, 548)
равно('считается добытым', настоящая.items[0].готово, true)
равно('дата добытия сохранена', настоящая.items[0].готовоAt, '2026-10-17T17:13:33.554Z')
равно('примечание сохранено', настоящая.note, 'Куплю до 4кк')
равно('адресат сохранён', настоящая.forCharId, 'cmvbewm5c13gfov')
равно('статус — выполнена', статусЦели(настоящая), 'выполнена')
равно('создателя нет — закроет только мастер', настоящая.создатель === undefined, true)

/* ------------------------------------------- смешанный список старых и новых */

const смешанные = normalizeGoals([
  { id: 'g1', priority: 2, seeker: 'Алекс', items: [{ itemId: 400, count: 1, готово: true }] },
  { id: 'w9', itemId: 500, count: 1, priority: 1, seeker: 'Бетта', done: false },
])
равно('смешанный список разбирается целиком', смешанные.length, 2)
равно('новая запись не тронута', смешанные[0].items.length, 1)
равно('старая запись рядом с ней разобрана', смешанные[1].items[0].itemId, 500)

/* -------------------------------------------------------------- прогресс */

const цель = normalizeGoals([
  {
    id: 'g1', priority: 1, seeker: 'Алекс',
    items: [
      { itemId: 1, count: 1, готово: true },
      { itemId: 2, count: 1, готово: false },
      { itemId: 3, count: 1, готово: false },
      { itemId: 4, count: 1, готово: true },
    ],
  },
])[0]

равно('прогресс считает добытые и все', прогрессЦели(цель), { готово: 2, всего: 4, процент: 50 })
равно('частично добытая цель активна', статусЦели(цель), 'активная')
равно('частично добытая не выполнена', цельВыполнена(цель), false)

const все = normalizeGoals([
  { id: 'g2', priority: 1, seeker: 'Алекс', items: [{ itemId: 1, count: 1, готово: true }] },
])[0]
равно('цель из одного добытого предмета выполнена', цельВыполнена(все), true)
равно('её статус — выполнена', статусЦели(все), 'выполнена')

/* ------------------------------------------------------------ статусы */

const отказ = normalizeGoals([
  { id: 'g3', priority: 2, seeker: 'Алекс', rejected: true, rejectedAt: '2026-10-01T00:00:00.000Z',
    items: [{ itemId: 1, count: 1, готово: false }] },
])[0]
равно('отказ виден как отказ', статусЦели(отказ), 'отклонена')
равно('дата отказа сохранилась', закрытаВ(отказ), '2026-10-01T00:00:00.000Z')

// Отказ и выполнение одновременно — состояние, которого быть не может.
const невозможно = normalizeGoals([
  { id: 'g4', priority: 2, seeker: 'Алекс', rejected: true, rejectedAt: '2026-10-01T00:00:00.000Z',
    items: [{ itemId: 1, count: 1, готово: true }] },
])[0]
равно('выполненная цель не может быть отклонённой', невозможно.rejected, false)
равно('она остаётся выполненной', статусЦели(невозможно), 'выполнена')

/* ------------------------------------------------- дата закрытия цели */

const поДатам = normalizeGoals([
  { id: 'g5', priority: 1, seeker: 'Алекс', items: [
    { itemId: 1, count: 1, готово: true, готовоAt: '2026-10-01T00:00:00.000Z' },
    { itemId: 2, count: 1, готово: true, готовоAt: '2026-10-09T00:00:00.000Z' },
  ] },
])[0]
равно('цель закрылась последним добытым', закрытаВ(поДатам), '2026-10-09T00:00:00.000Z')
правда('незакрытая цель даты не имеет', закрытаВ(цель) === undefined)

/* -------------------------------------------------------------- мусор */

равно('не массив — пусто', normalizeGoals(null).length, 0)
равно('не массив, а строка — пусто', normalizeGoals('ерунда').length, 0)
равно('запись без предметов отброшена', normalizeGoals([{ id: 'x', priority: 1, seeker: 'Кто' }]).length, 0)
равно('запись с пустым списком отброшена', normalizeGoals([{ id: 'x', priority: 1, seeker: 'Кто', items: [] }]).length, 0)
равно('мусор внутри не роняет разбор', normalizeGoals([null, 'ерунда', 42, {
  id: 'x', priority: 1, seeker: 'Кто', items: [null, { itemId: 5, count: 1 }],
}]).length, 1)
равно('предмет без id не попал', normalizeGoals([{
  id: 'x', priority: 1, seeker: 'Кто', items: [{ itemId: 0 }, { count: 1 }, { itemId: 5, count: 1 }],
}])[0].items.length, 1)

const грязный = normalizeGoals([{
  id: 'x', priority: 'срочно', seeker: 'Кто',
  items: [{ itemId: '400', count: -3, mod: 99 }],
}])[0]
равно('приоритет не из трёх становится средним', грязный.priority, 2)
равно('количество меньше единицы поднято до единицы', грязный.items[0].count, 1)
равно('заточка выше +16 урезана', грязный.items[0].mod, 16)

/* ------------------------------- номер предмета не должен съедать готовность */

const черезMap = normalizeGoals([{
  id: 'x', priority: 1, seeker: 'Кто',
  items: [{ itemId: 1, count: 1 }, { itemId: 2, count: 1, готово: true }],
}])[0]
равно('второй предмет добыт', черезMap.items[1].готово, true)
равно('первый — нет', черезMap.items[0].готово, false)

export default { пройдено, ошибки }
`

const папка = mkdtempSync(join(tmpdir(), 'цели-'))
const вход = join(папка, 'тест.mts')
const выход = join(папка, 'тест.mjs')
writeFileSync(вход, ТЕСТ, 'utf8')

try {
  await build({
    entryPoints: [вход],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    outfile: выход,
    logLevel: 'silent',
    alias: { '@': new URL('../src', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1') },
  })
  const модуль = await import(pathToFileURL(выход).href)
  const { пройдено, ошибки } = модуль.default
  if (ошибки.length) {
    console.error(`ПРОВАЛЕНО ${ошибки.length} из ${пройдено}:`)
    for (const о of ошибки) console.error('  ✗ ' + о)
    process.exit(1)
  }
  console.log(`ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ (${пройдено})`)
} finally {
  rmSync(папка, { recursive: true, force: true })
}