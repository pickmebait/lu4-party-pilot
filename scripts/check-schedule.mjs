/**
 * Проверка правил раздела «Расписание».
 *
 * Правила эти показываются человеку словами и числами, а ломаются тихо:
 * подсказка в клетке календаря разойдётся с подсказкой рядом, а прайм,
 * кончающийся в полночь, начнёт прыгать между 24:00 и 00:00. Ни то, ни
 * другое не бросает исключения — ошибка видна только сверкой с известным
 * ответом, поэтому проверка запускает код, а не читает исходник.
 */
import { build } from 'esbuild'
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const ТЕСТ = `
import {
  absentLabel,
  absencesByDay,
  daysBetween,
  describeAbsence,
  formatDay,
  formatMinutes,
  minutesForField,
  minutesFromField,
  monthGrid,
  offWord,
  parseKey,
  parseMinutes,
  primeOf,
  primeHours,
  weekDays,
  weekendKeys,
} from '@/lib/schedule.ts'

let пройдено = 0
const ошибки: string[] = []
const равно = (подпись, получили, ждём) => {
  пройдено++
  const a = JSON.stringify(получили)
  const b = JSON.stringify(ждём)
  if (a !== b) ошибки.push(подпись + '\\\\n      получили: ' + a + '\\\\n      ждём:     ' + b)
}
const правда = (подпись, условие) => {
  пройдено++
  if (!условие) ошибки.push(подпись)
}

/* ------------------------------------------------- поле времени и полночь */

/*
 * Прайм до утра обычен, и <input type="time"> больше 23:59 не принимает.
 * Полночь поэтому показывается нулём, но внутри остаётся 1440.
 */
равно('полночь в поле — 00:00', minutesForField(24 * 60, true), '00:00')
равно('полночь в начале остаётся полночью', minutesForField(24 * 60, false), '24:00')
равно('обычное время в начале как есть', minutesForField(1260, false), '21:00')
равно('обычное время в конце как есть', minutesForField(1410, true), '23:30')

равно('из поля 00:00 в конце — полночь', minutesFromField('00:00', true), 1440)
равно('из поля 00:00 в начале — ноль', minutesFromField('00:00', false), 0)
равно('из поля 21:00', minutesFromField('21:00', false), 1260)

/*
 * Правило обязано быть обратным. Стоит потерять одну половину — и прайм,
 * кончающийся в полночь, при каждом назначении будет то превращаться в
 * 23:59, то прыгать на следующие сутки.
 */
for (let минут = 1; минут <= 1440; минут += 7) {
  равно(
    'окно переживает перенос в поле и обратно: ' + минут,
    minutesFromField(minutesForField(минут, true), true),
    минут,
  )
}

/*
 * Ноль на конце поля — исключение, и исключение правильное: в поле это
 * полночь, и сохранять её нулём нельзя, потому что ноль в начале окна —
 * это другое время. Поэтому пара приводит ноль к полночи, и обратно уже
 * не отдаёт.
 */
равно('ноль в конце — это полночь', minutesFromField(minutesForField(0, true), true), 1440)

/* ------------------------------------------------------------- отсутствие */

равно('весь день читается словами', describeAbsence({ whole: true }), 'весь день')
равно('окно ухода читается временем', describeAbsence({ whole: false, window: { from: 1260, to: 1410 } }), '21:00–23:30')
равно('окно до полуночи читается как полночь', describeAbsence({ whole: false, window: { from: 1260, to: 1440 } }), '21:00–24:00')

равно('ник без окна остаётся ником', absentLabel('Алекс', { whole: true }), 'Алекс')
равно('ник с окном получает его в скобках', absentLabel('Алекс', { whole: false, window: { from: 1260, to: 1410 } }), 'Алекс (21:00–23:30)')

/* -------------------------------------------------------------- слова и дни */

равно('на одном дне — выходной', offWord(1), 'выходной')
равно('на неделе — выходные', offWord(5), 'выходные')
равно('на месяце — выходные', offWord(31), 'выходные')

равно('день в родительном падеже', formatDay('2026-10-07'), '7 октября')
равно('день с годом', formatDay('2026-10-07', true), '7 октября 2026')
равно('январь тоже в родительном', formatDay('2027-01-01'), '1 января')
равно('декабрь не спутан с другим', formatDay('2026-12-31'), '31 декабря')
равно('однозначное число без ведущего нуля', formatDay('2026-05-09'), '9 мая')

/* ------------------------------------------------------------------ прайм */

равно('минуты печатаются с ведущим нулём', formatMinutes(1260), '21:00')
равно('девять минут тоже с нулём', formatMinutes(545), '09:05')
равно('минуты вне суток обрезаются сверху', formatMinutes(9999), '24:00')
равно('отрицательное не печатается', formatMinutes(-5), '00:00')
равно('разбор времени', parseMinutes('20:30'), 1230)
равно('разбор мусора — ноль', parseMinutes('abc'), 0)
равно('разбор без минут', parseMinutes('20'), 1200)

равно('назначенного прайма нет', primeOf({ offs: [], prime: {}, checklist: [] }, '2026-10-07').kind, 'нет')
равно(
  'назначенное окно читается',
  primeOf({ offs: [], prime: { '2026-10-07': { from: 1260, to: 1410 } }, checklist: [] }, '2026-10-07'),
  { kind: 'окно', window: { from: 1260, to: 1410 } },
)
равно(
  'выходной поверх прайма',
  primeOf({ offs: ['2026-10-07'], prime: { '2026-10-07': { from: 1260, to: 1410 } }, checklist: [] }, '2026-10-07').kind,
  'выходной',
)
равно(
  'выходной без прайма',
  primeOf({ offs: ['2026-10-07'], prime: {}, checklist: [] }, '2026-10-07').kind,
  'выходной',
)

/* ------------------------------------------------------------- выделение */

равно('диапазон включает оба конца', daysBetween('2026-10-05', '2026-10-07'), ['2026-10-05', '2026-10-06', '2026-10-07'])
равно('диапазон из одного дня', daysBetween('2026-10-05', '2026-10-05'), ['2026-10-05'])
равно('перепутанные концы меняются местами', daysBetween('2026-10-07', '2026-10-05'), ['2026-10-05', '2026-10-06', '2026-10-07'])
равно('неделя начинается с понедельника', weekDays('2026-10-07')[0], '2026-10-05')

правда(
  'выходные — только суббота и воскресенье',
  weekendKeys(['2026-10-03', '2026-10-04', '2026-10-05']).join() === '2026-10-03,2026-10-04',
)

/* ------------------------------------------------------- отсутствия по дням */

const пати = [
  { id: 'c1', name: 'Алекс', away: { '2026-10-07': { whole: true }, '2026-10-08': { whole: false, window: { from: 1260, to: 1410 } } } },
  { id: 'c2', name: '', away: { '2026-10-07': { whole: false, window: { from: 60, to: 120 } } } },
  { id: 'c3', name: 'Без отметок', away: {} },
]
const карта = absencesByDay(пати, ['2026-10-07', '2026-10-08', '2026-10-09'])
равно('в первом дне двое', карта.get('2026-10-07').length, 2)
равно('во втором один', карта.get('2026-10-08').length, 1)
правда('в третьем никого нет', !карта.has('2026-10-09'))
равно('безымянный не остаётся безымянным', карта.get('2026-10-07')[1].имя, 'Без имени')

/* ------------------------------------------------------------- календарь */

const клетки = monthGrid(parseKey('2026-10-07'))
правда('в месяце от 28 до 42 клеток', клетки.length >= 28 && клетки.length <= 42)
правда('во всех клетках есть ключ', клетки.every((к) => /^\\d{4}-\\d{2}-\\d{2}$/.test(к.key)))
равно('дни месяца не повторяются', new Set(клетки.map((к) => к.key)).size, клетки.length)

/* ------------------------------------------------------- часы прайма */

равно(
  'часы считаются по длительности окна',
  primeHours({ offs: [], prime: { '2026-10-07': { from: 1260, to: 1410 } }, checklist: [] }, parseKey('2026-10-07')),
  2.5,
)
равно(
  'выходной ничего не отнимает',
  primeHours({ offs: ['2026-10-08'], prime: {}, checklist: [] }, parseKey('2026-10-08')),
  0,
)

export default { пройдено, ошибки }
`

const папка = mkdtempSync(join(tmpdir(), 'расписание-'))
const вход = join(папка, 'тест.mts')
const выход = join(папка, 'тест.mjs')
writeFileSync(вход, ТЕСТ, 'utf8')

try {
  await build({
    entryPoints: [вход],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    outfile: выход,
    logLevel: 'silent',
    alias: { '@': new URL('../src', import.meta.url).pathname.replace(/^[/\\]([A-Za-z]:)/, '$1') },
  })
  const модуль = await import(pathToFileURL(выход).href)
  const { пройдено, ошибки } = модуль.default
  if (ошибки.length) {
    console.error(`ПРОВАЛЕНО ${ошибки.length} из ${пройдено}:`)
    for (const о of ошибки) console.error('  ✗ ' + о)
    process.exit(1)
  }
  console.log(`ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ (${пройдено})`)
} finally {
  rmSync(папка, { recursive: true, force: true })
}
