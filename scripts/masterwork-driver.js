/**
 * Драйвер выкачки для страницы masterwork.wiki.
 *
 * Вставляется в консоль браузера после того, как страница прошла проверку.
 * Дальше работает сам и не требует участия:
 *
 *   - тянет карточки по одной с паузой (MW_ПАУЗА, по умолчанию 3000 мс);
 *   - каждые ПОРЦИЯ предметов отправляет порцию на локальный сервер
 *     scripts/serve-scrape.mjs, который складывает её в data/masterwork/parts;
 *   - при обрыве сессии (защита вики рвёт соединение каждые несколько минут)
 *     сам перезагружает страницу, ждёт проверки браузера, забирает список
 *     предметов и уже собранные id с сервера и продолжает с того же места.
 *
 * Проверить ход:
 *   П.статус()
 * Остановить:
 *   П.стоп()
 */
;(function () {
  if (window.П) return

  const сервер = window.MW_СЕРВЕР || 'http://127.0.0.1:8099'
  const ПОРЦИЯ = Number(window.MW_ПОРЦИЯ || 25)

  const П = {
    работает: false,
    номерЧасти: 0,
    собрано: 0,
    попыткиВосстановления: 0,
    остановлен: '',
    последняяОшибка: '',
    начало: Date.now(),

    /** Пауза между запросами. Задаётся до вставки скрипта: MW_ПАУЗА = 3000 */
    пауза: Number(window.MW_ПАУЗА || 3000),

    старт() {
      if (this.работает) return 'уже работает'
      this.работает = true
      this.остановлен = ''
      this.шаг()
      return 'запущено'
    },

    стоп() {
      this.работает = false
      this.остановлен = 'остановлено вручную'
      return 'остановлено'
    },

    статус() {
      return {
        работает: this.работает,
        собрано: this.собрано,
        номерЧасти: this.номерЧасти,
        минуты: Math.round((Date.now() - this.начало) / 60000),
        восстановлений: this.попыткиВосстановления,
        остановлен: this.остановлен,
        последняяОшибка: this.последняяОшибка,
      }
    },

    async шаг() {
      if (!this.работает) return

      // Страница пережила перезагрузку — поднимаем сборщик заново.
      if (!window.MW) {
        const восстановлено = await this.поднять()
        if (!восстановлено) return this.отдых()
        return
      }

      if (window.MW.готово()) {
        this.работает = false
        this.остановлен = 'выкачка завершена'
        return
      }

      const былоОшибок = Object.keys(window.MW.ошибки).length
      try {
        await window.MW.СобратьПартию(ПОРЦИЯ)
        const всего = Object.keys(window.MW.полный).length
        if (всего > this.собрано) {
          await this.сохранить(всего)
        }
        const сталоОшибок = Object.keys(window.MW.ошибки).length
        if (сталоОшибок > былоОшибок) {
          this.последняяОшибка = 'ошибок за порцию: ' + (сталоОшибок - былоОшибок)
          return this.отдых()
        }
      } catch (e) {
        this.последняяОшибка = String((e && e.message) || e).slice(0, 140)
        return this.отдых()
      }

      setTimeout(() => this.шаг(), 200)
    },

    /** Отправить порцию на локальный сервер. */
    async сохранить(всего) {
      const ids = Object.keys(window.MW.полный)
      const кусок = ids.slice(this.собрано).map((id) => window.MW.полный[id])
      const ответ = await fetch(`${сервер}/save`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          номерЧасти: this.номерЧасти,
          собрано: всего,
          сайт: window.MW.meta.сайт,
          вики: window.MW.meta.вики,
          предметы: кусок,
        }),
      })
      if (!ответ.ok) throw new Error('сервер не принял: HTTP ' + ответ.status)
      this.номерЧасти++
      this.собрано = всего
    },

    /** Загрузить сборщик, список предметов и уже собранные id. */
    async поднять() {
      try {
        this.последняяОшибка = 'поднимаю сборщик'
        const src = await fetch(`${сервер}/masterwork-scrape.js`).then((r) => r.text())
        if (!src.includes('window.MW = MW')) throw new Error('сервер отдал не тот файл')
        ;(0, eval)(src)
        if (!window.MW) throw new Error('сборщик не поднялся')

        this.последняяОшибка = 'беру список предметов'
        const сохранённое = await fetch(`${сервер}/done`).then((r) => r.json())
        const собранные = new Set((сохранённое.ids || []).map(String))

        const состояние = await window.MW.Восстановить(`${сервер}/list.json`, собранные)
        this.собрано = собранные.size
        this.номерЧасти = сохранённое.частей || 0
        this.попыткиВосстановления++
        this.последняяОшибка = ''
        console.log(
          `[MW] восстановлено: всего ${сохранение(состояние)}, осталось ${состояние.осталось}`,
        )
        setTimeout(() => this.шаг(), 1000)
        return true
      } catch (e) {
        this.последняяОшибка = 'не поднялся: ' + String((e && e.message) || e).slice(0, 120)
        return false
      }
    },

    /** Не сдаваться после обрыва: подождать и перезагрузить страницу. */
    отдых() {
      this.остановлен = ''
      setTimeout(() => {
        if (!this.работает) return
        // Сессия мертва — перезагружаем страницу и проходим проверку заново.
        window.MW = undefined
        location.reload()
      }, 30000)
    },
  }

  window.П = П
  console.log('[MW] драйвер готов. Запуск: П.старт()')
})()

/** Вспомогательное: объект состояния в строку. */
function сохранение(состояние) {
  return `${состояние.всего}`
}