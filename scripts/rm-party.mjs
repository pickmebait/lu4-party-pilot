/**
 * Удаление пати по её мастер-токену.
 *
 * Единственный способ убрать базу. Стирать файлы из data/parties вручную не
 * надо: там лежат чужие базы, и удаление файла отнимает у мастера доступ к
 * его же пати — навсегда, потому что отпечаток токена лежит в том же файле.
 *
 * Именно так была потеряна «Примерная пати»: уборка сносила всё, кроме README,
 * под предлогом «проверочные». Проверочной оказалась чужая.
 *
 *   node scripts/rm-party.mjs p2p_..._M_...
 *
 * Если токена нет, база возвращается из истории git целиком, вместе с
 * отпечатком, и токен снова подходит.
 */
import { API_URL } from './lib/api-url.mjs'

const токен = (process.argv[2] ?? '').trim()

/** Только мастерский: токен персонажа удалить пати не может. */
if (!/^p2p_[a-z0-9]+_M_[a-z0-9]{20,40}$/i.test(токен)) {
  console.error('Нужен мастер-токен пати: node scripts/rm-party.mjs p2p_..._M_...')
  console.error('Токен персонажа не подойдёт: удалить пати может только мастер.')
  process.exit(2)
}

/**
 * Связь до workers.dev рвётся примерно в одном запросе из пяти, и удаление
 * повторять нельзя: повтор пришёл бы на уже удалённую пати и вернул бы отказ
 * там, где всё вышло.
 */
let удалось = false
for (let попытка = 0; попытка < 6 && !удалось; попытка++) {
  try {
    const r = await fetch(`${API_URL}/api/party`, {
      method: 'DELETE',
      headers: { Authorization: `Bearer ${токен}` },
      signal: AbortSignal.timeout(20_000),
    })
    const текст = await r.text()
    if (r.ok) {
      console.log('Пати удалена:', текст)
      удалось = true
    } else {
      console.error('Сервер ответил', r.status, ':', текст.slice(0, 200))
      break
    }
  } catch (e) {
    console.error(`Обрыв связи (попытка ${попытка + 1}):`, e.message)
    await new Promise((р) => setTimeout(р, 800))
  }
}

if (!удалось) console.error('Не удалено. База на месте.')
process.exitCode = удалось ? 0 : 1