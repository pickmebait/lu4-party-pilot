/**
 * Поиск классов в стилях, которых нет в разметке.
 *
 * Классы в CSS пишутся руками, а убираются — забыв. После удаления кнопки
 * передачи остался .transfer-list, после переноса подписей блоков — старые
 * правила сетки. Найти их глазами по тысяче строк нереально, а повод
 * повозиться со стилем в том же коммите — есть.
 *
 * Считаются одиночные классы: составные вроде .gear-cell.filled разбираются
 * на части, потому что в разметке они пишутся по отдельности.
 *
 * Запуск: node scripts/audit-css.mjs
 */
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { join } from 'node:path'

const КОРОНЬ = process.cwd()

function файлы(папка, расширения) {
  const out = []
  for (const имя of readdirSync(папка)) {
    const полный = join(папка, имя)
    if (statSync(полный).isDirectory()) out.push(...файлы(полный, расширения))
    else if (расширения.some((р) => имя.endsWith(р))) out.push(полный)
  }
  return out
}

/**
 * Слова исходников и префиксы классов, собираемых в шаблоне.
 *
 * Разбирать атрибут className регуляркой не вышло: в className живут
 * вложенные шаблоны (`` `gear-cell filled ${код ? `g${код}` : ''}` ``), и
 * выражение вида «всё до обратной кавычки» на них ломается. Поэтому
 * берёмся проще — класс считается живым, если его имя встречается в
 * исходниках хоть где-нибудь как отдельное слово. Удалённая кнопка не
 * оставляет после себя слов, а именно это разрушение мы и ловим.
 *
 * Второе правило — про префиксы. `` g${код} `` даёт в исходнике слово «g»,
 * а в стилях живут .g-A, .g0…g16: имени «g-A» в исходниках нет никогда,
 * и без этого правила они помечались бы мёртвыми все шестнадцать.
 *
 * Возвращает { слова, префиксы }.
 */
function словаИсходников() {
  const слова = new Set()
  const префиксы = new Set()
  const разметка = [
    ...файлы(join(КОРОНЬ, 'src'), ['.tsx']),
    join(КОРОНЬ, 'index.html'),
  ]
  for (const файл of разметка) {
    const текст = readFileSync(файл, 'utf8')
    for (const слово of текст.split(/[^A-Za-z0-9_-]+/)) {
      if (/^[a-zA-Z][\w-]*$/.test(слово)) слова.add(слово)
    }
    // Часть имени перед ${ — начало класса, который достраивается в шаблоне.
    for (const m of текст.matchAll(/([a-zA-Z][\w-]*)\$\{/g)) префиксы.add(m[1])
  }
  return { слова, префиксы }
}

const { слова: использованные, префиксы: собираемые } = словаИсходников()
const css = readFileSync(join(КОРОНЬ, 'src', 'styles.css'), 'utf8')

/** Класс, которого нет в исходниках: ни целиком, ни как собираемый в шаблоне. */
function мёртвый(класс) {
  if (использованные.has(класс)) return false
  for (const префикс of собираемые) {
    if (класс.startsWith(префикс) && класс !== префикс) return false
  }
  return true
}

/** Классы, встречающиеся в правилах CSS. */
const вСтилях = new Map()
for (const m of css.matchAll(/\.([a-zA-Z][\w-]*)/g)) {
  if (!вСтилях.has(m[1])) вСтилях.set(m[1], [])
  вСтилях.get(m[1]).push(m.index)
}

const строки = [...вСтилях.entries()]
  .filter(([класс]) => мёртвый(класс))
  .sort((a, b) => b[1].length - a[1].length)

console.log(`Слов в исходниках: ${использованные.size}`)
console.log(`Собираемых в шаблоне: ${собираемые.size} (${[...собираемые].join(', ')})`)
console.log(`Классов в стилях: ${вСтилях.size}`)
console.log(`Классов без разметки: ${строки.length}`)
for (const [класс, места] of строки) {
  const строка = css.slice(0, места[0]).split('\n').length
  console.log(`  .${класс} — ${места.length} раз, первое на строке ${строка}`)
}

if (строки.length) process.exit(1)
