/**
 * Защита от возврата ложного «кто-то опередил».
 *
 * Ошибка была не в сети, а в выборе при конфликте: кнопка «Оставить мою»
 * закрывала выбор, не сдвигая метку пати. Автосохранение через паузу уходило с
 * той же меткой и получало тот же отказ — по кругу, до перезагрузки. Человек
 * правил пати один, а приложение твердило, что кто-то опередил.
 *
 * Живой сервер такую ошибку не покажет: он честно отвечает «база другая».
 * Поэтому проверка смотрит в исходники — ровно то, что можно упустить при
 * разборе запросов.
 */
import fs from 'fs'

let провалено = 0
const шаг = (ok, что, детали = '') => {
  if (ok) console.log(`  ok    ${что}`)
  else {
    провалено++
    console.log(`  СБОЙ  ${что}${детали ? ` — ${детали}` : ''}`)
  }
}

const полоса = fs.readFileSync('src/components/SyncBar.tsx', 'utf8')
const слияние = fs.readFileSync('src/lib/merge.ts', 'utf8')

/*
 * Разметка в исходнике разбита по строкам, и подпись кнопки стоит на своей.
 * Ищем по сплющенному тексту, иначе проверка ищет то, чего в файле нет.
 */
const сплющено = (текст) => текст.replace(/\s+/g, ' ')

console.log('\nВыбор при конфликте')

/** Обработчик кнопки — её onClick, не заходящий за предыдущую кнопку. */
const обработчикКнопки = (подпись) => {
  const текст = сплющено(полоса)
  const надпись = текст.indexOf(подпись)
  if (надпись < 0) return null
  const конец = текст.indexOf('</button>', надпись)
  if (конец < 0) return null
  /*
   * Ищем назад, но не дальше конца предыдущей кнопки: иначе к разметке без
   * обработчика приклеился бы чужой onClick, и проверка прошла бы, ничего не
   * проверяя.
   */
  const свояГраница = текст.lastIndexOf('</button>', надпись - 1) + '</button>'.length
  const открытие = текст.lastIndexOf('onClick', надпись)
  if (открытие < свояГраница) return ''
  return текст.slice(открытие, конец)
}

const оставить = обработчикКнопки('Оставить мою')
шаг(оставить !== null, 'кнопка «Оставить мою» есть')
шаг(
  оставить !== null && оставить.includes('updateSession'),
  '«Оставить мою» сдвигает метку пати',
  'без этого автосохранение уходит со старой меткой и получает тот же отказ',
)
шаг(
  оставить !== null && оставить.includes('сохранить()'),
  '«Оставить мою» действительно записывает своё поверх чужого',
  'иначе кнопка обещает выбор, которого нет',
)

/* ------------------------------------------------- сессия читается на месте */

console.log('\nМетка не устаревает внутри полосы')

const телоЗагрузки = полоса.slice(полоса.indexOf('const загрузить = useCallback'))
const телоСохранения = полоса.slice(полоса.indexOf('const сохранить = useCallback'))

шаг(
  телоЗагрузки.includes('const живое = getSession()'),
  'загрузка берёт метку из сессии на месте, а не из замыкания',
  'замыкание хранит метку на момент отрисовки — и откатывало базу назад',
)
шаг(
  телоСохранения.includes('const живое = getSession()'),
  'сохранение берёт метку из сессии на месте, а не из замыкания',
  'сохранение по старой метке гарантированно получало отказ',
)
шаг(
  /remote\.updatedAt[\s\S]{0,80}<\s*\(живое\.lastSyncedAt/.test(телоЗагрузки),
  'загрузка не применяет ответ, переставший быть свежим',
  'старый ответ откатывал базу, и следующая правка уходила от старой метки',
)

/* -------------------------------------------- отказ после своей же записи */

console.log('\nОтказ после собственной записи')

шаг(
  /export function одноИТоЖе/.test(слияние),
  'на клиенте есть сравнение баз по содержанию',
)
шаг(
  /delete копия\.updatedAt[\s\S]*delete копия\.updatedBy/.test(слияние),
  'сравнение не считает служебные метки',
  'их ставит сервер, и при повторе запроса они не обязаны совпасть',
)
шаг(
  телоСохранения.includes('одноИТоЖе(res.conflict'),
  'при отказе сверяется, не лежит ли в пати уже наше',
  'запись могла лечь, а ответ потеряться — тогда это не чужое действие',
)

/* ------------------------------------------------------- ожидания связи */

console.log('\nОбрыв связи замечается быстро')

/*
 * Замер двадцати живых записей: удачные укладываются в 1,3–2,1 секунды,
 * обрыв после этого проходит с повтором за 270–350 миллисекунд. Переиспользование
 * соединения проверено отдельно и ни при чём: за двадцать запросов подряд
 * разницы между соединениями нет вовсе.
 *
 * Значит обрыв — разовая заминка, и важно только то, как долго мы его не
 * замечаем. Возврат длинных ожиданий означает минуту молчания вместо трёх
 * секунд, и это ровно то, что человек описывает как «часто обрывается связь».
 */
const api = fs.readFileSync('src/lib/api.ts', 'utf8')

const число = (метка) => {
  const m = api.match(new RegExp(`${метка} = (\\d[\\d_]*)`))
  if (!m) return null
  return Number(m[1].replace(/_/g, ''))
}

const ожиданиеЧтения = число('ОЖИДАНИЕ_ОТВЕТА_МС')
const ожиданиеЗаписи = число('ОЖИДАНИЕ_ЗАПИСИ_МС')
const ожиданиеПослеОбрыва = число('ПОСЛЕ_ОБРЫВА_МС')

шаг(ожиданиеЧтения !== null, 'предел ожидания чтения объявлен')
шаг(ожиданиеЗаписи !== null, 'предел ожидания записи объявлен')
шаг(ожиданиеПослеОбрыва !== null, 'короткое ожидание после обрыва объявлено')

шаг(
  ожиданиеЧтения !== null && ожиданиеЧтения <= 8000,
  'ожидание чтения не длиннее восьми секунд',
  `сейчас ${ожиданиеЧтения} мс`,
)
шаг(
  ожиданиеЗаписи !== null && ожиданиеЗаписи <= 6000,
  'ожидание записи не длиннее шести секунд',
  `сейчас ${ожиданиеЗаписи} мс`,
)
шаг(
  ожиданиеПослеОбрыва !== null && ожиданиеПослеОбрыва <= 3000,
  'после обрыва ждём не дольше трёх секунд',
  `сейчас ${ожиданиеПослеОбрыва} мс`,
)

шаг(
  /отправить\(ПОСЛЕ_ОБРЫВА_МС\)/.test(api),
  'повтор после обрыва идёт с коротким ожиданием',
  'иначе обрыв растягивается на два полных предела подряд',
)
шаг(
  /обрывовПодряд > 0/.test(api),
  'следующий запрос после обрыва тоже ждёт коротко',
  'иначе второй обрыв подряд снова стоит полного ожидания',
)
шаг(
  /обрывовПодряд = 0/.test(api),
  'удачный ответ снова возвращает полное ожидание',
  'иначе короткое ожидание залипнет навсегда',
)

/* ---------------------------------------------------- великая база видна */

console.log('\nО великой базе говорят заранее')

/*
 * Предел в 33 000 байт стоит на приёме тела: тело крупнее до воркера не
 * доходит, и сервер не может отказать — он его не видит. Значит сказать
 * заранее может только клиент, и молчание в девятнадцать секунд тут хуже всего.
 */
шаг(
  /const ПРЕДЕЛ_ОТПРАВКИ = 30_000/.test(api),
  'предел отправки объявлен',
)
шаг(
  /свернуто\.велик/.test(api),
  'saveDb проверяет велик ли запрос',
)
шаг(
  /if \(свернуто\.велик\) \{\s*return \{\s*ok: false/.test(api),
  'на великую базу отказ возвращается, а запрос не уходит',
)
шаг(
  /База не влезает в отправку/.test(api),
  'отказ называет, что именно не так',
)
шаг(
  /тело\.length > ПРЕДЕЛ_ОТПРАВКИ/.test(api),
  'проверка идёт по длине тела, а не по базе',
  'база проверяется до сжатия и всегда «велика», хотя это неправда',
)

/* ------------------------------------------------------- правдивый текст */

шаг(
  !полоса.includes('Кто-то опередил'),
  'надпись «кто-то опередил» убрана',
  'при одном редакторе она выглядит как ложь',
)

console.log('')
console.log(провалено === 0 ? 'ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ' : `ПРОВАЛЕНО: ${провалено}`)
process.exit(провалено === 0 ? 0 : 1)