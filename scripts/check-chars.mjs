const id = addChar({ name: 'Наборы', cls: 'Abyss Walker', level: 75 })
setSubUnlocked(id, true)
const subId = addSub(id)
правда('саб создан для проверки наборов', typeof subId === 'string')

const main = { charId: id, subId: null }
const sub = { charId: id, subId }
const сейчас = () => getDb().chars.find((c) => c.id === id)
const наборы = () => сейчас().extraWeaponSets ?? []
const наборыСаба = () => сейчас().subs.find((s) => s.id === subId)?.extraWeaponSets ?? []

равно('второй набор получает номер 1', addWeaponSet(main), 1)
равно('третий набор получает номер 2', addWeaponSet(main), 2)
равно('четвёртый набор не добавляется', addWeaponSet(main), null)
равно('у основной профессии два дополнительных набора', наборы().length, 2)
равно('у саба пока нет дополнительных наборов', наборыСаба(), [])
равно('саб добавляет свой набор независимо', addWeaponSet(sub), 1)
равно('у саба появился один набор', наборыСаба().length, 1)
равно('наборы основной профессии не задеты', наборы().length, 2)

equipItem(main, 'rhand', 0, { id: 101 })
equipItem({ ...main, weaponSet: 1 }, 'rhand', 0, { id: 102 })
equipItem({ ...main, weaponSet: 2 }, 'rhand', 0, { id: 103 })

равно('вещь первого набора на месте', сейчас().slots.rhand[0].itemId, 101)
равно('вещь второго набора на месте', наборы()[0].rhand[0].itemId, 102)
равно('вещь третьего набора на месте', наборы()[1].rhand[0].itemId, 103)
правда(
  'правка дополнительного набора попадает в историю с номером',
  (getDb().history ?? []).some(
    (з) => з.вид === 'слот' && з.charId === id && з.weaponSet === 1,
  ),
)

removeWeaponSet(main, 0)
равно('после удаления первого набора на его месте второй', сейчас().slots.rhand[0].itemId, 102)
равно('третий набор сдвинулся на место второго', наборы()[0].rhand[0].itemId, 103)
равно('после удаления первого осталось два набора', 1 + наборы().length, 2)

removeWeaponSet(main, 1)
равно('последний набор не удаляется', 1 + наборы().length, 1)
равно('вещь в последнем наборе осталась', сейчас().slots.rhand[0].itemId, 102)
равно('удаление на основной не трогает саб', наборыСаба().length, 1)

/* ------------------------------------------------------ миграция кастетов */

/*
 * Кастеты стали двуручными. Миграция должна не просто дорисовать вторую
 * руку, а сохранить всё, что было надето слева: вещь уходит в казну с
 * заточкой, SA и редким эффектом, а не пропадает.
 */
const idКастета = 268
const idsКастетов = fistIds([
  { id: idКастета, weaponClass: 'Кастеты' },
  { id: 9999, weaponClass: 'Меч' },
])
равно('кастет находится по классу оружия', [...idsКастетов], [idКастета])

const кастет = (mod = 10) => ({ itemId: idКастета, mod, sa: 'Health' })
const вРуке = (item) => ({ rhand: [item], lhand: [null] })
const базаСКастетом = (slots, extra = {}) => ({
  ...emptyDb(),
  chars: [{ ...emptyChar(), id: 'fist', name: 'Кулак', slots, ...extra }],
})
const момент = '2026-10-24T00:00:00.000Z'

const исходная = базаСКастетом(вРуке(кастет()))
const раз = migrateFistHands(исходная, idsКастетов, момент)
равно('кастет мигрировал', раз.changed, true)
равно('правая рука без spans', раз.db.chars[0].slots.rhand, [кастет()])
равно(
  'левая рука — вторая ячейка кастета',
  раз.db.chars[0].slots.lhand,
  [{ ...кастет(), spans: true }],
)
равно('при пустой левой руке в казну ничего не ушло', раз.moved, [])
равно('казна не тронута', раз.db.warehouse, исходная.warehouse)

const повтор = migrateFistHands(раз.db, idsКастетов, момент)
