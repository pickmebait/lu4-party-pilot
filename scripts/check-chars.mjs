равно('пустое поле сохраняется нулём', levelToSave(''), 0)
равно('ноль при сохранении поднимается к минимуму', levelToSave('0'), LEVEL_MIN)
равно('выше потолка режется при сохранении', levelToSave('99'), LEVEL_MAX)
равно('обычное значение без изменений', levelToSave('42'), 42)
равно('разбирается и мусор', levelToSave('abc'), 0)
равно('хвост после двух цифр отбрасывается', levelToSave('4212'), 42)

