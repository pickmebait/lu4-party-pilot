/**
 * Проверка правил раздела персонажей.
 *
 * Три вещи, которые считались в четырёх местах по-разному и потому разошлись
 * бы при первой же правке: занятые слоты, границы уровня и годность ника.
 *
 * Проверка запускает код, а не читает исходник: ошибка в подсчёте слотов не
 * бросает исключения, она тихо показывает в шапке «9 из 12» вместо «11 из 12»,
 * и заметить это можно только сверкой с известным ответом.
 */
import { build } from 'esbuild'
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const ТЕСТ = `
import { слотыВетки, слотыПерсонажа } from '@/lib/derived.ts'
import { levelForInput, levelToSave, LEVEL_MIN, LEVEL_MAX } from '@/lib/classes.ts'
import { привестиНик, написаноБезПробелов, НИК_МАКС } from '@/lib/nick.ts'

let пройдено = 0
const ошибки: string[] = []
const равно = (подпись, получили, ждём) => {
  пройдено++
  const a = JSON.stringify(получили)
  const b = JSON.stringify(ждём)
  if (a !== b) ошибки.push(подпись + '\\n      получили: ' + a + '\\n      ждём:     ' + b)
}
const правда = (подпись, условие) => {
  пройдено++
  if (!условие) ошибки.push(подпись)
}

const вещь = (itemId, mod) => ({ itemId, mod })

/* --------------------------------------------------------------- слоты */

// Пустая ветка: слотов в игре двенадцать, занято ни одного.
равно('пустая ветка', слотыВетки({}), { занято: 0, всего: 0 })

// Ветка из двух ячеек в кольцах: считаются обе, а не только первая.
равно(
  'кольца считаются по ячейкам',
  слотыВетки({ ring: [вещь(1, 10), null] }),
  { занято: 1, всего: 2 },
)
равно(
  'обе вещи в кольцах заняты',
  слотыВетки({ ring: [вещь(1, 10), вещь(2, 10)] }),
  { занято: 2, всего: 2 },
)

// Нормализованная ветка: полный набор слотов, шесть занято из двенадцати.
const полная = {
  rhand: [вещь(10, 16)],
  lhand: [null],
  head: [вещь(11, 16)],
  chest: [вещь(12, 16)],
  legs: [вещь(13, 16)],
  gloves: [null],
  feet: [вещь(14, 16)],
  neck: [вещь(15, 16)],
  ear: [вещь(16, 16), null],
  ring: [вещь(17, 16), вещь(18, 16)],
}
равно('нормализованная ветка', слотыВетки(полная), { занято: 9, всего: 12 })

/*
 * Область видимости названа и различается намеренно: у персонажа с сабом на
 * карточке двенадцать слотов, а в сводке — двадцать четыре.
 *
 * Здесь саб пока сырой, без нормализации, и в нём ровно один слот. Считается
 * то, что на самом деле есть: функция не додумывает недостающие слоты, иначе
 * она показывала бы «занято из двадцати четырёх» тому, у кого надето одно.
 */
const персонаж = {
  id: 'c1', name: 'Алекс', cls: 'SM', level: 85, affil: 'роster',
  slots: полная, subUnlocked: true,
  subs: [{ id: 's1', cls: 'Paladin', level: 80, slots: { rhand: [вещь(20, 15)] } }],
  contacts: {}, away: {},
}
равно('ветка персонажа', слотыВетки(персонаж.slots), { занято: 9, всего: 12 })
равно('саб без нормализации — один слот', слотыПерсонажа(персонаж), { занято: 10, всего: 13 })

// Нормализованный саб добавляет свои двенадцать, и вместе выходит двадцать четыре.
const сНормализованнымСабом = { ...персонаж, subs: [{ ...персонаж.subs[0], slots: полная }] }
равно('нормализованный саб — 24 слота', слотыПерсонажа(сНормализованнымСабом), { занято: 18, всего: 24 })
равно('саб считается отдельно', слотыВетки(персонаж.subs[0].slots), { занято: 1, всего: 1 })

// Пустые слоты не считаются занятыми, но входят в общее число.
правда(
  'пустая ячейка не занята',
  слотыВетки({ rhand: [null] }).занято === 0,
)
правда(
  'пустая ячейка входит в общее число',
  слотыВетки({ rhand: [null] }).всего === 1,
)

/* -------------------------------------------------------------- уровень */

// При вводе: только цифры, не больше двух, верхняя граница сразу.
равно('буквы отбрасываются', levelForInput('a1b2'), '12')
равно('больше двух цифр не берём', levelForInput('123'), '12')
равно('выше потолка режется', levelForInput('99'), String(LEVEL_MAX))
равно('ноль при наборе остаётся нулём', levelForInput('0'), '0')
равно('пустое поле — пустое', levelForInput(''), '')
правда('пробелы и минус не мешают', levelForInput(' -4') === '4')

/*
 * При сохранении границы полные, и это не расхождение, а разное назначение:
 * в поле «0» в начале ввода — ещё не ноль, а в базе ноль означает «не указан».
 */
равно('пустое поле сохраняется нулём', levelToSave(''), 0)
равно('ноль при сохранении поднимается к минимуму', levelToSave('0'), LEVEL_MIN)
равно('выше потолка режется при сохранении', levelToSave('99'), LEVEL_MAX)
равно('обычное значение без изменений', levelToSave('42'), 42)
равно('разбирается и мусор', levelToSave('abc'), 0)
равно('хвост после двух цифр отбрасывается', levelToSave('4212'), 42)

/* ----------------------------------------------------------------- ник */

равно('пробелы убираются', привестиНик('А л е к с'), 'Алекс')
равно('длинный ник обрезается', привестиНик('а'.repeat(40)).length, НИК_МАКС)
равно('счёт по символам, а не по байтам', привестиНик('а'.repeat(16)).length, 16)
равно('иероглифы — символы, а не байты', привестиНик('战'.repeat(16)).length, 16)
равно('короткий китайский ник целиком', привестиНик('战战战战战战').length, 6)
равно('не строка — пусто', привестиНик(null), '')
равно('сырое не обрезается', написаноБезПробелов('а'.repeat(40)).length, 40)

export default { пройдено, ошибки }
`

const папка = mkdtempSync(join(tmpdir(), 'персонажи-'))
const вход = join(папка, 'тест.mts')
const выход = join(папка, 'тест.mjs')
writeFileSync(вход, ТЕСТ, 'utf8')

try {
  await build({
    entryPoints: [вход],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    outfile: выход,
    logLevel: 'silent',
    alias: { '@': new URL('../src', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1') },
  })
  const модуль = await import(pathToFileURL(выход).href)
  const { пройдено, ошибки } = модуль.default
  if (ошибки.length) {
    console.error(`ПРОВАЛЕНО ${ошибки.length} из ${пройдено}:`)
    for (const о of ошибки) console.error('  ✗ ' + о)
    process.exit(1)
  }
  console.log(`ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ (${пройдено})`)
} finally {
  rmSync(папка, { recursive: true, force: true })
}
