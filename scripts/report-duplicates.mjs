/**
 * Разбор полных дублей в справочнике.
 *
 * Показывает, что именно сборщик считает дублем и не теряется ли при этом
 * что-то важное: иконка, класс, тип. Если в паре строк расходится хоть что-то,
 * значит удалять их нельзя.
 *
 * Запуск: node scripts/report-duplicates.mjs [сколькоПоказать]
 */
import { readFileSync } from 'node:fs'

const показать = Number(process.argv[2] || 12)
const сырьё = JSON.parse(readFileSync('data/masterwork/list.json', 'utf8'))
const записи = Object.values(сырьё.краткий)

/** Ключ по тому, что видит игрок в пикере: имя, тип, грейд и характеристики. */
const ключВидимого = (p) =>
  [p.имя, p.тип, p.грейд, p.категория, (p.колонки || []).join(',')].join('|')

/**
 * Ключ полного совпадения — то же плюс иконка и класс SA.
 * Только такие пары нельзя различить в пикере вообще.
 */
const ключПолного = (p) =>
  [ключВидимого(p), p.иконка || '', p.класс || ''].join('|')

function сгруппировать(ключ) {
  const группы = new Map()
  for (const p of записи) {
    const k = ключ(p)
    if (!группы.has(k)) группы.set(k, [])
    группы.get(k).push(p)
  }
  return [...группы.values()].filter((г) => г.length > 1)
}

const пары = сгруппировать(ключВидимого)
const полные = сгруппировать(ключПолного)

let расходятсяПоИконке = 0
let расходятсяПоКлассу = 0
const тройки = []

for (const группа of пары) {
  if (new Set(группа.map((p) => p.иконка)).size > 1) расходятсяПоИконке++
  if (new Set(группа.map((p) => p.класс)).size > 1) расходятсяПоКлассу++
  if (группа.length > 2) тройки.push(группа)
}

console.log('Предметов в списке:', записи.length)
console.log('')
console.log('Пары по видимым полям (имя, тип, грейд, характеристики):')
console.log('  групп:', пары.length, '| предметов внутри:', пары.reduce((s, г) => s + г.length, 0))
console.log('  из них расходится иконка:', расходятсяПоИконке)
console.log('  из них расходится класс SA:', расходятсяПоКлассу)
console.log('  групп больше двух предметов:', тройки.length)
console.log('')
console.log('Пары по полному совпадению (+ иконка и класс SA):')
console.log('  групп:', полные.length, '| предметов внутри:', полные.reduce((s, г) => s + г.length, 0))
console.log('')
console.log('Вывод: первые', пары.length, 'групп нельзя считать дублями — в', расходятсяПоКлассу, 'из них разный класс SA.')
console.log('       Настоящих дублей, неразличимых в пикере,', полные.length + '.')
console.log()

// Как выглядят пары: разница по id и по названию
const сРазницейId = пары.filter((г) => new Set(г.map((p) => p.id)).size > 1).length
const одинаковыеId = пары.filter((г) => new Set(г.map((p) => p.id)).size === 1).length
console.log('Пар с разными id:', сРазницейId, '| с одинаковыми id (разные страницы выдачи):', одинаковыеId)
console.log()

console.log('Примеры пар, которые НЕ дубль (разный класс SA или иконка):')
let показано = 0
for (const группа of пары) {
  const классы = new Set(группа.map((p) => p.класс || '—'))
  const иконки = new Set(группа.map((p) => p.иконка))
  if (классы.size === 1 && иконки.size === 1) continue
  if (показано++ >= показать) break
  console.log(`  ${группа[0].имя}  → id ${группа.map((p) => p.id).join(', ')}`)
  console.log(`    класс SA: ${[...классы].join(' / ')} | иконок: ${иконки.size}`)
}
console.log()

console.log('Примеры настоящих дублей:')
let показано2 = 0
for (const группа of полные) {
  if (показано2++ >= показать) break
  console.log(
    `  ${группа[0].имя}  → id ${группа.map((p) => p.id).join(', ')} | ` +
      `${группа[0].тип || '—'} | ${группа[0].грейд || '—'}`,
  )
}

// Сколько id «старше» и «моложе» — второй экземпляр обычно рядом по номеру?
const разрывы = пары
  .map((г) => Math.max(...г.map((p) => p.id)) - Math.min(...г.map((p) => p.id)))
  .sort((a, b) => a - b)
const рядом = разрывы.filter((р) => р < 200).length
console.log()
console.log('Разрыв между id в паре: меньше 200 у', рядом, 'пар из', разрывы.length)
if (разрывы.length) {
  console.log('  минимальный:', разрывы[0], 'медианный:', разрывы[Math.floor(разрывы.length / 2)], 'максимальный:', разрывы[разрывы.length - 1])
}