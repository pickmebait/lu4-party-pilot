/**
 * Сборка public/items.json из данных masterwork.wiki.
 *
 * Источник: data/masterwork/list.json — полный список предметов вики Lu4: Gamma,
 * собранный scripts/masterwork-scrape.js (поиск по трём типам экипировки).
 * Формат источника:
 *   { meta, краткий: { "<id>": { id, slug, имя, иконка, грейд, класс, тип,
 *                              колонки: [...], категория } } }
 *
 * Запуск:
 *   node scripts/build-catalog.mjs            собрать items.json и скачать иконки
 *   node scripts/build-catalog.mjs --no-icons  только items.json
 *
 * Отличия от прошлой базы (lu4db), в плюс:
 *   - настоящие игровые id, а не последовательные;
 *   - грейд проставлен у всех предметов;
 *   - слот приходит прямо из вики, а не выводится по префиксу имени;
 *   - тип оружия приходит прямо из вики.
 *
 * Чего в списке нет (это лежит в карточках, они не выкачаны):
 *   - тип брони: тяжёлая / лёгкая / магическая;
 *   - одна или две руки у оружия;
 *   - комплекты и полные таблицы зачарования.
 * Эти поля остаются пустыми. Приложение показывает такие предметы при любом
 * выборе фильтра, а не прячет молча.
 */
import { readFile, writeFile, mkdir, stat } from 'node:fs/promises'
import { join } from 'node:path'

const ИСТОЧНИК = 'data/masterwork/list.json'
const ЦЕЛЬ = 'public/items.json'
/** Папка на диске, куда кладутся иконки. */
const ПАПКА_ИКОНОК = 'public/icons-mw'
/** То же самое, но так, как это видит приложение: путь от корня сайта. */
const ПУТЬ_ИКОНОК = 'icons-mw'
const ОСНОВА_ИКОНОК = 'https://masterwork.wiki/'

/** Слот вики → слот приложения. Пусто значит «в игре не надевается». */
const СЛОТ_БРОНИ = {
  'Головной убор': 'head',
  Шлем: 'head',
  'Верх. доспех': 'chest',
  'Полный доспех': 'chest',
  'Ниж. доспех': 'legs',
  Перчатки: 'gloves',
  Сапоги: 'feet',
  Щит: 'l_hand',
}

/** Классы оружия вики → шесть групп для фильтра. */
const ТИП_ОРУЖИЯ = {
  Меч: 'Мечи',
  'Парные клинки': 'Мечи',
  Дробящее: 'Дробящие',
  'Парное Дробящее': 'Дробящие',
  Кинжал: 'Кинжалы',
  'Парные Кинжалы': 'Кинжалы',
  Лук: 'Луки',
  Древковое: 'Копья',
  Кастет: 'Кастеты',
}

/** Дуальное оружие: надевается парой в обе руки. */
const ДУАЛЬНОЕ = /Парн/

/** Грейды, для которых в приложении есть кнопки фильтра. */
const ГРЕЙДЫ = ['NG', 'D', 'C', 'B', 'A', 'S']

/** Что вики пишет в колонках списка, по категориям. */
const КОЛОНКИ = {
  Оружие: ['atkPhys', 'atkMag'],
  Доспехи: ['physDef'],
  Аксессуар: ['mDef'],
}

const безИконок = process.argv.includes('--no-icons')

const сырьё = JSON.parse(await readFile(ИСТОЧНИК, 'utf8'))
const записи = Object.values(сырьё.краткий)

const предметы = []
const отчёт = {
  всего: записи.length,
  служебных: 0,
  соСлотом: 0,
  безСлота: 0,
  сГрейдом: 0,
  дуальных: 0,
  поГрейду: {},
  поСлоту: {},
  поТипуОружия: {},
}

for (const з of записи) {
  // Вики держит служебные записи: имя «(Not Use)» или «0». В игре их нет,
  // в пикере они только мешают.
  if (!з.имя || /^\(?not use\)?$/i.test(з.имя.trim()) || /^[\d\s.\-_/*]+$/.test(з.имя.trim())) {
    отчёт.служебных++
    continue
  }

  const out = {
    id: з.id,
    name: з.имя,
    tex: з.slug.replace(/^\d+-/, ''),
    icon: з.иконка ? ПУТЬ_ИКОНОК + '/' + з.иконка.split('/').pop() : undefined,
  }

  if (з.грейд) {
    out.gradeName = з.грейд
    отчёт.сГрейдом++
    отчёт.поГрейду[з.грейд] = (отчёт.поГрейду[з.грейд] || 0) + 1
  }
  if (з.класс) out.variant = з.класс

  if (з.категория === 'Оружие') {
    const группа = ТИП_ОРУЖИЯ[з.тип]
    if (группа) {
      out.slot = 'r_hand'
      out.weaponClass = з.тип
      out.weaponType = группа
      отчёт.поТипуОружия[группа] = (отчёт.поТипуОружия[группа] || 0) + 1
      if (ДУАЛЬНОЕ.test(з.тип)) {
        out.dual = true
        out.twoHanded = true
        отчёт.дуальных++
      }
      // Одна или две руки вики в списке не отдаёт: это поле карточки.
    }
  } else if (з.категория === 'Доспехи') {
    const слот = СЛОТ_БРОНИ[з.тип]
    if (слот) {
      out.slot = слот
      if (слот === 'chest' && з.тип === 'Полный доспех') out.fullbody = true
    }
  } else if (з.категория === 'Аксессуар') {
    if (з.тип === 'Кольцо') out.slot = 'ring'
    else if (з.тип === 'Серьга') out.slot = 'ear'
    else if (з.тип === 'Ожерелье') out.slot = 'neck'
  }

  const поля = КОЛОНКИ[з.категория] || []
  з.колонки.forEach((значение, i) => {
    const ключ = поля[i]
    if (!ключ) return
    const n = Number(значение)
    if (Number.isFinite(n)) out[ключ] = n
  })

  if (out.slot) {
    отчёт.соСлотом++
    отчёт.поСлоту[out.slot] = (отчёт.поСлоту[out.slot] || 0) + 1
  } else {
    отчёт.безСлота++
  }

  // Ключи без значения не пишем: меньше мусора в json.
  for (const k of Object.keys(out)) if (out[k] === undefined) delete out[k]

  предметы.push(out)
}

предметы.sort((a, b) => a.id - b.id)

const каталог = {
  generatedAt: new Date().toISOString(),
  source: `masterwork.wiki · Lu4: Gamma · список предметов ${new Date(сырьё.meta.начало).toISOString().slice(0, 10)}`,
  notes: {
    ids: 'настоящие игровые id',
    нетВСписке: 'тип брони, одна/две руки, комплекты — эти поля есть только в карточках',
  },
  items: предметы,
}

await writeFile(ЦЕЛЬ, JSON.stringify(каталог), 'utf8')

console.log(`Записано ${ЦЕЛЬ}: ${предметы.length} предметов`)
console.log(`  служебных записей отброшено: ${отчёт.служебных}`)
console.log(`  со слотом: ${отчёт.соСлотом}, без слота: ${отчёт.безСлота}`)
console.log(`  с грейдом: ${отчёт.сГрейдом}, дуальных: ${отчёт.дуальных}`)
console.log(`  грейды: ${JSON.stringify(отчёт.поГрейду)}`)
console.log(`  слоты: ${JSON.stringify(отчёт.поСлоту)}`)
console.log(`  типы оружия: ${JSON.stringify(отчёт.поТипуОружия)}`)
console.log(`  грейды в фильтрах: ${ГРЕЙДЫ.join(', ')}`)

// Иконки лежат на вики отдельными файлами и отдаются мимо защиты страницы,
// поэтому их можно скачать обычным клиентом. Адреса берём из источника, а не
// из готового каталога: там уже переименованный путь приложения.
if (!безИконок) {
  await скачатьИконки(записи)
}

async function скачатьИконки(записиИсточника) {
  await mkdir(ПАПКА_ИКОНОК, { recursive: true })
  const нужные = [...new Set(записиИсточника.map((з) => з.иконка).filter(Boolean))]
  let скачано = 0
  let битых = 0
  const ОДНОВРЕМЕННО = 4

  const очередь = [...нужные]
  async function рабочий() {
    for (;;) {
      const адрес = очередь.pop()
      if (!адрес) return
      const путь = join(ПАПКА_ИКОНОК, адрес.split('/').pop())
      try {
        await stat(путь)
        continue
      } catch {
        /* файла нет — качаем */
      }
      try {
        const r = await fetch(ОСНОВА_ИКОНОК + адрес.replace(/^\/+/, ''), {
          headers: { 'User-Agent': 'lu4-party-pilot' },
        })
        if (!r.ok) throw new Error('HTTP ' + r.status)
        await writeFile(путь, Buffer.from(await r.arrayBuffer()))
        скачано++
      } catch {
        битых++
      }
    }
  }
  await Promise.all(Array.from({ length: ОДНОВРЕМЕННО }, рабочий))
  console.log(`Иконки: ${нужные.length} всего, скачано ${скачано}, не получилось ${битых}`)
  if (битых) {
    console.log('  у таких предметов иконка не загрузится, приложение покажет первую букву названия')
  }
}