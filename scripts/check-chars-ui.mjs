/**
 * Проверка раздела персонажей без браузера.
 *
 * После разделения Chars.tsx оболочка вкладки, список, форма добавления и
 * пикер предметов собираются по отдельности. Компилятор не замечает
 * потерянный пропс или перепутанный обработчик: экран просто показывает не
 * то. Здесь каждый извлечённый компонент вызывается с настоящими данными и
 * проверяется по разметке.
 *
 * Клики не выполняются — проверяется то, что видно до них: пустые состояния,
 * подписи полей, выбранный вид списка и окно выбора предмета.
 */
import { build } from 'esbuild'
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const ТЕСТ = `
import { renderToStaticMarkup } from 'react-dom/server'
import { CharsView } from '@/components/Chars.tsx'
import { СписокПерсонажей } from '@/components/CharList.tsx'
import { QuickAddForm } from '@/components/QuickAddForm.tsx'
import { SlotPicker } from '@/components/SlotPicker.tsx'
import { emptyDb, replaceDb } from '@/lib/store.ts'

const пусто = (n) => Array.from({ length: n }, () => null)
const слоты = {
  rhand: пусто(1), lhand: пусто(1), head: пусто(1), chest: пусто(1), legs: пусто(1),
  gloves: пусто(1), feet: пусто(1), neck: пусто(1), ear: пусто(2), ring: пусто(2),
}
const персонаж = (id, name, cls) => ({
  id, name, cls, level: 80, affil: 'roster', slots: слоты, subs: [],
  subUnlocked: false, contacts: {}, away: {},
})

/*
 * Справочник-заглушка: списку персонажей предметы не нужны, а пикеру хватает
 * пустого набора — он должен показать пустое состояние, а не упасть.
 */
const каталог = {
  loading: false,
  catalog: { generatedAt: '', items: [] },
  error: null,
  count: 0,
  byId: () => null,
  nameOf: (id) => 'предмет ' + id,
  search: () => [],
  countMatching: () => 0,
  all: () => [],
  knownIds: new Set(),
}

let пройдено = 0
const ошибки: string[] = []
const есть = (подпись, разметка, кусок) => {
  пройдено++
  if (!разметка.includes(кусок)) ошибки.push(подпись + '\\\\n      нет в разметке: ' + кусок + '\\\\n      разметка: ' + разметка.slice(0, 600))
}
const нет = (подпись, разметка, кусок) => {
  пройдено++
  if (разметка.includes(кусок)) ошибки.push(подпись + '\\\\n      лишнее в разметке: ' + кусок)
}

/* ------------------------------------------------------------- список */

const никто = renderToStaticMarkup(
  <СписокПерсонажей
    вид="строка"
    chars={[]}
    всего={0}
    фильтр="все"
    сбросить={() => {}}
    catalog={каталог}
    onPick={() => {}}
  />,
)
есть('пустая пати объяснена', никто, 'Персонажей пока нет.')
есть('пустая пати подсказывает следующий шаг', никто, 'Добавь членов пати')
есть('пустое состояние оформлено', никто, 'class="empty"')

const чужаяГруппа = renderToStaticMarkup(
  <СписокПерсонажей
    вид="строка"
    chars={[]}
    всего={2}
    фильтр="decade"
    сбросить={() => {}}
    catalog={каталог}
    onPick={() => {}}
  />,
)
есть('пустая группа названа', чужаяГруппа, 'В группе «Десятка» никого нет.')
есть('из пустой группы можно вернуться', чужаяГруппа, 'Показать всех')
есть('возврат — ссылка, а не потерянный экран', чужаяГруппа, 'class="link-btn"')

const карточки = renderToStaticMarkup(
  <СписокПерсонажей
    вид="строка"
    chars={[персонаж('c1', 'PickMe', 'Sorcerer'), персонаж('c2', '2345', 'Paladin')]}
    всего={2}
    фильтр="все"
    сбросить={() => {}}
    catalog={каталог}
    onPick={() => {}}
  />,
)
есть('вид «Строка» рисует карточки', карточки, 'class="char-card')
есть('первый персонаж назван', карточки, 'PickMe')
есть('второй персонаж назван', карточки, '2345')
есть('профессия видна', карточки, 'Sorcerer')
есть('принадлежность видна', карточки, 'Состав')

const строки = renderToStaticMarkup(
  <СписокПерсонажей
    вид="колонка"
    chars={[персонаж('c1', 'PickMe', 'Sorcerer')]}
    всего={1}
    фильтр="все"
    сбросить={() => {}}
    catalog={каталог}
    onPick={() => {}}
  />,
)
есть('вид «Колонка» рисует строки', строки, 'class="char-row')
есть('в строке есть имя', строки, 'PickMe')
есть('в строке есть снаряжение', строки, 'row-gear')
нет('в строке нет карточки', строки, 'class="char-card')

/* ------------------------------------------------------- оболочка вкладки */

replaceDb(emptyDb())
const пустаяВкладка = renderToStaticMarkup(<CharsView catalog={каталог} />)
есть('раздел персонажей отрисован', пустаяВкладка, 'class="view"')
есть('фильтр по принадлежности на месте', пустаяВкладка, 'aria-label="Фильтр по принадлежности"')
есть('кнопки фильтра резервируют ширину', пустаяВкладка, 'data-label="Все"')
есть('вид раздела на месте', пустаяВкладка, 'aria-label="Вид раздела"')
есть('вкладка «Все» выбрана', пустаяВкладка, '>Все</button>')
есть('фильтр «Состав» есть', пустаяВкладка, '>Состав</button>')
есть('вид «Строка» есть', пустаяВкладка, '>Строка</button>')
есть('вид «Колонка» есть', пустаяВкладка, '>Колонка</button>')
есть('мастеру видна кнопка добавления', пустаяВкладка, 'Добавить персонажа')
есть('без персонажей список пуст', пустаяВкладка, 'Персонажей пока нет.')

const база = emptyDb()
база.chars = [
  персонаж('c1', 'PickMe', 'Sorcerer'),
  персонаж('c2', '2345', 'Paladin'),
]
replaceDb(база)
const сПерсонажами = renderToStaticMarkup(<CharsView catalog={каталог} />)
есть('персонажи появились в сетке', сПерсонажами, 'class="chars-grid"')
есть('первый персонаж в оболочке', сПерсонажами, 'PickMe')
есть('второй персонаж в оболочке', сПерсонажами, '2345')

/* ------------------------------------------------------- форма добавления */

const форма = renderToStaticMarkup(<QuickAddForm onDone={() => {}} onCancel={() => {}} />)
есть('форма добавления отрисована', форма, 'class="form"')
есть('поле имени подписано', форма, 'Имя персонажа')
есть('поле профессии подписано', форма, 'Профессия')
есть('поле уровня подписано', форма, 'Уровень')
есть('принадлежность выбирается', форма, 'Принадлежность')
есть('добавить без имени нельзя', форма, 'disabled=""')
есть('кнопка добавления подписана', форма, '>Добавить</button>')
есть('от формы можно отказаться', форма, '>Отмена</button>')

/* --------------------------------------------------------- выбор предмета */

const пикер = renderToStaticMarkup(
  <SlotPicker
    target={{ charId: 'c1', subId: null, slot: 'head', index: 0 }}
    catalog={каталог}
    onClose={() => {}}
  />,
)
есть('окно выбора предмета открыто', пикер, 'class="modal-backdrop picker-backdrop"')
есть('окно названо слотом', пикер, 'aria-label="Шлем"')
есть('заголовок слота виден', пикер, '>Шлем</h3>')
есть('есть поиск предмета', пикер, 'placeholder="Поиск: название, техническое имя или номер…"')
есть('пустой справочник объяснён', пикер, 'Справочник ещё загружается или пуст.')
есть('окно можно закрыть', пикер, 'aria-label="Закрыть"')

replaceDb(emptyDb())

export default { пройдено, ошибки }
`

const папка = mkdtempSync(join(new URL('../.git', import.meta.url).pathname.replace(/^[/\\]([A-Za-z]:)/, '$1'), 'персонажи-ui-'))
const вход = join(папка, 'тест.tsx')
const выход = join(папка, 'тест.mjs')
writeFileSync(вход, ТЕСТ, 'utf8')

try {
  await build({
    entryPoints: [вход],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    outfile: выход,
    jsx: 'automatic',
    logLevel: 'silent',
    packages: 'external',
    alias: { '@': new URL('../src', import.meta.url).pathname.replace(/^[/\\]([A-Za-z]:)/, '$1') },
  })
  const модуль = await import(pathToFileURL(выход).href)
  const { пройдено, ошибки } = модуль.default
  if (ошибки.length) {
    console.error(`ПРОВАЛЕНО ${ошибки.length} из ${пройдено}:`)
    for (const о of ошибки) console.error('  ✗ ' + о)
    process.exit(1)
  }
  console.log(`ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ (${пройдено})`)
} finally {
  rmSync(папка, { recursive: true, force: true })
}
