/**
 * Название приложения.
 *
 * Единая точка, потому что имя повторяется в трёх местах — во вкладке
 * браузера, в шапке приложения и на экране входа, — и однажды разъедется,
 * как уже разъезжалось с подписью под логотипом: в шапке было
 * «экипировка пати», на экране входа «экипировки пати».
 *
 * В index.html имя осталось текстом: статическая разметка модуль не
 * импортирует, а ради одного заголовка тянуть сборку не стоит.
 */
export const APP_NAME = 'Const Party Pilot'

/**
 * То же имя для имён файлов: «Const Party Pilot» → «const-party-pilot».
 *
 * Выгружаемую базу человек видит и пересылает, так что переименование должно
 * тянуться за собой и сюда — иначе файл останется со старым именем.
 */
export const APP_SLUG = APP_NAME.toLowerCase().replace(/[^a-z0-9]+/g, '-')