/**
 * Ось вечера для карточки выбранного дня.
 *
 * В клетке календаря достаточно времени начала, а в сводке нужен весь вечер:
 * где стоит прайм, когда начинается осада и не уехало ли всё это на соседние
 * сутки из-за часового пояса. Поэтому ось считается в минутах от полуночи
 * выбранного дня, а не от полуночи события: так окно, перешедшее через
 * полночь или пришедшее из соседнего дня, остаётся на одной шкале.
 *
 * Обычная шкала — с 18:00 до 02:00. Если прайм и события из-за пояса ушли за
 * её пределы, ось сужается вокруг них с запасом в час: иначе дальневосточный
 * вечер занимал бы четверть ширины, а остальное было бы пустым.
 */
import { dayShiftBetween, type WallTime } from './timezone'

const ЧАС = 60
const СУТКИ = 24 * ЧАС

/** Обычный вечер: с 18:00 до 02:00 следующих суток. */
const ВЕЧЕР_ОТ = 18 * ЧАС
const ВЕЧЕР_ДО = 26 * ЧАС

/** Окно события или прайма на часах пользователя. */
export interface TimelineSpan {
  from: WallTime
  to: WallTime
}

export interface DayTimeline {
  /** Начало оси в минутах от полуночи выбранного дня. */
  from: number
  /** Конец оси; у вечера с переходом через полночь больше 1440. */
  to: number
  /** Метки на оси — тоже минуты от полуночи выбранного дня. */
  ticks: number[]
}

/** Минуты от полуночи выбранного дня: вчерашние и завтрашние тоже. */
export function minutesOnDay(day: string, wall: WallTime): number {
  return dayShiftBetween(day, wall.key) * СУТКИ + wall.minutes
}

/* Ось режем по чётным часам: подписи 18, 20, 22, 00, 02 читаются ровно. */
const вниз = (минуты: number): number => Math.floor(минуты / (2 * ЧАС)) * 2 * ЧАС
const вверх = (минуты: number): number => Math.ceil(минуты / (2 * ЧАС)) * 2 * ЧАС

/** Расстояние от начала оси до момента в процентах её ширины. */
export function timelineOffset(ось: DayTimeline, минуты: number): number {
  const ширина = ось.to - ось.from
  return ширина > 0 ? ((минуты - ось.from) / ширина) * 100 : 0
}

/**
 * Границы оси и подписи.
 *
 * Без прайма и событий остаётся обычный вечер. Если всё содержимое лежит вне
 * него, ось строится вокруг содержимого: так в поясе, где прайм наступает
 * утром, карточка показывает утро, а не пустую ночь.
 */
export function dayTimeline(
  day: string,
  prime: TimelineSpan | null,
  events: readonly TimelineSpan[],
): DayTimeline {
  const начала = [
    ...(prime ? [minutesOnDay(day, prime.from)] : []),
    ...events.map((e) => minutesOnDay(day, e.from)),
  ]
  const концы = [
    ...(prime ? [minutesOnDay(day, prime.to)] : []),
    ...events.map((e) => minutesOnDay(day, e.to)),
  ]

  if (начала.length === 0) {
    return { from: ВЕЧЕР_ОТ, to: ВЕЧЕР_ДО, ticks: [ВЕЧЕР_ОТ, 20 * ЧАС, 22 * ЧАС, 24 * ЧАС, ВЕЧЕР_ДО] }
  }

  const содержимоеОт = Math.min(...начала)
  const содержимоеДо = Math.max(...концы)
  const внеВечера = содержимоеДо <= ВЕЧЕР_ОТ || содержимоеОт >= ВЕЧЕР_ДО

  const from = внеВечера
    ? вниз(содержимоеОт - ЧАС)
    : вниз(Math.min(ВЕЧЕР_ОТ, содержимоеОт))
  const to = внеВечера
    ? вверх(содержимоеДо + ЧАС)
    : вверх(Math.max(ВЕЧЕР_ДО, содержимоеДо))

  /* Длинную ось подписываем реже: двенадцать подписей в узкой карточке
     сливаются в сплошную строку. */
  const ширина = to - from
  const шаг = ширина > 20 * ЧАС ? 4 * ЧАС : ширина > 12 * ЧАС ? 3 * ЧАС : 2 * ЧАС
  const ticks: number[] = []
  for (let минуты = from; минуты <= to; минуты += шаг) ticks.push(минуты)
  if (ticks[ticks.length - 1] !== to) ticks.push(to)

  return { from, to, ticks }
}
