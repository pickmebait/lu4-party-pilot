/**
 * Производственный календарь РФ.
 *
 * Данные лежат файлом рядом: isdayoff.ru отдаёт 403 и не присылает
 * Access-Control-Allow-Origin, поэтому из браузера его API недоступен
 * никак. Файл обновляется скриптом scripts/build-holidays.mjs — обычно
 * раз в год, после постановления правительства о переносах.
 */
import календарь from './holidays-ru.json'
import { isoKey } from './schedule'

/** Как день выглядит в календаре. */
export interface DayInfo {
  /** Суббота или воскресенье. */
  выходной: boolean
  /** Государственный праздник. */
  праздник: boolean
  /**
   * Выходной, объявленный рабочим: суббота или воскресенье, в которые
   * выходят. Работать будут — отмечать прайм тут не стоит.
   */
  рабочий: boolean
  /** Предпраздничный сокращённый день. */
  сокращённый: boolean
  /** Праздничный день, ставший рабочим. */
  праздникРабочий: boolean
}

interface Год {
  праздники: string[]
  рабочие: string[]
  сокращённые: string[]
}

const годы = календарь.годы as unknown as Record<string, Год>

function список(год: string): Год | undefined {
  return годы[год]
}

/**
 * Сведения о дне.
 *
 * За годом, которого нет в файле, праздников не будет вовсе: честнее не
 * гадать по правилам и не показать 9 мая рабочим, чем угадывать
 * переносы, которые меняет постановление.
 */
export function dayInfo(дата: Date): DayInfo {
  const key = isoKey(дата)
  const год = список(key.slice(0, 4))
  const короткая = key.slice(5)
  const d = дата.getDay()
  const субботаВоскресенье = d === 0 || d === 6

  const праздник = !!год?.праздники.includes(короткая)
  const рабочийВыходной = !!год?.рабочие.includes(короткая)
  const сокращённый = !!год?.сокращённые.includes(короткая)

  return {
    выходной: субботаВоскресенье && !рабочийВыходной,
    праздник: праздник && !рабочийВыходной,
    рабочий: рабочийВыходной,
    сокращённый,
    праздникРабочий: праздник && рабочийВыходной,
  }
}

/** Праздничные дни года — показываем подписью «новогодние», «9 мая»… */
export function holidayName(дата: Date): string {
  const key = isoKey(дата)
  const год = список(key.slice(0, 4))
  if (!год?.праздники.includes(key.slice(5))) return ''
  return ПРАЗДНИКИ[key.slice(5)] ?? 'Праздник'
}

