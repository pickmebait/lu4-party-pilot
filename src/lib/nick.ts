/**
 * Имя персонажа.
 *
 * В игре ник — от одного до шестнадцати символов без пробелов. Правило
 * живёт здесь одно, а не в каждой форме: в прошлом ограничение на длину
 * стояло в одной форме правки и не стояло в другой, и персонаж с длинным
 * именем появлялся мимо проверки.
 *
 * Приводится к виду один раз и на входе, и на правке: пробелы убираются,
 * длинное имя обрезается. Так в базе не может оказаться того, чего в игре
 * не бывает, даже если значение пришло из файла, а не из формы.
 */

/** Сколько символов в нике в игре. */
export const НИК_МАКС = 16

/**
 * Приводит написанное к нику.
 *
 * Пробелы убираются целиком, а не заменяются: в игре ника с пробелом не
 * бывает, и подставить вместо него что-то — значит тихо изменить то, что
 * человек написал. Обрезка по символам, а не по байтам: счёт идёт по
 * графемам, и китайский ник из трёх иероглифов в шестнадцати символов
 * укладывается, а в байтах — нет.
 */
export function привестиНик(значение: unknown): string {
  if (typeof значение !== 'string') return ''
  const безПробелов = [...значение.replace(/\s+/g, '')]
  return безПробелов.slice(0, НИК_МАКС).join('')
}

/**
 * То же, но без обрезки — для подсчёта при вводе.
 *
 * Отдельная функция, потому что обрезанное имя всегда «правильное», и по
 * нему нельзя понять, что человек написал лишнего. Форма спрашивает по
 * сырому, а сохраняет по обрезанному.
 */
export function написаноБезПробелов(значение: string): string {
  return typeof значение === 'string' ? значение.replace(/\s+/g, '') : ''
}

/** Годится ли написанное имя для сохранения. */
export function никГодится(значение: string): boolean {
  return привестиНик(значение).length > 0
}