/**
 * Роли персонажей для сводки.
 *
 * В базе роль не хранится отдельным полем: есть только класс, и пати
 * раскладывается по ролям уже при показе. Это осознанно производное
 * правило, а не данные: класс можно сменить, и роль поедет за ним сама,
 * без второй правки в карточке.
 *
 * Маппинг не претендует на игровую энциклопедию. Он отвечает на вопрос
 * «кем этот персонаж закрывает место в пати», а не на вопрос «какие ветки
 * у класса есть». Поэтому один класс попадает ровно в одну роль, а редкие
 * и нестандартные профессии честно остаются без роли, вместо того чтобы
 * угадывать их по названию.
 */
import { normalize } from './util'

export const РОЛИ = [
  'танк',
  'хил',
  'бард',
  'саппорт',
  'ДД',
  'добыча',
  'без роли',
] as const

export type Роль = (typeof РОЛИ)[number]

/** Подписи для интерфейса: ключи короткие, чтобы не путаться в коде. */
export const РОЛЬ_ПОДПИСЬ: Record<Роль, string> = {
  танк: 'Танк',
  хил: 'Хил',
  бард: 'Бард',
  саппорт: 'Саппорт',
  ДД: 'ДД',
  добыча: 'Добыча',
  'без роли': 'Без роли',
}

/**
 * Класс → роль.
 *
 * Составлен по списку CLASSES из classes.ts. Если класс не попал сюда,
 * это не ошибка данных: на сервере бывают свои профессии, и показывать
 * их как ДД или танка значило бы придумывать за человека.
 */
const РОЛИ_ПО_КЛАССУ: Record<string, Роль> = {
  // Танки.
  paladin: 'танк',
  'dark avenger': 'танк',
  'shillien knight': 'танк',
  'temple knight': 'танк',

  // Хилы.
  bishop: 'хил',
  'elven elder': 'хил',
  'shillien elder': 'хил',

  // Барды.
  swordsinger: 'бард',
  bladedancer: 'бард',

  // Саппорт: бафферы и полевые усилители.
  prophet: 'саппорт',
  warcryer: 'саппорт',
  overlord: 'саппорт',

  // Добыча: спойлер и крафтер.
  'bounty hunter': 'добыча',
  warsmith: 'добыча',

  // ДД.
  gladiator: 'ДД',
  warlord: 'ДД',
  tyrant: 'ДД',
  destroyer: 'ДД',
  hawkeye: 'ДД',
  'silver ranger': 'ДД',
  'phantom ranger': 'ДД',
  'treasure hunter': 'ДД',
  plainswalker: 'ДД',
  'abyss walker': 'ДД',
  sorcerer: 'ДД',
  spellsinger: 'ДД',
  spellhowler: 'ДД',
  necromancer: 'ДД',
  warlock: 'ДД',
  'elemental summoner': 'ДД',
  'phantom summoner': 'ДД',
}

/** Роль по названию класса; пустой или незнакомый класс — «без роли». */
export function roleOfClass(cls: string | undefined): Роль {
  const ключ = normalize(cls ?? '')
  return РОЛИ_ПО_КЛАССУ[ключ] ?? 'без роли'
}
