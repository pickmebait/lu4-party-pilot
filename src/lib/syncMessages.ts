/**
 * Слова, которые видит человек, и слова, которые видит тот, кто разбирается.
 *
 * Полоса синхронизации говорит о сохранении, и раньше она говорила об этом
 * так: «В пати изменилось, пока ты правил (от: Ирок, 3 минуты назад)».
 * Кто автор, когда и с каким кодом — это про устройство, а человек правил
 * персонажа и ждёт, пока правка ляжет в пати. Смешанное сообщение читается
 * как отчёт, а не как ответ.
 *
 * Поэтому сообщение и подробности разведены. На виду — что произошло и что
 * человеку с этим делать. Под значком — откуда это известно: сервер, код,
 * метка версии. Подробности нужны не для красоты, а когда правка не дошла и
 * надо разбираться: без них «не сохранилось» не отличить от «сервер не
 * отвечает» и от «токен отозвали».
 *
 * Все пользовательские надписи собраны здесь, чтобы править их было в одном
 * месте, а не выискивать по компонентам.
 */
import type { Db } from '@/types'
import { formatAgo } from './util'

/**
 * Что показать человеку: короткое сообщение и, если есть, подробности.
 *
 * Подробности — отдельным полем, а не дописанными в конец текста. Иначе
 * «заглянуть» нельзя: спрятать технику, не спрятав половину сообщения.
 */
export interface Сообщение {
  /** Короткая надпись. Что произошло и что делать, если что-то не так. */
  текст: string
  /** Что под значком: сервер, код ответа, метки версий. */
  детали?: string
  /**
   * Через сколько надпись убрать сама.
   *
   * Только для хороших новостей. Ошибку и сообщение о чужой правке убирать
   * нельзя: они просят что-то сделать или предупреждают, и молча пропавший
   * текст человек прочитает уже на следующей правке.
   */
  убратьЧерезМс?: number
}

/**
 * Какое дело за сообщением.
 *
 * От этого цвет плашки, а не от настроения: то, что сделано, и то, что не
 * вышло, выглядят по-разному, и человек должен различать их боковым зрением,
 * не читая.
 */
export type РодСообщения = 'идёт' | 'сделано' | 'ошибка'

/* ------------------------------------------------------------------ надписи */

/**
 * Слова, которые видит человек.
 *
 * Правятся здесь и больше нигде. Одна надпись — одно дело, чтобы одна и та же
 * мысль не звучала в двух местах по-разному.
 */
export const СЛОВА = {
  /*
   * Идёт работа. «Сохраню» короче «Сохраняю в пати…» ровно потому, что слова
   * «в пати» ничего не добавляют: человек и так в пати, название видно в
   * кнопке рядом. Надпись висит на экране всё время записи, и каждое лишнее
   * слово — это лишнее время чтения.
   */
  сохраняю: 'Сохраняю…',
  загружаю: 'Загружаю из пати…',

  /*
   * Успех. Раньше после удачного сохранения надписи не было вовсе — тишина
   * стоила дороже, чем строка: человек, не увидевший ответа, правит заново
   * или ждёт. Лишняя правка — это лишняя запись в общей базе, которую потом
   * приходится разбирать с теми, кто в неё тоже пишет.
   */
  сохранено: 'Сохранено',
  сохраненоПослеПовтора: 'Сохранено. Связь оборвалась, отправил заново',
  сохраненоБезОтвета: 'Сохранено. Ответ не дошёл, метку взял заново',
  сохраненоСЧужойПравкой: 'Сохранено. Подтянул чужую правку',

  загружено: 'Загружено из пати',
  загруженоСАвтором: (кто: string) => `Загружено из пати. Правка: ${кто}`,

  /*
   * Неудачи. Главное в каждой — сказать, теряет человек правку или нет.
   * Обрыв связи правку не теряет: она лежит в браузере и уйдёт сама. Если
   * написать «не сохранилось» и промолчать про это, человек решит самое
   * худшее и начнёт переписывать всё заново.
   *
   * Формулировки короткие не только потому, что так короче читается. Надпись
   * стоит в одной строке с кнопкой доступа, и места ей остаётся около трёхсот
   * пикселей: всё, что длиннее, переносится, полоса растёт, и шапка прыгает
   * вниз ровно тогда, когда человек читает, что произошло с его правкой.
   * Проверка scripts/замер-сообщений.mjs меряет настоящим шрифтом.
   */
  нетСвязи: 'Не сохранилось. Правка цела, сохраню сама',
  нетСвязиПриЗагрузке: 'Не получилось загрузить. Показываю то, что есть',
  токенНеПодходит: 'Токен не подходит. Войди заново',
  базаСлишкомБольшая: 'Правка не влезла. База слишком большая',
  правкаНеСохранена: 'Правка не сохранена',
  /*
   * Лимит GitHub — не ошибка правки и не повод её переписывать. Правка цела
   * в браузере, ждёт сброса лимита. Обещание «сохраню» здесь важнее причины:
   * человеку нечего чинить, надо просто подождать.
   */
  лимитGitHub: 'Лимит GitHub. Правка цела, сохраню',
  лимитGitHubПриЗагрузке: 'Лимит GitHub. Показываю то, что есть',

  /*
   * Чужая правка. Тут важно сказать, что будет дальше, иначе человек решит,
   * что правка пропала: под токеном персонажа она подставится сама,
   * мастеру покажут выбор.
   */
  вПаТИИзменилось: 'В пати изменилось, пока ты правил',
  вПаТИИзменилосьПодставится: 'В пати изменилось — твоя правка ляжет поверх',
  естьНесохранённые: 'Есть несохранённые правки, загрузка подождёт',
  персонажаУбрали: 'Персонажа убрали из пати. Правка не сохранена',

  повторИдёт: 'Связь оборвалась — отправляю заново',
} as const

/* --------------------------------------------------------------- подробности */

/** Одна строка подробностей: подпись и значение. */
const строка = (подпись: string, значение: unknown): string =>
  `${подпись}: ${значение === undefined || значение === null || значение === '' ? '—' : значение}`

/** Кто и когда правил базу в пати — для разбора, не для надписи. */
export function ктоПравил(db: Db | undefined): string {
  if (!db) return 'нет данных'
  return `${db.updatedBy || 'неизвестно'}, ${formatAgo(db.updatedAt)}`
}

/**
 * Подробности обмена: адрес, вид запроса, код ответа и сколько раз уходил.
 *
 * Ровно то, что нужно при разборе неудачи, и ровно то, что не нужно при
 * работе: четыре строки, в которых есть адрес сервера и HTTP-код, — шум для
 * человека, который правил снаряжение.
 */
export function деталиЗапроса(часть: {
  адрес?: string
  вид?: string
  код?: number
  попыток?: number
  меткаСервера?: string
  меткаСвоя?: string
  текстСервера?: string
}): string {
  /*
   * Нулевой код — это не «неизвестно», а обрыв связи: так его помечает
   * lib/api, и именно он отличает «сервер не ответил» от «сервер отказал».
   * Раньше здесь стояло «нет ответа — обрыв связи» на все случаи, где кода
   * нет, и подробности об успешной записи врали: ответа там как раз был.
   */
  const код = часть.код === 0 ? 'нет ответа — обрыв связи' : часть.код ?? '—'

  return [
    строка('Адрес', часть.адрес),
    строка('Запрос', часть.вид),
    строка('Код ответа', код),
    строка('Попыток', часть.попыток),
    строка('Метка пати', часть.меткаСервера),
    строка('Метка здесь', часть.меткаСвоя),
    строка('Ответ сервера', часть.текстСервера),
  ].join('\n')
}

/* ----------------------------------------------- готовые сообщения по исходам */

/** Что сказать, когда сервер не отвечает. */
export function приОбрыве(детали?: string): Сообщение {
  return { текст: СЛОВА.нетСвязи, детали }
}

/** Что сказать, когда правка записалась с первой попытки. */
export function приУспехе(детали?: string): Сообщение {
  return { текст: СЛОВА.сохранено, детали, убратьЧерезМс: 4000 }
}

/** Что сказать, когда правка записалась, но запрос пришлось повторить. */
export function приПовторе(детали?: string): Сообщение {
  return { текст: СЛОВА.сохраненоПослеПовтора, детали, убратьЧерезМс: 6000 }
}

/** Что сказать, когда запись легла, а ответ потерялся. */
export function приПотерянномОтвете(детали?: string): Сообщение {
  return { текст: СЛОВА.сохраненоБезОтвета, детали, убратьЧерезМс: 6000 }
}

/** Что сказать, когда сервер отказал по делу. */
export function приОтказе(текстСервера: string, код?: number, адрес?: string): Сообщение {
  return {
    текст: СЛОВА.правкаНеСохранена,
    детали: деталиЗапроса({ адрес, код, текстСервера }),
  }
}

/**
 * Что сказать, когда GitHub не принимает запросы из-за лимита.
 *
 * Это не повод что-то чинить: лимит общий на серверный токен и сбрасывается
 * сам. Поэтому надпись обещает сохранить позже, а не просит проверить токен.
 * Когда именно ждать — в подробностях, их присылает сервер.
 */
export function приЛимите(детали?: string): Сообщение {
  return { текст: СЛОВА.лимитGitHub, детали }
}
