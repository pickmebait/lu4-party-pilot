/**
 * Адрес базы зашит в сборку при развёртывании через VITE_API_URL.
 *
 * Игрокам вводить его не нужно: на экране входа остаётся только токен пати.
 * Если переменная не задана, приложение честно сообщает, что не настроено,
 * вместо того чтобы предлагать поле, которого не будет в рабочей сборке.
 */

/** Нормализованный адрес: без хвостовых слэшей. */
export const API_URL = (import.meta.env.VITE_API_URL ?? '').trim().replace(/\/+$/, '')

/** Есть ли адрес, с которым вообще можно работать. */
export const CONFIGURED = /^https?:\/\/[^\s<]+$/i.test(API_URL)
