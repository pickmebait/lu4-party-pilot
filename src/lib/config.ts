/**
 * Адрес сервера с базой.
 *
 * Задаётся один раз при развёртывании через переменную окружения
 * VITE_API_URL — тогда игрокам не нужно ничего вводить, кроме токена пати.
 * Если переменной нет, адрес берётся из настроек браузера, а если и его
 * нет — спрашивается один раз и запоминается.
 */

/** Из сборки. Пусто, если при деплое переменная не задана. */
export const BUILD_API_URL = (import.meta.env.VITE_API_URL ?? '').trim()

/** Заглушка для первого запуска, чтобы поле не выглядело пустым. */
export const PLACEHOLDER_API_URL = 'https://lu4-party-pilot.<поддомен>.workers.dev'

/** Похоже ли значение на заполненный адрес (а не на заглушку и не пусто). */
export function looksLikeUrl(v: string): boolean {
  const s = v.trim()
  return /^https?:\/\/[^\s<]+$/i.test(s)
}
