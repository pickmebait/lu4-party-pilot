export interface Движение {
  who: string
  забрал: number
  положил: number
  /** Разница: положили минус забрали. Положительное — отдал пати. */
  разница: number
}

export interface КазнаЗаПериод {
  операций: number
  /** Предметов забрали. */
  забрали: number
  /** Предметов положили. */
  положили: number
  /** Операций в неделю — темп обмена. */
  вНеделю: number
  поЛюдям: Движение[]
  /** Самые забираемые позиции. */
  топ: { itemId: number; count: number }[]
  /** Дней между первой и последней передачей — на сколько растянулось. */
  охватДней: number
  /** Журнал упирается в предел и «всё время» — это хвост. */
  обрезан: boolean
  /** Первая дата в журнале: раньше неё ничего не сохранилось. */
  откуда: string | null
}

export function казнаЗаПериод(db: Db, сОт: string | null): КазнаЗаПериод {
  const журнал = db.warehouse.log
    .filter((з) => (сОт === null || з.ts.slice(0, 10) >= сОт))
    .sort((a, b) => a.ts.localeCompare(b.ts))

  const поЛюдям = new Map<string, Движение>()
  const поПредметам = new Map<number, number>()
  let забрали = 0
  let положили = 0

  for (const з of журнал) {
    const имя = з.who || 'неизвестно'
    const д = поЛюдям.get(имя) ?? { who: имя, забрал: 0, положил: 0, разница: 0 }
    if (з.dir === 'out') {
      д.забрал += з.count
      забрали += з.count
      поПредметам.set(з.itemId, (поПредметам.get(з.itemId) ?? 0) + з.count)
    } else {
      д.положил += з.count
      положили += з.count
    }
    д.разница = д.положил - д.забрал
    поЛюдям.set(имя, д)
  }

  const первая = журнал.length ? журнал[0].ts.slice(0, 10) : null
  const последняя = журнал.length ? журнал[журнал.length - 1].ts.slice(0, 10) : null
  const охватДней =
    первая && последняя
      ? Math.max(
          1,
          Math.round((parseKey(последняя).getTime() - parseKey(первая).getTime()) / 86_400_000) + 1,
        )
      : 0

  return {
    операций: журнал.length,
    забрали,
    положили,
    вНеделю: охватДней ? Math.round((журнал.length / охватДней) * 7 * 10) / 10 : 0,
    поЛюдям: [...поЛюдям.values()].sort((a, b) => b.забрал - a.забрал),
    топ: [...поПредметам.entries()]
      .map(([itemId, count]) => ({ itemId, count }))
      .sort((a, b) => b.count - a.count)
      .slice(0, 8),
    охватДней,
    обрезан: db.warehouse.log.length >= ПОТОЛОК_ЖУРНАЛА,
    откуда: первая,
  }
}

