/**
 * Расчёты для раздела «Сводка».
 *
 * Всё считается по датам, которые уже есть в базе: прайм и выходные лежат
 * по дням, отсутствия — внутри персонажа, передачи в казне помечены временем,
 * закрытые хотелки — датой закрытия. Эти данные хранятся бессрочно, и по ним
 * можно считать любой период.
 *
 * Чего в базе нет, того здесь нет: снаряжение, саб-классы и комплекты хранятся
 * как текущее состояние, без следа изменений. Поэтому готовность и пробелы —
 * это «сейчас», и периодом они не фильтруются. В разметке такие плитки
 * помечены, чтобы не выдавать снимок за историю.
 *
 * Одна оговорка про казну: журнал передач обрезан пятьюстами записями, и
 * «всё время» по нему — это на самом деле хвост. Когда записи упираются в
 * предел, расчёты помечают это прямо, иначе вывод читался бы как точный.
 */
import type { Char, Db, SetDef, SlotEntry, ВещьВИстории, Изменение } from '@/types'
import { SLOT_KEYS, SLOT_MAX, type SlotKey } from '@/types'
import { isoKey, parseKey } from './schedule'
import { branchesOf, computeSets } from './derived'

/** Сколько последних записей помещается в журнал передач. */
const ПОТОЛОК_ЖУРНАЛА = 500

/**
 * Сколько записей об изменении хранится.
 *
 * Дублирует ПОТОЛОК_ИСТОРИИ из store.ts: аналитика не должна импортировать
 * само хранилище — иначе расчёт, который должен был бы работать на сырой базе
 * из сети, потянул бы за собой и браузерные функции.
 */
const ПОТОЛОК_ИСТОРИИ = 500

/** Период в днях; 0 — всё время. */
export type ПериодДней = 30 | 60 | 90 | 0

export const ПЕРИОДЫ: { дней: ПериодДней; подпись: string }[] = [
  { дней: 30, подпись: '30 дней' },
  { дней: 60, подпись: '60 дней' },
  { дней: 90, подпись: '90 дней' },
  { дней: 0, подпись: 'всё время' },
]

/**
 * Первый день периода или null для «всего времени».
 *
 * Отсчёт от сегодняшнего дня, а не от первого числа месяца: человек думает
 * «за последний месяц», а не «за календарный месяц».
 */
export function началоПериода(дней: ПериодДней, сегодня = isoKey(new Date())): string | null {
  if (дней === 0) return null
  const d = parseKey(сегодня)
  d.setDate(d.getDate() - (дней - 1))
  return isoKey(d)
}

/** Дата внутри периода и не позже сегодняшнего. */
function внутри(key: string, сОт: string | null, сегодня: string): boolean {
  if (key > сегодня) return false
  return сОт === null || key >= сОт
}

