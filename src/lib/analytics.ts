/**
 * Расчёты для раздела «Сводка».
 *
 * Всё считается по датам, которые уже есть в базе: прайм и выходные лежат
 * по дням, отсутствия — внутри персонажа, передачи в казне помечены временем,
 * закрытые хотелки — датой закрытия. Эти данные хранятся бессрочно, и по ним
 * можно считать любой период.
 *
 * Чего в базе нет, того здесь нет: снаряжение, саб-классы и комплекты хранятся
 * как текущее состояние, без следа изменений. Поэтому готовность и пробелы —
 * это «сейчас», и периодом они не фильтруются. В разметке такие плитки
 * помечены, чтобы не выдавать снимок за историю.
 *
 * Одна оговорка про казну: журнал передач обрезан пятьюстами записями, и
 * «всё время» по нему — это на самом деле хвост. Когда записи упираются в
 * предел, расчёты помечают это прямо, иначе вывод читался бы как точный.
 */
import type { Db, SetDef } from '@/types'
import { SLOT_KEYS, type SlotKey } from '@/types'
import { isoKey, parseKey } from './schedule'
import { branchesOf, computeSets } from './derived'

/** Сколько последних записей помещается в журнал передач. */
const ПОТОЛОК_ЖУРНАЛА = 500

/** Период в днях; 0 — всё время. */
export type ПериодДней = 30 | 60 | 90 | 0

export const ПЕРИОДЫ: { дней: ПериодДней; подпись: string }[] = [
  { дней: 30, подпись: '30 дней' },
  { дней: 60, подпись: '60 дней' },
  { дней: 90, подпись: '90 дней' },
  { дней: 0, подпись: 'всё время' },
]

/**
 * Первый день периода или null для «всего времени».
 *
 * Отсчёт от сегодняшнего дня, а не от первого числа месяца: человек думает
 * «за последний месяц», а не «за календарный месяц».
 */
export function началоПериода(дней: ПериодДней, сегодня = isoKey(new Date())): string | null {
  if (дней === 0) return null
  const d = parseKey(сегодня)
  d.setDate(d.getDate() - (дней - 1))
  return isoKey(d)
}

/** Дата внутри периода и не позже сегодняшнего. */
function внутри(key: string, сОт: string | null, сегодня: string): boolean {
  if (key > сегодня) return false
  return сОт === null || key >= сОт
}

/* --------------------------------------------------------------- расписание */

/** Часы с округлением до десятых: план считают по часам, а не по минутам. */
const вЧасы = (минут: number) => Math.round((минут / 60) * 10) / 10

export interface ПраймЗаПериод {
  /** Дней с назначенным праймом. */
  дней: number
  /** Суммарные часы прайма. */
  часов: number
  /** Дней, объявленных выходными пати. */
  выходных: number
  /** Средняя длина окна в минутах; 0, если прайма не было. */
  среднееОкно: number
  /** Сколько праймов было в каждый день недели, от понедельника. */
  поДнямНедели: number[]
  /** Часы по месяцам — для столбиков. */
  поМесяцам: { месяц: string; часов: number }[]
  /** Дней прайма ещё впереди: в сумму не входят, но видны отдельно. */
  впереди: number
}

export function праймЗаПериод(db: Db, сОт: string | null, сегодня: string): ПраймЗаПериод {
  let минут = 0
  let дней = 0
  let впереди = 0
  const поДнямНедели = [0, 0, 0, 0, 0, 0, 0]
  const поМесяцам = new Map<string, number>()

  for (const [key, окно] of Object.entries(db.schedule.prime)) {
    const сколько = Math.max(0, окно.to - окно.from)
    if (key > сегодня) {
      впереди++
      continue
    }
    if (!внутри(key, сОт, сегодня)) continue
    дней++
    минут += сколько
    поДнямНедели[(parseKey(key).getDay() + 6) % 7]++
    const месяц = key.slice(0, 7)
    поМесяцам.set(месяц, (поМесяцам.get(месяц) ?? 0) + сколько)
  }

  const выходных = db.schedule.offs.filter((k) => внутри(k, сОт, сегодня)).length

  return {
    дней,
    часов: вЧасы(минут),
    выходных,
    среднееОкно: дней ? Math.round(минут / дней) : 0,
    поДнямНедели,
    поМесяцам: [...поМесяцам.entries()]
      .sort((a, b) => a[0].localeCompare(b[0]))
      .map(([месяц, мин]) => ({ месяц, часов: вЧасы(мин) })),
    впереди,
  }
}

/* -------------------------------------------------------------------- явка */

export interface Пропуски {
  charId: string
  имя: string
  /** Сколько праймов персонаж пропустил. */
  пропусков: number
  /** Доля от всех праймов периода, 0–100. */
  доля: number
}

export interface Явка {
  /** Праймов за период. */
  праймов: number
  /** Праймов, на которых не отмечено ни одного отсутствия. */
  полных: number
  /** Среднее, сколько человек приходило. */
  средняя: number
  поПерсонажам: Пропуски[]
  /** Даты праймов, где кого-то не было: сколько их и как часто повторялся состав. */
  датыНеполных: { день: string; отсутствуют: string[] }[]
}

export function явкаЗаПериод(db: Db, сОт: string | null, сегодня: string): Явка {
  const дниПрайма = Object.keys(db.schedule.prime)
    .filter((k) => внутри(k, сОт, сегодня))
    .sort()

  const поПерсонажам: Пропуски[] = []
  let полных = 0
  let всегоПриходов = 0
  const датыНеполных: Явка['датыНеполных'] = []

  for (const c of db.chars) {
    const пропусков = дниПрайма.filter((d) => c.away?.[d]).length
    поПерсонажам.push({
      charId: c.id,
      имя: c.name || 'Без имени',
      пропусков,
      доля: дниПрайма.length ? Math.round((пропусков / дниПрайма.length) * 100) : 0,
    })
    всегоПриходов += дниПрайма.length - пропусков
  }

  for (const день of дниПрайма) {
    const отсутствуют = db.chars.filter((c) => c.away?.[день]).map((c) => c.name || 'Без имени')
    if (отсутствуют.length === 0) полных++
    else датыНеполных.push({ день, отсутствуют })
  }

  return {
    праймов: дниПрайма.length,
    полных,
    средняя: дниПрайма.length ? Math.round((всегоПриходов / дниПрайма.length) * 10) / 10 : 0,
    // Худшие сверху: так список сразу отвечает, кого звать.
    поПерсонажам: поПерсонажам.sort((a, b) => b.пропусков - a.пропусков),
    датыНеполных,
  }
}

/* ------------------------------------------------------------------- казна */

export interface Движение {
  who: string
  забрал: number
  положил: number
  /** Разница: положили минус забрали. Положительное — отдал пати. */
  разница: number
}

export interface КазнаЗаПериод {
  операций: number
  /** Предметов забрали. */
  забрали: number
  /** Предметов положили. */
  положили: number
  /** Операций в неделю — темп обмена. */
  вНеделю: number
  поЛюдям: Движение[]
  /** Самые забираемые позиции. */
  топ: { itemId: number; count: number }[]
  /** Дней между первой и последней передачей — на сколько растянулось. */
  охватДней: number
  /** Журнал упирается в предел и «всё время» — это хвост. */
  обрезан: boolean
  /** Первая дата в журнале: раньше неё ничего не сохранилось. */
  откуда: string | null
}

export function казнаЗаПериод(db: Db, сОт: string | null): КазнаЗаПериод {
  const журнал = db.warehouse.log
    .filter((з) => (сОт === null || з.ts.slice(0, 10) >= сОт))
    .sort((a, b) => a.ts.localeCompare(b.ts))

  const поЛюдям = new Map<string, Движение>()
  const поПредметам = new Map<number, number>()
  let забрали = 0
  let положили = 0

  for (const з of журнал) {
    const имя = з.who || 'неизвестно'
    const д = поЛюдям.get(имя) ?? { who: имя, забрал: 0, положил: 0, разница: 0 }
    if (з.dir === 'out') {
      д.забрал += з.count
      забрали += з.count
      поПредметам.set(з.itemId, (поПредметам.get(з.itemId) ?? 0) + з.count)
    } else {
      д.положил += з.count
      положили += з.count
    }
    д.разница = д.положил - д.забрал
    поЛюдям.set(имя, д)
  }

  const первая = журнал.length ? журнал[0].ts.slice(0, 10) : null
  const последняя = журнал.length ? журнал[журнал.length - 1].ts.slice(0, 10) : null
  const охватДней =
    первая && последняя
      ? Math.max(
          1,
          Math.round((parseKey(последняя).getTime() - parseKey(первая).getTime()) / 86_400_000) + 1,
        )
      : 0

  return {
    операций: журнал.length,
    забрали,
    положили,
    вНеделю: охватДней ? Math.round((журнал.length / охватДней) * 7 * 10) / 10 : 0,
    поЛюдям: [...поЛюдям.values()].sort((a, b) => b.забрал - a.забрал),
    топ: [...поПредметам.entries()]
      .map(([itemId, count]) => ({ itemId, count }))
      .sort((a, b) => b.count - a.count)
      .slice(0, 8),
    охватДней,
    обрезан: db.warehouse.log.length >= ПОТОЛОК_ЖУРНАЛА,
    откуда: первая,
  }
}

/* --------------------------------------------------------------- хотелки */

export interface ХотелкиЗаПериод {
  закрыто: number
  активные: number
  /** Активные по приоритету: срочно, нужно, желательно. */
  поПриоритету: [number, number, number]
  /** Кто просит больше всего. */
  поИщущим: { кто: string; сколько: number }[]
}

export function хотелкиЗаПериод(db: Db, сОт: string | null): ХотелкиЗаПериод {
  const поПриоритету: [number, number, number] = [0, 0, 0]
  const поИщущим = new Map<string, number>()
  let закрыто = 0
  let активные = 0

  for (const w of db.wishes) {
    if (w.done) {
      if (w.doneAt && (сОт === null || w.doneAt.slice(0, 10) >= сОт)) закрыто++
      continue
    }
    активные++
    поПриоритету[(w.priority ?? 3) - 1]++
    const кто = w.seeker || 'без имени'
    поИщущим.set(кто, (поИщущим.get(кто) ?? 0) + 1)
  }

  return {
    закрыто,
    активные,
    поПриоритету,
    поИщущим: [...поИщущим.entries()]
      .map(([кто, сколько]) => ({ кто, сколько }))
      .sort((a, b) => b.сколько - a.сколько),
  }
}

/* -------------------------------------------------------------- снаряжение */

export interface Готовность {
  charId: string
  имя: string
  занято: number
  всего: number
  /** Средняя заточка по занятым слотам. */
  средняя: number
  /** Самая слабая занятая заточка — на неё смотрят в первую очередь. */
  худшая: number
}

export interface Отставание {
  charId: string
  имя: string
  слот: string
  своя: number
  лучшая: number
}

export interface Снаряжение {
  поПерсонажам: Готовность[]
  /** Слоты, где персонаж заметно слабее лучшего в пати. */
  отставание: Отставание[]
  /** Комплекты: у кого сколько частей надето. */
  комплекты: {
    set: SetDef
    /** Сколько частей в комплекте всего. */
    всего: number
    поЛюдям: { charId: string; имя: string; надето: number }[]
  }[]
}

/** Заточка вещи в слоте; 0 — пусто. */
function заточка(entry: { mod?: number } | null | undefined): number {
  return entry ? (entry.mod ?? 0) : -1
}

/**
 * Готовность снаряжения — только текущая.
 *
 * Следа изменений в базе нет, поэтому период здесь не участвует: показать
 * «как я развивался» физически не из чего. Такие плитки помечены «сейчас».
 */
export function снаряжение(db: Db): Снаряжение {
  const лучшие = new Map<string, number>()

  // Две ходки: первая собирает лучшую заточку по слоту, вторая считает.
  for (const c of db.chars) {
    for (const слоты of branchesOf(c)) {
      for (const k of SLOT_KEYS as readonly SlotKey[]) {
        for (const e of слоты[k] ?? []) {
          const м = заточка(e)
          if (м < 0) continue
          if (м > (лучшие.get(k) ?? -1)) лучшие.set(k, м)
        }
      }
    }
  }

  const поПерсонажам: Готовность[] = []
  const отставание: Отставание[] = []

  for (const c of db.chars) {
    let всего = 0
    let занято = 0
    const моды: number[] = []

    for (const слоты of branchesOf(c)) {
      for (const k of SLOT_KEYS as readonly SlotKey[]) {
        for (const e of слоты[k] ?? []) {
          всего++
          const м = заточка(e)
          if (м < 0) continue
          занято++
          моды.push(м)
          // Отставанием считаем разрыв от трёх и больше: меньший — погрешность.
          const лучшая = лучшие.get(k) ?? м
          if (лучшая - м >= 3) {
            отставание.push({
              charId: c.id,
              имя: c.name || 'Без имени',
              слот: k,
              своя: м,
              лучшая,
            })
          }
        }
      }
    }

    поПерсонажам.push({
      charId: c.id,
      имя: c.name || 'Без имени',
      занято,
      всего,
      средняя: моды.length
        ? Math.round((моды.reduce((a, b) => a + b, 0) / моды.length) * 10) / 10
        : 0,
      худшая: моды.length ? Math.min(...моды) : 0,
    })
  }

  // Комплект по персонажам: чьи части на ком надеты.
  const надетоПо = new Map<string, Set<number>>()
  for (const c of db.chars) {
    const надето = new Set<number>()
    for (const слоты of branchesOf(c)) {
      for (const k of SLOT_KEYS as readonly SlotKey[]) {
        for (const e of слоты[k] ?? []) if (e) надето.add(e.itemId)
      }
    }
    надетоПо.set(c.id, надето)
  }

  // Части берём из самого комплекта, а не из computeSets: там надетое всё
  // по пати сразу, и по персонажам её не разложить.
  // всей пати сразу, и по персонажам её не разложить.
  const комплекты = computeSets(db).map(({ set }) => {
    const части = [...new Set(set.pieces)]
    return {
      set,
      всего: части.length,
      поЛюдям: db.chars.map((c) => ({
        charId: c.id,
        имя: c.name || 'Без имени',
        надето: части.filter((p) => надетоПо.get(c.id)?.has(p)).length,
      })),
    }
  })

  return {
    поПерсонажам: поПерсонажам.sort((a, b) => a.средняя - b.средняя),
    отставание: отставание.sort(
      (a, b) => b.лучшая - b.своя - (a.лучшая - a.своя),
    ),
    комплекты,
  }
}