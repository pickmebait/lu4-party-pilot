export interface ХотелкиЗаПериод {
  закрыто: number
  активные: number
  /** Активные по приоритету: срочно, нужно, желательно. */
  поПриоритету: [number, number, number]
  /** Кто просит больше всего. */
  поИщущим: { кто: string; сколько: number }[]
}

export function хотелкиЗаПериод(db: Db, сОт: string | null): ХотелкиЗаПериод {
  const поПриоритету: [number, number, number] = [0, 0, 0]
  const поИщущим = new Map<string, number>()
  let закрыто = 0
  let активные = 0

  for (const w of db.wishes) {
    if (w.done) {
      if (w.doneAt && (сОт === null || w.doneAt.slice(0, 10) >= сОт)) закрыто++
      continue
    }
    активные++
    поПриоритету[(w.priority ?? 3) - 1]++
    const кто = w.seeker || 'без имени'
    поИщущим.set(кто, (поИщущим.get(кто) ?? 0) + 1)
  }

  return {
    закрыто,
    активные,
    поПриоритету,
    поИщущим: [...поИщущим.entries()]
      .map(([кто, сколько]) => ({ кто, сколько }))
      .sort((a, b) => b.сколько - a.сколько),
  }
}

/**
 * История из базы или пустой список.
 *
 * Не `?? []`: поле необязательное и приходит из сети, а `??` спасает только от
 * отсутствия. Строка вместо массива дошла бы до фильтра и уронила всю сводку
 * одним неверным значением в базе.
 */
function историяБазы(db: Db): Изменение[] {
  return Array.isArray(db.history) ? db.history : []
}

/* ------------------------------------------------------------------ история */

/**
 * Записи одного персонажа, сделанные позже указанного дня.
 *
 * Дата сравнится по первым десяти символам ISO, то есть по московскому времени,
 * а не по местному: переезд в другой пояс сдвинул бы границу периода на
 * несколько часов. Для сводки за дни это незаметно, а вот «что было вечером
 * пятницы» может оказаться на сутки раньше.
 */
function позже(история: Изменение[], charId: string, когда: string): Изменение[] {
  return история
    .filter(
      (з): з is Изменение =>
        !!з &&
        typeof з === 'object' &&
        typeof з.ts === 'string' &&
        typeof з.charId === 'string' &&
        з.charId === charId &&
        з.ts.slice(0, 10) > когда,
    )
    .sort((а, б) => б.ts.localeCompare(а.ts))
}

/** Заточки всех занятых ячеек по слепку слота. */
function модыСлепка(слепок: (ВещьВИстории | null)[]): number[] {
  const out: number[] = []
  for (const вещь of слепок) if (вещь) out.push(вещь.mod)
  return out
}

/** Заточки занятых ячеек в текущем состоянии. */
function модыЯчеек(ячейки: (SlotEntry | null)[] | undefined): number[] {
  const out: number[] = []
  for (const вещь of ячейки ?? []) if (вещь) out.push(вещь.mod ?? 0)
  return out
}

/**
 * Заточки персонажа на заданный день.
 *
 * Берётся нынешнее состояние и откатывается всё, что записано позже нужного
 * дня. Снимки не хранятся: по разницам состояние восстанавливается обратным
 * ходом, поэтому год правки снаряжения занимает десятки килобайт, а год
 * ежедневных снимков — мегабайты.
 *
 * Сабы берутся нынешние: если саб добавили после того дня, он окажется в счёте
 * для того дня пустым и зря впишет долг. Считать по истории создания сабов
 * можно, но ценой отдельной записи в базе, а выигрыш — одна строка в сводке.
 */
function модыНа(char: Char, история: Изменение[], когда: string): number[] {
  const ключ = (subId: string | null, слот: SlotKey) => `${subId ?? ''}|${слот}`
  const состояние = new Map<string, number[]>()

  const ветки: { subId: string | null; slots: Char['slots'] }[] = [
    { subId: null, slots: char.slots },
    ...char.subs.map((s) => ({ subId: s.id, slots: s.slots })),
  ]
  for (const ветка of ветки) {
    for (const слот of SLOT_KEYS as readonly SlotKey[]) {
      состояние.set(ключ(ветка.subId, слот), модыЯчеек(ветка.slots[слот]))
    }
  }

  for (const з of позже(история, char.id, когда)) {
    if (з.вид !== 'слот') continue
    состояние.set(ключ(з.subId, з.слот), модыСлепка(з.было))
  }

  return [...состояние.values()].flat()
}

/** Сколько ячеек слота пусто на заданный день. */
function пустыхНа(char: Char, история: Изменение[], когда: string): number {
  const ключ = (subId: string | null, слот: SlotKey) => `${subId ?? ''}|${слот}`
  const занято = new Map<string, number>()

  const ветки: { subId: string | null; slots: Char['slots'] }[] = [
    { subId: null, slots: char.slots },
    ...char.subs.map((s) => ({ subId: s.id, slots: s.slots })),
  ]
  for (const ветка of ветки) {
    for (const слот of SLOT_KEYS as readonly SlotKey[]) {
      занято.set(ключ(ветка.subId, слот), модыЯчеек(ветка.slots[слот]).length)
    }
  }

  for (const з of позже(история, char.id, когда)) {
    if (з.вид !== 'слот') continue
    занято.set(ключ(з.subId, з.слот), модыСлепка(з.было).length)
  }

  let пустых = 0
  for (const ветка of ветки) {
    for (const слот of SLOT_KEYS as readonly SlotKey[]) {
      пустых += SLOT_MAX[слот] - (занято.get(ключ(ветка.subId, слот)) ?? 0)
    }
  }
  return Math.max(0, пустых)
}

/** Уровень персонажа на заданный день. */
function уровеньНа(char: Char, история: Изменение[], когда: string): number {
  let уровень = char.level
  for (const з of позже(история, char.id, когда)) {
    if (з.вид === 'уровень') уровень += з.было - з.стало
  }
  return Math.max(0, уровень)
}

const среднее = (моды: number[]) =>
  моды.length ? Math.round((моды.reduce((а, б) => а + б, 0) / моды.length) * 10) / 10 : 0

export interface Рост {
  charId: string
  имя: string
  /** Средняя заточка сейчас. */
  сейчас: number
  /** Средняя заточка в начале периода. */
  было: number
  /** На сколько выросла заточка; может быть отрицательной. */
  прирост: number
  /**
   * Сколько раз снаряжение или уровень правили за период.
   *
   * Считаются все правки, а не только те, где вещей стало больше: поднять
   * заточку с +2 до +4 это и есть улучшение, и по узкому правилу оно молча
   * выпадало бы из счёта.
   */
  правок: number
  уровеньСейчас: number
  уровеньБыл: number
}

/**
 * Как росло снаряжение за период.
 *
 * Считается обратным ходом по истории: состояние на начало периода
 * восстанавливается откатом всех более поздних записей. Само сравнение — с
 * началом периода, а не «сколько улучшений всего»: пересчитывать среднюю
 * заточку с нуля было бы сравнением с выдуманным состоянием, которого не
 * было.
 */
export function развитие(db: Db, сОт: string | null, сегодня: string): {
  поПерсонажам: Рост[]
  записей: number
  обрезана: boolean
} {
  const история = историяБазы(db)
  const начало = сОт ?? '0000-01-01'
  const поПерсонажам: Рост[] = []

  for (const c of db.chars) {
    const сейчас = модыНа(c, история, сегодня)
    const было = модыНа(c, история, начало)
    const правок = история.filter(
      (з): з is Изменение =>
        !!з &&
        typeof з === 'object' &&
        typeof з.ts === 'string' &&
        з.charId === c.id &&
        з.ts.slice(0, 10) >= начало &&
        з.ts.slice(0, 10) <= сегодня,
    ).length
    const сейчасСред = среднее(сейчас)
    const былоСред = среднее(было)
    поПерсонажам.push({
      charId: c.id,
      имя: c.name || 'Без имени',
      сейчас: сейчасСред,
      было: былоСред,
      прирост: Math.round((сейчасСред - былоСред) * 10) / 10,
      правок,
      уровеньСейчас: c.level,
      уровеньБыл: уровеньНа(c, история, начало),
    })
  }

  return {
    поПерсонажам: поПерсонажам.sort((а, б) => б.прирост - а.прирост),
    записей: история.length,
    обрезана: история.length >= ПОТОЛОК_ИСТОРИИ,
  }
}

export interface Долг {
  день: string
  /** Всего пустых ячеек у пати на этот прайм. */
  пустых: number
  /** У кого больше всего пустых. */
  уКого: { имя: string; пустых: number }[]
}

/**
 * Долг по снаряжению к прайму: сколько слотов было пусто к каждому вечеру.
 *
 * Считается по истории изменения, а не по текущему состоянию: «к тому прайму
 * не было собрано четыре слота» — единственный вопрос, ради которого история
 * и заводится, а из нынешних слотов он не отвечается никак.
 */
export function долгКПрайму(
  db: Db,
  сОт: string | null,
  сегодня: string,
  свойCharId?: string | null,
): {
  дни: Долг[]
  среднийДолг: number
  мойДолг: number
  хужеВсего: Долг | null
  /** Сколько пустых ячеек набрал каждый за весь период. */
  поЛюдям: { charId: string; имя: string; всего: number }[]
} {
  const история = историяБазы(db)
  const дниПрайма = Object.keys(db.schedule.prime)
    .filter((k) => внутри(k, сОт, сегодня))
    .sort()

  const дни: Долг[] = дниПрайма.map((день) => {
    const поЛюдям = db.chars.map((c) => ({
      имя: c.name || 'Без имени',
      пустых: пустыхНа(c, история, день),
    }))
    return {
      день,
      пустых: поЛюдям.reduce((а, п) => а + п.пустых, 0),
      уКого: [...поЛюдям].sort((а, б) => б.пустых - а.пустых).slice(0, 3),
    }
  })

  const мойДолг = свойCharId
    ? дниПрайма.reduce((a, день) => {
        const мой = db.chars.find((c) => c.id === свойCharId)
        return мой ? a + пустыхНа(мой, история, день) : a
      }, 0)
    : 0

  // Недобор по персонажам за весь период: кому из пати заводить снаряжение
  // в первую очередь — из среднего по вечерам это не видно.
  //
  // Ключ — id, а не ник: в пати встречаются два персонажа с одинаковым ником,
  // и по нику они слиплись бы в одну строку с суммой за обоих.
  const накоплено = new Map<string, number>()
  for (const день of дниПрайма) {
    for (const c of db.chars) {
      накоплено.set(c.id, (накоплено.get(c.id) ?? 0) + пустыхНа(c, история, день))
    }
  }

  return {
    дни,
    среднийДолг: дни.length
      ? Math.round((дни.reduce((всего, день) => всего + день.пустых, 0) / дни.length) * 10) / 10
      : 0,
    мойДолг,
    хужеВсего: дни.length
      ? дни.reduce((хуже, день) => (день.пустых > хуже.пустых ? день : хуже), дни[0])
      : null,
    поЛюдям: [...накоплено.entries()]
      .map(([charId, всего]) => ({
        charId,
        имя: db.chars.find((c) => c.id === charId)?.name || 'Без имени',
        всего,
      }))
      .sort((первый, второй) => второй.всего - первый.всего),
  }
}

/* -------------------------------------------------------------- снаряжение */

export interface Готовность {
  charId: string
  имя: string
  занято: number
  всего: number
  /** Средняя заточка по занятым слотам. */
  средняя: number
  /** Самая слабая занятая заточка — на неё смотрят в первую очередь. */
  худшая: number
}

export interface Отставание {
  charId: string
  имя: string
  слот: string
  своя: number
  лучшая: number
}

export interface Снаряжение {
  поПерсонажам: Готовность[]
  /** Слоты, где персонаж заметно слабее лучшего в пати. */
  отставание: Отставание[]
  /** Комплекты: у кого сколько частей надето. */
  комплекты: {
    set: SetDef
    /** Сколько частей в комплекте всего. */
    всего: number
    поЛюдям: { charId: string; имя: string; надето: number }[]
  }[]
}

/** Заточка вещи в слоте; 0 — пусто. */
function заточка(entry: { mod?: number } | null | undefined): number {
  return entry ? (entry.mod ?? 0) : -1
}

/**
 * Готовность снаряжения — только текущая.
 *
 * Следа изменений в базе нет, поэтому период здесь не участвует: показать
 * «как я развивался» физически не из чего. Такие плитки помечены «сейчас».
 */
export function снаряжение(db: Db): Снаряжение {
  const лучшие = new Map<string, number>()

  // Две ходки: первая собирает лучшую заточку по слоту, вторая считает.
  for (const c of db.chars) {
    for (const слоты of branchesOf(c)) {
      for (const k of SLOT_KEYS as readonly SlotKey[]) {
        for (const e of слоты[k] ?? []) {
          const м = заточка(e)
          if (м < 0) continue
          if (м > (лучшие.get(k) ?? -1)) лучшие.set(k, м)
        }
      }
    }
  }

  const поПерсонажам: Готовность[] = []
  const отставание: Отставание[] = []

  for (const c of db.chars) {
    let всего = 0
    let занято = 0
    const моды: number[] = []

    for (const слоты of branchesOf(c)) {
      for (const k of SLOT_KEYS as readonly SlotKey[]) {
        for (const e of слоты[k] ?? []) {
          всего++
          const м = заточка(e)
          if (м < 0) continue
          занято++
          моды.push(м)
          // Отставанием считаем разрыв от трёх и больше: меньший — погрешность.
          const лучшая = лучшие.get(k) ?? м
          if (лучшая - м >= 3) {
            отставание.push({
              charId: c.id,
              имя: c.name || 'Без имени',
              слот: k,
              своя: м,
              лучшая,
            })
          }
        }
      }
    }

    поПерсонажам.push({
      charId: c.id,
      имя: c.name || 'Без имени',
      занято,
      всего,
      средняя: моды.length
        ? Math.round((моды.reduce((a, b) => a + b, 0) / моды.length) * 10) / 10
        : 0,
      худшая: моды.length ? Math.min(...моды) : 0,
    })
  }

  // Комплект по персонажам: чьи части на ком надеты.
  const надетоПо = new Map<string, Set<number>>()
  for (const c of db.chars) {
    const надето = new Set<number>()
    for (const слоты of branchesOf(c)) {
      for (const k of SLOT_KEYS as readonly SlotKey[]) {
        for (const e of слоты[k] ?? []) if (e) надето.add(e.itemId)
      }
    }
    надетоПо.set(c.id, надето)
  }

  // Части берём из самого комплекта, а не из computeSets: там надетое всё
  // по пати сразу, и по персонажам её не разложить.
  // всей пати сразу, и по персонажам её не разложить.
  const комплекты = computeSets(db).map(({ set }) => {
    const части = [...new Set(set.pieces)]
    return {
      set,
      всего: части.length,
      поЛюдям: db.chars.map((c) => ({
        charId: c.id,
        имя: c.name || 'Без имени',
        надето: части.filter((p) => надетоПо.get(c.id)?.has(p)).length,
      })),
    }
  })

  return {
    поПерсонажам: поПерсонажам.sort((a, b) => a.средняя - b.средняя),
    отставание: отставание.sort(
      (a, b) => b.лучшая - b.своя - (a.лучшая - a.своя),
    ),
    комплекты,
  }
}