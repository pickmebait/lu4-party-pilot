/** Часы с округлением до десятых: план считают по часам, а не по минутам. */
const вЧасы = (минут: number) => Math.round((минут / 60) * 10) / 10

export interface ПраймЗаПериод {
  /** Дней с назначенным праймом. */
  дней: number
  /** Суммарные часы прайма. */
  часов: number
  /** Дней, объявленных выходными пати. */
  выходных: number
  /** Средняя длина окна в минутах; 0, если прайма не было. */
  среднееОкно: number
  /** Сколько праймов было в каждый день недели, от понедельника. */
  поДнямНедели: number[]
  /** Часы по месяцам — для столбиков. */
  поМесяцам: { месяц: string; часов: number }[]
  /** Дней прайма ещё впереди: в сумму не входят, но видны отдельно. */
  впереди: number
}

export function праймЗаПериод(db: Db, сОт: string | null, сегодня: string): ПраймЗаПериод {
  let минут = 0
  let дней = 0
  let впереди = 0
  const поДнямНедели = [0, 0, 0, 0, 0, 0, 0]
  const поМесяцам = new Map<string, number>()

  for (const [key, окно] of Object.entries(db.schedule.prime)) {
    const сколько = Math.max(0, окно.to - окно.from)
    if (key > сегодня) {
      впереди++
      continue
    }
    if (!внутри(key, сОт, сегодня)) continue
    дней++
    минут += сколько
    поДнямНедели[(parseKey(key).getDay() + 6) % 7]++
    const месяц = key.slice(0, 7)
    поМесяцам.set(месяц, (поМесяцам.get(месяц) ?? 0) + сколько)
  }

  const выходных = db.schedule.offs.filter((k) => внутри(k, сОт, сегодня)).length

  return {
    дней,
    часов: вЧасы(минут),
    выходных,
    среднееОкно: дней ? Math.round(минут / дней) : 0,
    поДнямНедели,
    поМесяцам: [...поМесяцам.entries()]
      .sort((a, b) => a[0].localeCompare(b[0]))
      .map(([месяц, мин]) => ({ месяц, часов: вЧасы(мин) })),
    впереди,
  }
}

