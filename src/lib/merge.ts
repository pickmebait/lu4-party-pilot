/**
 * Совместная работа: правка своего персонажа поверх чужой версии базы.
 *
 * Правки хранятся одним документом на всю пати, поэтому копия у каждого
 * устаревает, как только кто-то другой сохранился. Раньше это означало, что
 * сохранить нельзя было вообще: сервер отвечал «можно править только своего
 * персонажа», и человек терял правку на середине работы.
 *
 * Смысл слияния простой: в чужой базе всё правильное, кроме моего
 * персонажа, — его я и заменяю своим. Это ровно то, что токен персонажа
 * позволяет, и ничего больше.
 */
import type { Char, Db } from '@/types'

export interface Слияние {
  /** Что отправить на сервер. */
  db: Db
  /** Чужие изменения, которые подтянулись вместе с правкой. */
  подтянуто: boolean
  /**
   * Персонажа удалили, пока правился. Тогда его правке некуда идти, и
   * сообщаем об этом отдельно — иначе человек увидит «сохранено» и не
   * заметит, что персонажа больше нет.
   */
  персонажаНет: boolean
}

/**
 * Подставляет правку своего персонажа в чужую версию базы.
 *
 * Всё остальное берётся из сервера как есть: чужие персонажи, общая казна,
 * расписание, хотелки. Свой персонаж — целиком из локальной копии, потому
 * что он и есть то, что этому токену принадлежит.
 */
export function слитьСвое(mine: Db, server: Db, charId: string, кто: string): Слияние {
  const мой: Char | undefined = mine.chars.find((c) => c.id === charId)

  if (!мой) {
    // Персонажа нет ни в чём: значит, его уже удалили. Своего пристраивать
    // некуда, отправляем базу сервера как есть и говорим об этом прямо.
    return { db: { ...server, updatedBy: кто }, подтянуто: true, персонажаНет: true }
  }

  const естьНаСервере = server.chars.some((c) => c.id === charId)

  return {
    db: {
      ...server,
      updatedBy: кто,
      chars: server.chars.map((c) => (c.id === charId ? мой : c)),
    },
    подтянуто: true,
    персонажаНет: !естьНаСервере,
  }
}

/**
 * Что именно подтянулось с чужой стороны.
 *
 * Имена нужны не для красоты: человек должен увидеть, чьи правки его
 * затронули, иначе «всё сохранилось» не значит ничего.
 */
export function ктоЗатронут(mine: Db, server: Db, charId: string): string[] {
  const мойПрежний = mine.chars.find((c) => c.id === charId)
  if (!мойПрежний) return []

  const имена = new Set<string>()
  for (const чужой of server.chars) {
    if (чужой.id === charId) continue
    const мой = mine.chars.find((c) => c.id === чужой.id)
    if (мой && JSON.stringify(мой) !== JSON.stringify(чужой)) имена.add(чужой.name || 'персонаж')
  }

  const вКазне = server.warehouse.stacks.length !== mine.warehouse.stacks.length
  if (вКазне) имена.add('общая казна')

  return [...имена]
}