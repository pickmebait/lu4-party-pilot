import { НИК_МАКС, написаноБезПробелов, привестиНик } from '@/lib/nick'

/**
 * Поле ника.
 *
 * Правило и без того живёт одно, в lib/nick.ts, но само поле было написано
 * в двух формах — правки персонажа и добавления нового. И оно уже разошлось:
 * в одной подсказка «Ник в игре — до 16 символов», в другой «Лишнее будет
 * отброшено», и правило «не пусто» было только в одной из них. Через месяц
 * разошлись бы и рамки поля.
 *
 * Здесь всё поле целиком: рамка, подсказка, обрезка при вводе и приведение при
 * уходе. Формы отдают значение и получают его — править им больше нечего.
 */
export function NickInput({
  value,
  onChange,
  className = 'input',
  autoFocus = false,
}: {
  value: string
  onChange: (v: string) => void
  className?: string
  autoFocus?: boolean
}) {
  const слишкомДлинный = написаноБезПробелов(value).length > НИК_МАКС
  const пустой = привестиНик(value).length === 0

  return (
    <>
      <input
        className={className}
        autoFocus={autoFocus}
        value={value}
        maxLength={НИК_МАКС + 4}
        placeholder={`ник в игре, до ${НИК_МАКС} символов без пробелов`}
        onChange={(e) => {
          // Обрезаем с запасом на пробелы: человек не должен упереться в потолок,
          // не успев дописать имя.
          const чистый = написаноБезПробелов(e.target.value)
          onChange([...чистый].slice(0, НИК_МАКС + 4).join(''))
        }}
        onBlur={() => onChange(привестиНик(value))}
      />
      {слишкомДлинный && (
        <p className="hint err-hint">
          Ник в игре — до {НИК_МАКС} символов. Лишнее будет отброшено.
        </p>
      )}
      {!слишкомДлинный && пустой && <p className="hint">Без ника персонажа не найти.</p>}
    </>
  )
}

/** Годится ли написанное имя для сохранения. Одно место для обеих форм. */
export function никПодходит(value: string): boolean {
  return написаноБезПробелов(value).length <= НИК_МАКС && привестиНик(value).length > 0
}