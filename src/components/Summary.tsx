import { useEffect, useMemo, useState } from 'react'
import { useDb } from '@/lib/store'
import {
  дниПраймов,
  началоПериода,
  основнаяГотовность,
  премиумСводка,
  праймЗаПериод,
  явкаЗаПериод,
  type ПериодДней,
} from '@/lib/analytics'
import { formatDay, formatDayRange, formatMinutes, formatWeekday } from '@/lib/schedule'
import { userTimeZone, wallTimeAt } from '@/lib/timezone'
import { началоИстории } from './summary/format'
import { РЕЖИМЫ, type Режим } from './summary/model'
import { Штаб } from './summary/Staff'
import { Ритм } from './summary/Rhythm'
import { SegPill } from './SegPill'

/**
 * Выбранный режим живёт в модуле, а не в состоянии компонента.
 *
 * Раздел пересоздаётся при каждом уходе на другую вкладку. Если хранить
 * режим в компоненте, вернувшись, человек получил бы «Общую» вместо
 * периода, который выбирал. Это не данные пати, а способ посмотреть —
 * и он должен переживать переключение вкладок.
 */
let выбранныйРежим: Режим = 'общая'

/* ------------------------------------------------------------- разметка */

/**
 * Сводка: «Штаб пати» для текущего состояния и «Ритм пати» для истории.
 *
 * Период — настоящий фильтр только во втором режиме. В «Штабе» он отвечает
 * лишь на вопрос «как давно» у пары цифр, потому что снаряжение, ПА и
 * контакты хранятся как текущее состояние, без истории.
 */
export function SummaryView({
  onOpenSchedule,
  часовойПояс = userTimeZone(),
  момент,
  начальныйРежим,
  начальныеСабы,
}: {
  onOpenSchedule?: () => void
  /** Пояс пользователя; параметр нужен проверкам и запасному пути. */
  часовойПояс?: string
  /** Начальный момент; в приложении не задаётся, нужен проверкам. */
  момент?: Date
  /** Начальный вид; в приложении не задаётся, нужен проверкам истории. */
  начальныйРежим?: Режим
  /** Начальная вкладка классов; в приложении не задаётся, нужна проверкам. */
  начальныеСабы?: boolean
}) {
  const db = useDb()
  const [режим, setРежим] = useState<Режим>(начальныйРежим ?? выбранныйРежим)
  const [сейчас, setСейчас] = useState(() => момент ?? new Date())

  // Время нужно настоящее: «до старта» — не украшение, а единственная
  // цифра, которую человек проверяет перед входом. Раз в полминуты хватает,
  // чтобы она не врала и не дёргала страницу. Заданный момент не тикает:
  // проверки должны видеть один и тот же вечер.
  useEffect(() => {
    if (момент) return
    const таймер = window.setInterval(() => setСейчас(new Date()), 30_000)
    return () => window.clearInterval(таймер)
  }, [момент])

  const выбрать = (новый: Режим) => {
    выбранныйРежим = новый
    setРежим(новый)
  }

  /*
   * Сегодняшний день и часы — из того же пояса, в котором считаются прайм и
   * ось. `new Date().getHours()` совпадает с ним не всегда: браузер может не
   * отдать пояс, и тогда время уже московское, а «сегодня» осталось бы
   * местным.
   */
  const местноеСейчас = wallTimeAt(сейчас.getTime(), часовойПояс)
  const сегодня = местноеСейчас.key
  const минутСейчас = местноеСейчас.minutes
  const дней: ПериодДней = режим === 'общая' ? 30 : режим
  const сОт = режим === 'общая' ? null : началоПериода(дней, сегодня)

  const основные = useMemo(
    () => db.chars.filter((c) => c.affil !== 'window'),
    [db.chars],
  )
  const явка30 = useMemo(
    () => явкаЗаПериод(db, началоПериода(30, сегодня), сегодня, основные),
    [db, сегодня, основные],
  )
  const прайм = useMemo(() => праймЗаПериод(db, сОт, сегодня), [db, сОт, сегодня])
  const явка = useMemo(
    () => явкаЗаПериод(db, сОт, сегодня, основные),
    [db, сОт, сегодня, основные],
  )
  const дниПрайма = useMemo(
    () => дниПраймов(db.schedule, сОт, сегодня),
    [db, сОт, сегодня],
  )
  const готовность = useMemo(() => основнаяГотовность(db), [db])
  const премиум = useMemo(() => премиумСводка(db, сегодня), [db, сегодня])

  const начало = сОт ?? началоИстории(db, сегодня)
  const крошка =
    режим === 'общая'
      ? `${formatWeekday(сегодня)}, ${formatDay(сегодня)} · ${formatMinutes(минутСейчас)}`
      : formatDayRange([начало, сегодня])

  return (
    <section className="view dash-view">
      <div className="view-head dash-head">
        <div className="view-actions affil">
          <SegPill
            варианты={РЕЖИМЫ}
            значение={режим}
            onВыбрать={выбрать}
            ariaLabel="Режим сводки"
          />
        </div>
        <span className="dash-crumb">{крошка}</span>
      </div>

      {db.chars.length === 0 ? (
        <div className="empty">
          <p>В пати пока нет персонажей.</p>
          <p className="hint">
            Как только они появятся, здесь станут видны прайм, явка, снаряжение и роли.
          </p>
        </div>
      ) : режим === 'общая' ? (
        <Штаб
          db={db}
          сегодня={сегодня}
          сейчас={сейчас}
          часовойПояс={часовойПояс}
          основные={основные}
          явка30={явка30}
          готовность={готовность}
          премиум={премиум}
          onOpenSchedule={onOpenSchedule}
          начальныеСабы={начальныеСабы}
        />
      ) : (
        <Ритм
          db={db}
          сегодня={сегодня}
          дней={дней}
          сОт={сОт}
          прайм={прайм}
          явка={явка}
          дниПрайма={дниПрайма}
          начало={начало}
          основные={основные}
        />
      )}
    </section>
  )
}
