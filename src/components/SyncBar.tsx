import { useCallback, useEffect, useRef, useState } from 'react'
import type { Db } from '@/types'
import { fetchDb, saveDb } from '@/lib/api'
import { ктоЗатронут, одноИТоЖе, слитьСвое } from '@/lib/merge'
import {
  авторПравки,
  базаПрочитана,
  getDb,
  getSession,
  replaceDb,
  updateSession,
  useDb,
  useОткрытаяФорма,
} from '@/lib/store'
import { formatAgo } from '@/lib/util'
import { PartyMenu } from './PartyMenu'

type SyncState =
  | { kind: 'idle' }
  | { kind: 'busy'; what: string }
  | { kind: 'ok'; text: string }
  | { kind: 'err'; text: string }

/**
 * Что сказать, когда запрос пришлось отправить заново.
 *
 * Слова подобраны так, чтобы человек понял дело, а не устройство: он правил
 * персонажа и ждёт, пока правка ляжет в пати. «Связь оборвалась — отправляю
 * заново» говорит ровно это, а «повтор запроса» — про то, как устроен обмен.
 *
 * Обрыв связи человек обычно не замечает: он не рвётся сразу, а зависает.
 * Поэтому надпись нужна — иначе человек решит, что приложение подвисло, и
 * начнёт править заново.
 */
const ПОВТОР_НАЧАЛ = 'Связь оборвалась — отправляю заново'
const ПОВТОР_ПРОШЁЛ = 'Сохранено. Первый запрос не дошёл, отправлен заново.'


/**
 * Сколько ждём покоя, прежде чем отправлять правку.
 *
 * Замер сделан целиком: полторы секунды ждём, около полутора уходит на запись
 * в GitHub, и столько же человек смотрит на надпись «Сохраняю…» — почти
 * четыре секунды на одно сохранение.
 *
 * Пауза набрана по размеру: набран уровень и переключил ветку — две отправки
 * подряд не нужны, и запись соберёт их в одну. Цена паузы не в потерянном
 * времени, а в лишней записи в репозиторий, поэтому её и сокращают. Полторы
 * секунды ещё собирают всё, что человек успел сделать подряд, а ждать дольше
 * уже заметно: правка всё равно не уйдёт мгновенно.
 */
const ПАУЗА_СОХРАНЕНИЯ_МС = 1500

/**
 * Пауза перед следующей попыткой, если предыдущие не вышли.
 *
 * Без неё получается лавина. Неудача ставит надпись об ошибке, надпись меняет
 * состояние, эффект автосохранения на это перезапускается и через паузу
 * пробует снова. Надпись снова меняется — и так по кругу, пока связь не
 * вернётся: за минуту уходит сотня одинаковых запросов, а человек смотрит на
 * мельтешащую надпись и ничего не понимает.
 *
 * Пауза растёт вдвое с каждой неудачей и упирается в минуту. Правка при этом
 * не теряется: она лежит в базе на устройстве и уйдёт, как только связь
 * вернётся, — хоть через минуту, хоть через час.
 */
const откатСохранения = (неудач: number): number =>
  Math.min(ПАУЗА_СОХРАНЕНИЯ_МС * 2 ** Math.max(0, неудач - 1), 60_000)

/** Как часто спрашивать сервер, пока вкладка открыта и правок не сохранено. */
const ПАУЗА_ПРОВЕРКИ_МС = 45_000

/**
 * Синхронизация с пати и меню доступа.
 *
 * Кнопок «Загрузить» и «Сохранить» больше нет, и это не косметика.
 * Правки хранятся в общей базе, за которую отвечает не только тот, кто
 * нажал кнопку: пока человек думает, передумает и напишет «Сохранить», его
 * копия успевает разойтись с чужой, и сохранение приходится разбирать.
 * Теперь всё происходит само: правка уходит после короткой паузы в
 * спокойствии, а база подтягивается при возвращении на вкладку.
 *
 * Что осталось на виду — только то, о чём человек должен знать: идёт
 * отправка, что приехало, что подтянулось вместе с его правкой и в чём
 * проблема. Спрятать и это нельзя: молча ушедшая в чужую базу правка
 * выглядела бы как потерянная.
 */
export function SyncBar() {
  const db = useDb()
  const session = getSession()!
  const формаОткрыта = useОткрытаяФорма()
  const [state, setState] = useState<SyncState>({ kind: 'idle' })
  const [incoming, setIncoming] = useState<Db | null>(null)

  const свойCharId = session.role === 'char' ? session.charId : null
  const загружается = useRef(false)
  const сохраняется = useRef(false)
  /**
   * Что мы последний раз отправляли на сервер.
   *
   * Нужно, чтобы отличить чужое действие от своего же. Связь рвётся уже после
   * того, как запись легла на сервер, — и тогда сервер честно отвечает «база
   * уже другая», хотя менялась она ровно на ту, которую просили. По отданному
   * запросу видно сразу: если в пати лежит именно это, значит запись наша.
   */
  const посланное = useRef<{ db: Db } | null>(null)
  /**
   * Сколько сохранений подряд не вышло. Сбрасывается при первом успехе.
   *
   * Именно состояние, а не ссылка: следующая попытка должна планироваться
   * заново после каждой неудачи, и для этого автосохранению нужно увидеть
   * изменение. Со ссылкой эффект не перезапустится — он читает её, но
   * изменения не замечает, — и после первой неудачи правка зависнет до
   * перезагрузки страницы.
   */
  const [неудач, setНеудач] = useState(0)

  /*
   * Есть ли несохранённое.
   *
   * Три случая, и все три означают «не затирать серверным»:
   *
   *   база-заглушка  — она не от этой пати, отправлять нечего, и отправка
   *                    пустоты поверх настоящей базы стёрла бы чужое;
   *   своя правка    — метка разошлась с последней подтверждённой;
   *   правка без опоры — метки сессии нет вовсе: вход был без сети, сервер
   *                    ещё ни разу не отдавал свою версию, и сравнивать не с
   *                    чем. Правка при этом настоящая, и стирать её нельзя.
   */
  const естьСвоиПравки = () =>
    базаПрочитана() && (!session.lastSyncedAt || (getDb().updatedAt ?? '') !== session.lastSyncedAt)

  /**
   * Чтение сервера.
   *
   * молча = не сообщать об успехе: обновление идёт само каждые полминуты,
   * и надпись «загружено» мигала бы без причины. Говорим, когда приехало
   * что-то новое, когда сломалось или когда человек нажал кнопку сам.
   */
  const загрузить = useCallback(
    async (молча: boolean) => {
      if (загружается.current) return
      загружается.current = true
      if (!молча) setState({ kind: 'busy', what: 'Загружаю из пати…' })

      try {
        const res = await fetchDb(session.apiUrl, session.token)
        if (!res.ok) {
          if (!молча) setState({ kind: 'err', text: res.error })
          return
        }

        const remote = res.value
        const local = getDb()
        /*
         * Сессию читаем отсюда, а не из замыкания: пока запрос летел, она могла
         * уехать вперёд — например, прийти успешное сохранение.
         */
        const живое = getSession()!

        /*
         * Ответ, который за время полёта перестал быть свежим, — не применять.
         *
         * Чтение уходит за четверть секунды, за это время успевает пройти
         * сохранение и поднять метку выше той, что мы запросили. Возврат старого
         * ответа откатывал бы базу назад, и следующая же правка ушла бы в
         * сервер от старой метки — с отказом, которого на самом деле нет.
         */
        if ((remote.updatedAt ?? '') < (живое.lastSyncedAt ?? '')) return

        /*
         * Метка пустая — базу этой пати ещё ни разу не читали, и на руках
         * пустая заглушка, а не правки человека. Считать её правками нельзя:
         * тогда загрузка откажется затирать собственную заглушку и человек
         * так и увидит пустую пати.
         */
        const свои = базаПрочитана()
          ? !живое.lastSyncedAt || (local.updatedAt ?? '') !== живое.lastSyncedAt
          : false

        if (свои) {
          /*
           * Есть несохранённое — не затираем молча.
           *
           * Если в базе кто-то уже работал, говорим и про это: сохранение
           * разберётся само, токен персонажа подставит свою правку в чужую
           * базу, мастеру покажем выбор.
           *
           * Сообщение ставится в любом случае. Раньше при выходе отсюда
           * надпись оставалась «Загружаю из пати…», и полоса зависала: кнопки
           * не нажимаются, а человек не понимает, чего ждёт.
           */
          const вПатиНовее = (remote.updatedAt ?? '') !== живое.lastSyncedAt
          if (!молча || вПатиНовее) {
            setState(
              вПатиНовее
                ? {
                    kind: 'err',
                    text: `В пати есть более свежая версия (от: ${remote.updatedBy || 'неизвестно'}, ${formatAgo(remote.updatedAt)}). Правка подставится в неё сама.`,
                  }
                : {
                    kind: 'err',
                    text: 'Есть несохранённые правки — загрузка их бы затёрла.',
                  },
            )
          }
          return
        }

        const изменилось = (remote.updatedAt ?? '') !== живое.lastSyncedAt
        if (!изменилось && молча) return

        replaceDb(remote)
        updateSession({ lastSyncedAt: remote.updatedAt })
        setState({
          kind: 'ok',
          text: `Загружено из пати${remote.updatedBy ? ` (от: ${remote.updatedBy})` : ''}`,
        })
      } finally {
        загружается.current = false
      }
    },
    [session.apiUrl, session.token, session.lastSyncedAt],
  )

  const сохранить = useCallback(async () => {
    if (сохраняется.current) return
    if (!естьСвоиПравки()) return
    сохраняется.current = true

    /*
     * Сессию читаем отсюда, а не из замыкания: замыкание хранит метку на
     * момент отрисовки, а сохранение может быть вызвано позже — после того как
     * метка уже сдвинулась. Сохранение по старой метке гарантированно
     * получало отказ от сервера, и метка от этого уже не отставала.
     */
    const живое = getSession()!

    try {
      const current = getDb()
      посланное.current = { db: current }
      const res = await saveDb(
        живое.apiUrl,
        живое.token,
        current,
        живое.lastSyncedAt,
        // Пока запрос ещё идёт, человек видит, что он ушёл заново. Молчать
        // тут нельзя: надпись «Сохраняю в пати…» двадцать секунд выглядит как
        // зависшее приложение.
        () => setState({ kind: 'busy', what: ПОВТОР_НАЧАЛ }),
      )

      if (res.ok) {
        setНеудач(0)
        updateSession({ lastSyncedAt: res.value.updatedAt })
        // Локальная метка должна совпасть с серверной, иначе следующая
        // правка снова сочтётся несохранённой.
        replaceDb({ ...current, updatedAt: res.value.updatedAt })
        // Повтор был виден уже во время отправки, но он мог и не выйти: дубль
        // уходит после ожидания, даже если первый запрос просто медленный.
        // Подтверждаем по счётчику попыток, а не по тому, показывали ли надпись.
        setState(
          res.попыток > 1
            ? { kind: 'ok', text: ПОВТОР_ПРОШЁЛ }
            : { kind: 'idle' },
        )
        return
      }

      /*
       * Отказ по правам при токене персонажа — это не запрет. Человек правил
       * своего персонажа, а у него в копии устарел сосед. Сервер присылает
       * актуальную базу: подставляем в неё своего персонажа и сохраняем
       * снова. Так правка уходит и чужое не теряется.
       */
      if (res.forbidden && свойCharId) {
        const чей = ктоЗатронут(current, res.forbidden.db, свойCharId)
        const слияние = слитьСвое(current, res.forbidden.db, свойCharId, авторПравки())

        if (слияние.персонажаНет) {
          replaceDb(слияние.db)
          updateSession({ lastSyncedAt: слияние.db.updatedAt })
          setState({
            kind: 'err',
            text: 'Твоего персонажа удалили из пати, пока ты правил. Правка не сохранена.',
          })
          return
        }

        const повтор = await saveDb(
          живое.apiUrl,
          живое.token,
          слияние.db,
          res.forbidden.db.updatedAt,
        )
        if (!повтор.ok) {
          setState({ kind: 'err', text: повтор.error })
          return
        }

        replaceDb({ ...слияние.db, updatedAt: повтор.value.updatedAt })
        updateSession({ lastSyncedAt: повтор.value.updatedAt })
        setState(
          чей.length
            ? { kind: 'ok', text: `Сохранено. Подтянуты изменения: ${чей.join(', ')}` }
            : { kind: 'idle' },
        )
        return
      }

      /*
       * Персонажа удалили, пока человек правил.
       *
       * Правка в этом случае не сохранится, а сообщение о выборе между
       * двумя версиями бессмысленно: выбирать нечего, персонажа больше нет.
       */
      if (res.conflict && свойCharId && !res.conflict.chars.some((c) => c.id === свойCharId)) {
        replaceDb(res.conflict)
        updateSession({ lastSyncedAt: res.conflict.updatedAt })
        setIncoming(null)
        setState({
          kind: 'err',
          text: 'Твоего персонажа удалили из пати, пока ты правил. Правка не сохранена.',
        })
        return
      }

      /*
       * Отказ после собственной записи — не чужое действие.
       *
       * Связь рвётся уже после того, как запрос до сервера дошёл, и тогда он
       * отвечает «в пати уже другое состояние», хотя менялась база ровно на ту,
       * которую просили. Сверяем отданное с лежащим: если там наше — запись
       * состоялась, а потерялся только ответ. Метку берём с сервера и
       * говорим об этом прямо: человек должен знать, что отправка потребовала
       * второй попытки, а не молчать.
       */
      const отданное = посланное.current
      if (res.conflict && отданное && одноИТоЖе(res.conflict, отданное.db)) {
        updateSession({ lastSyncedAt: res.conflict.updatedAt })
        if (одноИТоЖе(current, отданное.db)) {
          replaceDb({ ...current, updatedAt: res.conflict.updatedAt })
          setНеудач(0)
          setState({ kind: 'ok', text: 'Сохранено. Ответ не дошёл — метку пати взял заново.' })
        }
        return
      }

      if (res.conflict) {
        setIncoming(res.conflict)
        setState({
          kind: 'err',
          text: `В пати изменилось, пока ты правил (от: ${res.conflict.updatedBy || 'неизвестно'}, ${formatAgo(res.conflict.updatedAt)}).`,
        })
        return
      }
      /*
       * Обрыв связи и отказ сервера считаем отдельно.
       *
       * Отказ по делу — конфликт, нет прав — это не повод бить чаще: человек
       * разберётся сам, и долбить тут нечего. А вот когда сервер не отвечает
       * вовсе, дело выправится само, и повтор лишь постепенно отрастит паузу.
       */
      if (res.статус === 0) setНеудач((n) => n + 1)
      setState({ kind: 'err', text: res.error })
    } finally {
      сохраняется.current = false
    }
    посланное.current = null
  }, [свойCharId])

  /*
   * Автосохранение.
   *
   * Пауза собирает несколько правок подряд в одну отправку: иначе набор
   * уровня и заточки дал бы десяток записей в репозиторий и десяток
   * коммитов на одну минуту работы.
   *
   * Пока открыта форма правки, ждать незачем — правки в базе ещё нет, и
   * отправлять нечего. Сама форма поставит её, когда нажмут «Сохранить».
   *
   * Пока запись уже идёт, новую не заводим и надпись не трогаем. Эффект
   * перезапускается на каждой смене состояния, и без проверки он через паузу
   * снова ставил бы «Сохраняю в пати…» поверх того, что уже написано.
   * А надпись к этому моменту не «Сохраняю в пати…», а «Связь оборвалась —
   * отправляю заново»: человек узнал бы, что запрос ушёл повторно, и через
   * полторы секунды снова не узнал бы.
   */
  useEffect(() => {
    if (формаОткрыта) return
    /*
     * Пока на руках заглушка, сохранять нельзя: её метка своя, свежая, и без
     * проверки приложение решило бы, что человек правил, и отправило пустоту
     * поверх настоящей базы.
     *
     * Только про заглушку. Пустая метка сессии — не повод молчать: правка
     * человека настоящая, и молчание оставило бы её в браузере навсегда, а
     * догрузка с сервера рано или поздно её стёрла бы.
     */
    if (!базаПрочитана()) return
    if ((db.updatedAt ?? '') === session.lastSyncedAt) return
    if (state.kind === 'err' && incoming) return

    const таймер = setTimeout(() => {
      /*
       * Проверка именно здесь, а не в теле эффекта.
       *
       * Тело эффекта тоже перезапускается, пока запись идёт, и проверка в нём
       * гасила бы всё до конца: ссылка ещё занята, эффект уходит, а переменяться
       * ей уже не на что — правка зависла бы до перезагрузки. Здесь проверка
       * просто снимает лишний таймер, а следующая попытка всё равно
       * запланируется по счётчику неудач.
       */
      if (сохраняется.current) return
      setState({ kind: 'busy', what: 'Сохраняю в пати…' })
      void сохранить()
    }, откатСохранения(неудач))
    return () => clearTimeout(таймер)
  }, [db.updatedAt, session.lastSyncedAt, формаОткрыта, сохранить, state.kind, incoming, неудач])

  /**
   * Обновление само, пока вкладка открыта.
   *
   * Три повода, а не таймер на каждую секунду: вернуться к вкладке,
   * переключиться на неё и подождать. Каждая проверка — это чтение из
   * репозитория, поэтому лишних обращений к GitHub быть не должно.
   */
  useEffect(() => {
    /*
     * База этой пати ещё не прочитана — вход был без сети, и на экране пусто.
     * Ждать следующей проверки нельзя: человек смотрит на пустую пати и
     * думает, что она стёрта. Тянем сразу и говорим об этом надписью.
     */
    if (!базаПрочитана() && !формаОткрыта) {
      setState({ kind: 'busy', what: 'Загружаю из пати…' })
      void загрузить(false)
    }

    const тик = setInterval(() => {
      if (document.visibilityState !== 'visible') return
      if (естьСвоиПравки()) return
      if (формаОткрыта) return
      void загрузить(true)
    }, ПАУЗА_ПРОВЕРКИ_МС)

    const вернулись = () => {
      if (document.visibilityState !== 'visible') return
      if (естьСвоиПравки()) return
      if (формаОткрыта) return
      void загрузить(true)
    }

    window.addEventListener('focus', вернулись)
    document.addEventListener('visibilitychange', вернулись)
    return () => {
      clearInterval(тик)
      window.removeEventListener('focus', вернулись)
      document.removeEventListener('visibilitychange', вернулись)
    }
  }, [загрузить, session, формаОткрыта])

  return (
    <div className="sync">
      <div className="sync-main">
        <PartyMenu />
      </div>

      {state.kind === 'busy' && <div className="sync-msg">{state.what}</div>}
      {state.kind === 'ok' && <div className="sync-msg ok">{state.text}</div>}
      {state.kind === 'err' && <div className="sync-msg err">{state.text}</div>}

      {incoming && (
        <div className="sync-actions">
          <button
            className="btn primary tiny"
            onClick={() => {
              replaceDb(incoming)
              updateSession({ lastSyncedAt: incoming.updatedAt })
              setIncoming(null)
              setState({ kind: 'idle' })
            }}
          >
            Взять версию из пати
          </button>
          <button
            className="btn tiny"
            onClick={() => {
              /*
               * Оставить своё — значит записать своё поверх того, что в пати.
               *
               * Раньше кнопка просто закрывала выбор, и это было ловушкой:
               * метка оставалась прежней, автосохранение через паузу уходило с
               * ней снова и снова, и то же самое сообщение возвращалось к
               * человеку по кругу. Теперь метка становится свежей, правка
               * действительно уходит поверх чужой, а токен персонажа на
               * ответе о недостатке прав подставит в неё своего
               * персонажа, как и раньше.
               */
              const серверная = incoming
              setIncoming(null)
              setState({ kind: 'busy', what: 'Сохраняю в пати…' })
              updateSession({ lastSyncedAt: серверная.updatedAt })
              void сохранить()
            }}
          >
            Оставить мою
          </button>
        </div>
      )}
    </div>
  )
}