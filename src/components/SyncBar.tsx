/**
 * Сколько ждём покоя, прежде чем отправлять правку.
 *
 * Замер сделан целиком: полторы секунды ждём, около полутора уходит на запись
 * в GitHub, и столько же человек смотрит на надпись «Сохраняю…» — почти
 * четыре секунды на одно сохранение.
 *
 * Пауза набрана по размеру: набран уровень и переключил ветку — две отправки
 * подряд не нужны, и запись соберёт их в одну. Цена паузы не в потерянном
 * времени, а в лишней записи в репозиторий, поэтому её и сокращают. Полторы
 * секунды ещё собирают всё, что человек успел сделать подряд, а ждать дольше
 * уже заметно: правка всё равно не уйдёт мгновенно.
 */
const ПАУЗА_СОХРАНЕНИЯ_МС = 1500

/**
 * Пауза перед следующей попыткой, если предыдущие не вышли.
 *
 * Без неё получается лавина. Неудача ставит надпись об ошибке, надпись меняет
 * состояние, эффект автосохранения на это перезапускается и через паузу
 * пробует снова. Надпись снова меняется — и так по кругу, пока связь не
 * вернётся: за минуту уходит сотня одинаковых запросов, а человек смотрит на
 * мельтешащую надпись и ничего не понимает.
 *
 * Пауза растёт вдвое с каждой неудачей и упирается в две минуты. Правка при
 * этом не теряется: она лежит в базе на устройстве и уйдёт, как только связь
 * вернётся, — хоть через минуту, хоть через час.
 */
const ПРЕДЕЛ_ПАУЗЫ_СОХРАНЕНИЯ_МС = 120_000

/**
 * Сколько ждём сброса лимита GitHub, если сервер назвал время.
 *
 * Ждать ровно до сброса — самое дешёвое поведение: раньше него GitHub всё
 * равно откажет, и каждый такой отказ только тратит остаток лимита. Предел в
 * 65 минут — это часовое окно GitHub плюс запас: если сервер назвал срок,
 * незачем просыпаться раньше и тратить запрос впустую.
 */
const ПРЕДЕЛ_ОЖИДАНИЯ_ЛИМИТА_МС = 65 * 60_000

const откатСохранения = (неудач: number, ждатьДо = 0): number => {
  const обычная = Math.min(
    ПАУЗА_СОХРАНЕНИЯ_МС * 2 ** Math.max(0, неудач - 1),
    ПРЕДЕЛ_ПАУЗЫ_СОХРАНЕНИЯ_МС,
  )
  const поЛимиту = Math.min(Math.max(0, ждатьДо - Date.now()), ПРЕДЕЛ_ОЖИДАНИЯ_ЛИМИТА_МС)
  return Math.max(обычная, поЛимиту)
}

/**
 * Когда снова можно трогать GitHub после ответа 429.
 *
 * Время присылает сервер, и обычно его достаточно. Но если ответ пришёл от
 * старой версии Worker'а или без поля — молчать нельзя: без срока сохранение
 * вернулось бы к паузе в полторы секунды и снова начало тратить лимит.
 * Минута — заведомо больше любой короткой паузы и заметно меньше часа.
 */
const срокПослеЛимита = (retryAfter?: number): number =>
  Date.now() + (retryAfter && retryAfter > 0 ? retryAfter : 60) * 1000

/** Как часто спрашивать сервер, пока вкладка открыта и правок не сохранено. */
const ПАУЗА_ПРОВЕРКИ_МС = 7_000

/** Дальше этого опрос не отступает: даже при долгой ошибке проверяем раз в минуту. */
const ПРЕДЕЛ_ПАУЗЫ_ПРОВЕРКИ_МС = 60_000

/**
 * Синхронизация с пати и меню доступа.
 *
 * Кнопок «Загрузить» и «Сохранить» больше нет, и это не косметика.
 * Правки хранятся в общей базе, за которую отвечает не только тот, кто
 * нажал кнопку: пока человек думает, передумает и напишет «Сохранить», его
 * копия успевает разойтись с чужой, и сохранение приходится разбирать.
 * Теперь всё происходит само: правка уходит после короткой паузы в
 * спокойствии, а база подтягивается при возвращении на вкладку.
 *
 * Что осталось на виду — только то, о чём человек должен знать: идёт
 * отправка, что приехало, что подтянулось вместе с его правкой и в чём
 * проблема. Спрятать и это нельзя: молча ушедшая в чужую базу правка
 * выглядела бы как потерянная.
 */
export function SyncBar() {
  const db = useDb()
  const session = getSession()!
  const формаОткрыта = useОткрытаяФорма()
  const [state, setState] = useState<SyncState>({ kind: 'idle' })
  const [incoming, setIncoming] = useState<Db | null>(null)

  const свойCharId = session.role === 'char' ? session.charId : null
  const загружается = useRef(false)
  const проверяется = useRef(false)
  const сохраняется = useRef(false)
  /** Сколько проверок меты подряд не вышло: от этого растёт пауза. */
  const неудачПроверки = useRef(0)
  /** Канал для соседних вкладок: своя запись должна быть видна им сразу. */
  const канал = useRef<BroadcastChannel | null>(null)
  /** Когда последний раз отправляли keepalive при уходе: visibilitychange и pagehide идут парой. */
  const уходОтправлен = useRef(0)
  /**
   * Что мы последний раз отправляли на сервер.
   *
   * Нужно, чтобы отличить чужое действие от своего же. Связь рвётся уже после
   * того, как запись легла на сервер, — и тогда сервер честно отвечает «база
   * уже другая», хотя менялась она ровно на ту, которую просили. По отданному
   * запросу видно сразу: если в пати лежит именно это, значит запись наша.
   */
  const посланное = useRef<{ db: Db } | null>(null)
  /**
   * Сколько сохранений подряд не вышло. Сбрасывается при первом успехе.
   *
   * Именно состояние, а не ссылка: следующая попытка должна планироваться
   * заново после каждой неудачи, и для этого автосохранению нужно увидеть
   * изменение. Со ссылкой эффект не перезапустится — он читает её, но
   * изменения не замечает, — и после первой неудачи правка зависнет до
   * перезагрузки страницы.
   */
  const [неудач, setНеудач] = useState(0)
  /**
   * До какого времени не трогать GitHub: сервер сказал, когда сбросится
   * лимит. Ноль — ограничения по времени нет.
   *
   * Общий на чтение и запись: лимит у GitHub один на токен, и если он кончился,
   * то и чтение, и запись получат тот же отказ. Поэтому и опрос, и
   * автосохранение ждут одного и того же срока. Раньше чтение продолжало
   * ходить каждые семь секунд даже во время лимита, и это только тратило его.
   */
  const [ждатьДо, setЖдатьДо] = useState(0)

  /*
   * Убрать надпись, когда она своя.
   *
   * Только об успехе. Ошибку убирать нельзя: она объясняет, что правка не
   * дошла, и молча пропавший текст человек прочитает уже на следующей
   * правке — когда идёт не то, о чём он его читал.
   *
   * Пока человек открыл подробности, надпись не трогаем: он их читает, и
   * исчезновение текста вместе с ними выглядело бы как поломка.
   */
  const подробностиОткрыты = useRef(false)
  const запомнитьОткрытие = useCallback((открыто: boolean) => {
    подробностиОткрыты.current = открыто
  }, [])
  useEffect(() => {
    const note = state.kind === 'idle' ? null : state.note
    if (!note?.убратьЧерезМс) return
    const таймер = setTimeout(() => {
      if (!подробностиОткрыты.current) setState({ kind: 'idle' })
    }, note.убратьЧерезМс)
    return () => clearTimeout(таймер)
  }, [state])

  /*
   * Несохранённое — это признак базы, а не расхождение меток.
   *
   * Старая копия без метки сервера больше не считается правкой: именно
   * из-за неё часть людей не видела расписание, а сервер получал пустую
   * базу поверх свежей. Признак ставится при каждом изменении и снимается
   * только принятой с сервера версией.
   */

  /**
   * Чтение сервера.
   *
   * молча = не сообщать об успехе: обновление идёт само, а лёгкая мета
   * проверяется каждые семь секунд, и надпись «загружено» мигала бы без
   * причины. Говорим, когда приехало что-то новое, когда сломалось или когда
   * человек нажал кнопку сам.
   */
  const загрузить = useCallback(
    async (молча: boolean) => {
      if (загружается.current) return
      загружается.current = true
      живойСтатусНачали()
      if (!молча) setState({ kind: 'busy', note: { текст: СЛОВА.загружаю } })

      try {
        const res = await fetchDb(session.apiUrl, session.token)
        if (!res.ok) {
          /*
           * Лимит запоминаем и при молчаливой проверке: иначе опрос каждые
           * 7 секунд продолжал бы тратить остаток лимита, а сохранение не
           * знало бы, что ждать надо до того же срока.
           */
          if (res.статус === 429) {
            const до = срокПослеЛимита(res.retryAfter)
            setЖдатьДо(до)
            живойСтатусЛимит(до, res.error)
          } else if (res.статус === 0) {
            живойСтатусОбрыв(res.error)
          } else {
            живойСтатусЗаметка(res.error)
          }
          if (!молча) {
            setState({
              kind: 'err',
              note:
                res.статус === 0
                  ? {
                      /*
                       * Обрыв при загрузке — не то же, что при записи: человек
                       * ничего не теряет, у него на руках последнее, что он
                       * видел. Говорим прямо, иначе он подумает, что пропала
                       * его собственная правка.
                       */
                      текст: СЛОВА.нетСвязиПриЗагрузке,
                      детали: деталиЗапроса({
                        адрес: session.apiUrl,
                        вид: 'чтение базы',
                        код: res.статус,
                        текстСервера: res.error,
                      }),
                    }
                  : res.статус === 429
                    ? {
                        текст: СЛОВА.лимитGitHubПриЗагрузке,
                        детали: деталиЗапроса({
                          адрес: session.apiUrl,
                          вид: 'чтение базы',
                          код: res.статус,
                          текстСервера: res.error,
                        }),
                      }
                    : приОтказе(res.error, res.статус, session.apiUrl),
            })
          }
          return
        }

        // Чтение прошло — GitHub снова отвечает, значит лимита больше нет.
        setЖдатьДо(0)
        живойСтатусУспех(res.value.updatedAt ?? null)

        const remote = res.value
        /*
         * Сессию читаем отсюда, а не из замыкания: пока запрос летел, она могла
         * уехать вперёд — например, прийти успешное сохранение.
         */
        const живое = getSession()!

        /*
         * Ответ, который за время полёта перестал быть свежим, — не применять.
         *
         * Чтение уходит за четверть секунды, за это время успевает пройти
         * сохранение и поднять метку выше той, что мы запросили. Возврат старого
         * ответа откатывал бы базу назад, и следующая же правка ушла бы в
         * сервер от старой метки — с отказом, которого на самом деле нет.
         */
        if ((remote.updatedAt ?? '') < (живое.lastSyncedAt ?? '')) return

        /*
         * Несохранённая правка — единственная причина не принимать серверную
         * версию молча. Сама по себе пустая метка сессии правкой не является:
         * так старая копия базы затирала свежее расписание.
         */
        const свои = естьНесохранённое()

        if (свои) {
          /*
           * Есть несохранённое — не затираем молча.
           *
           * Если в базе кто-то уже работал, говорим и про это: сохранение
           * разберётся само, токен персонажа подставит свою правку в чужую
           * базу, мастеру покажем выбор.
           *
           * Сообщение ставится в любом случае. Раньше при выходе отсюда
           * надпись оставалась «Загружаю из пати…», и полоса зависала: кнопки
           * не нажимаются, а человек не понимает, чего ждёт.
           */
          const вПатиНовее = (remote.updatedAt ?? '') !== живое.lastSyncedAt
          if (!молча || вПатиНовее) {
            setState({
              kind: 'err',
              note: {
                /*
                 * Что будет дальше — половина смысла надписи. Без неё человек
                 * читает «в пати изменилось» как «правка потеряна» и начинает
                 * переписывать всё заново, хотя правка уйдёт сама.
                 */
                текст: вПатиНовее ? СЛОВА.вПаТИИзменилосьПодставится : СЛОВА.естьНесохранённые,
                детали: деталиЗапроса({
                  адрес: живое.apiUrl,
                  вид: 'чтение базы',
                  код: res.статус,
                  меткаСервера: remote.updatedAt,
                  меткаСвоя: живое.lastSyncedAt,
                  текстСервера: 'предыдущий запрос не дошёл',
                }),
              },
            })
          }
          return
        }

        const изменилось = (remote.updatedAt ?? '') !== живое.lastSyncedAt
        if (!изменилось && молча) return

        replaceDb(remote)
        updateSession({ lastSyncedAt: remote.updatedAt })
        setState({
          kind: 'ok',
          note: {
            текст: remote.updatedBy ? СЛОВА.загруженоСАвтором(remote.updatedBy) : СЛОВА.загружено,
            детали: деталиЗапроса({
              адрес: живое.apiUrl,
              вид: 'чтение базы',
              код: res.статус,
              меткаСервера: remote.updatedAt,
            }),
            убратьЧерезМс: 4000,
          },
        })
      } finally {
        загружается.current = false
      }
    },
    [session.apiUrl, session.token, session.lastSyncedAt],
  )

  /**
   * Лёгкая проверка: изменилась ли база на сервере.
   *
   * Полную базу каждые семь секунд не тянем. Спрашиваем только версию и имя;
   * если версия другая — загружаем базу обычным путём. Ответ сервер берёт из
   * своего семисекундного снимка, поэтому GitHub не получает запрос на каждую
   * вкладку и не сжигает лимит.
   */
  const проверитьМету = useCallback(async (): Promise<boolean> => {
    if (проверяется.current) return false
    проверяется.current = true

    try {
      const res = await fetchMetaLight(session.apiUrl, session.token)
      if (!res.ok) {
        неудачПроверки.current += 1
        if (res.статус === 429) {
          const до = срокПослеЛимита(res.retryAfter)
          setЖдатьДо(до)
          живойСтатусЛимит(до, res.error)
        } else if (res.статус === 0) {
          живойСтатусОбрыв(res.error)
        } else {
          живойСтатусЗаметка(res.error)
        }
        return false
      }

      неудачПроверки.current = 0
      const meta = res.value
      /*
       * Сессию читаем здесь, а не из замыкания: пока запрос летел, могла
       * прийти успешная запись и сдвинуть метку.
       */
      const живое = getSession()
      if (!живое) return false

      if (meta.name && meta.name !== живое.name) updateSession({ name: meta.name })
      живойСтатусУспех(meta.updatedAt ?? null)

      if ((meta.updatedAt ?? '') !== (живое.lastSyncedAt ?? '')) {
        await загрузить(true)
      }
      return true
    } catch (e) {
      неудачПроверки.current += 1
      живойСтатусОбрыв(e instanceof Error ? e.message : 'неизвестная ошибка')
      return false
    } finally {
      проверяется.current = false
    }
  }, [session.apiUrl, session.token, загрузить])

  /*
   * Соседние вкладки.
   *
   * Своя запись обновляет сервер и его снимок сразу, поэтому другим вкладкам
   * незачем ждать семи секунд: они получают сигнал и проверяют мету тут же.
   * Канал не заменяет опрос — он только сокращает задержку внутри одного
   * браузера.
   */
  const проверитьМетуСвежая = useRef(проверитьМету)
  useEffect(() => {
    проверитьМетуСвежая.current = проверитьМету
  }, [проверитьМету])

  useEffect(() => {
    if (typeof BroadcastChannel === 'undefined') return
    const ch = new BroadcastChannel(`pp-party-${session.partyId}`)
    канал.current = ch
    ch.onmessage = (event: MessageEvent) => {
      if (event.data?.type !== 'saved') return
      if (document.visibilityState !== 'visible') return
      void проверитьМетуСвежая.current()
    }
    return () => {
      ch.close()
      if (канал.current === ch) канал.current = null
    }
  }, [session.partyId])

  const сообщитьВкладкам = useCallback((updatedAt: string) => {
    канал.current?.postMessage({ type: 'saved', partyId: session.partyId, updatedAt })
  }, [session.partyId])

  const сохранить = useCallback(async () => {
    if (сохраняется.current) return
    if (!естьНесохранённое()) return
    сохраняется.current = true
    живойСтатусНачали()

    /*
     * Сессию читаем отсюда, а не из замыкания: замыкание хранит метку на
     * момент отрисовки, а сохранение может быть вызвано позже — после того как
     * метка уже сдвинулась. Сохранение по старой метке гарантированно
     * получало отказ от сервера, и метка от этого уже не отставала.
     */
    const живое = getSession()!

    try {
      const current = getDb()
      посланное.current = { db: current }
      const res = await saveDb(
        живое.apiUrl,
        живое.token,
        current,
        живое.lastSyncedAt,
        // Пока запрос ещё идёт, человек видит, что он ушёл заново. Молчать
        // тут нельзя: надпись «Сохраняю…» двадцать секунд выглядит как
        // зависшее приложение.
        () =>
          setState({
            kind: 'busy',
            note: {
              /*
               * Обрыв связи человек обычно не замечает: связь не рвётся
               * сразу, а зависает. Без надписи он решит, что приложение
               * подвисло, и начнёт править заново.
               */
              текст: СЛОВА.повторИдёт,
              детали: деталиЗапроса({
                адрес: живое.apiUrl,
                вид: 'запись базы, дубль после обрыва',
              }),
            },
          }),
      )

      const подробностиЗаписи = (попыток: number, код?: number, текстСервера?: string) =>
        деталиЗапроса({
          адрес: живое.apiUrl,
          вид: 'запись базы',
          код,
          попыток,
          меткаСервера: res.ok ? res.value.updatedAt : undefined,
          меткаСвоя: живое.lastSyncedAt,
          текстСервера,
        })

      if (res.ok) {
        setНеудач(0)
        setЖдатьДо(0)
        updateSession({ lastSyncedAt: res.value.updatedAt })
        живойСтатусУспех(res.value.updatedAt)
        сообщитьВкладкам(res.value.updatedAt)
        // Локальная метка должна совпасть с серверной, иначе следующая
        // правка снова сочтётся несохранённой.
        replaceDb({ ...current, updatedAt: res.value.updatedAt })
        // Повтор был виден уже во время отправки, но он мог и не выйти: дубль
        // уходит после ожидания, даже если первый запрос просто медленный.
        // Подтверждаем по счётчику попыток, а не по тому, показывали ли надпись.
        setState(
          res.попыток > 1
            ? { kind: 'ok', note: приПовторе(подробностиЗаписи(res.попыток)) }
            : { kind: 'ok', note: приУспехе(подробностиЗаписи(res.попыток)) },
        )
        return
      }

      /*
       * Отказ по правам при токене персонажа — это не запрет. Человек правил
       * своего персонажа, а у него в копии устарел сосед. Сервер присылает
       * актуальную базу: подставляем в неё своего персонажа и сохраняем
       * снова. Так правка уходит и чужое не теряется.
       */
      if (res.forbidden && свойCharId) {
        const чей = ктоЗатронут(current, res.forbidden.db, свойCharId)
        const слияние = слитьСвое(current, res.forbidden.db, свойCharId, авторПравки())

        if (слияние.персонажаНет) {
          replaceDb(слияние.db)
          updateSession({ lastSyncedAt: слияние.db.updatedAt })
          setState({
            kind: 'err',
            note: {
              текст: СЛОВА.персонажаУбрали,
              детали: подробностиЗаписи(1, res.статус, res.error),
            },
          })
          return
        }

        const повтор = await saveDb(
          живое.apiUrl,
          живое.token,
          слияние.db,
          res.forbidden.db.updatedAt,
        )
        if (!повтор.ok) {
          setНеудач((n) => n + 1)
          if (повтор.статус === 429) {
            const до = срокПослеЛимита(повтор.retryAfter)
            setЖдатьДо(до)
            живойСтатусЛимит(до, повтор.error)
            setState({
              kind: 'err',
              note: приЛимите(подробностиЗаписи(1, повтор.статус, повтор.error)),
            })
            return
          }
          if (повтор.статус === 0) живойСтатусОбрыв(повтор.error)
          else живойСтатусЗаметка(повтор.error)
          setState({ kind: 'err', note: приОтказе(повтор.error, повтор.статус, живое.apiUrl) })
          return
        }

        setНеудач(0)
        setЖдатьДо(0)
        replaceDb({ ...слияние.db, updatedAt: повтор.value.updatedAt })
        updateSession({ lastSyncedAt: повтор.value.updatedAt })
        живойСтатусУспех(повтор.value.updatedAt)
        сообщитьВкладкам(повтор.value.updatedAt)
        /*
         * Список подтянутых имён — уже не часть надписи. Он велик и к правке
         * человека отношения не имеет: чужую правку он не делал и проверять
         * её не собирался. В подробностях он и лежит.
         */
        setState({
          kind: 'ok',
          note: чей.length
            ? {
                текст: СЛОВА.сохраненоСЧужойПравкой,
                детали: `${деталиЗапроса({
                  адрес: живое.apiUrl,
                  вид: 'запись базы с подстановкой своей правки',
                  код: повтор.статус,
                  попыток: повтор.попыток,
                  меткаСервера: повтор.value.updatedAt,
                })}\nПодтянуто чужое: ${чей.join(', ')}`,
                убратьЧерезМс: 6000,
              }
            : приУспехе(
                деталиЗапроса({
                  адрес: живое.apiUrl,
                  вид: 'запись базы с подстановкой своей правки',
                  код: повтор.статус,
                  попыток: повтор.попыток,
                }),
              ),
        })
        return
      }

      /*
       * Персонажа удалили, пока человек правил.
       *
       * Правка в этом случае не сохранится, а сообщение о выборе между
       * двумя версиями бессмысленно: выбирать нечего, персонажа больше нет.
       */
      if (res.conflict && свойCharId && !res.conflict.chars.some((c) => c.id === свойCharId)) {
        replaceDb(res.conflict)
        updateSession({ lastSyncedAt: res.conflict.updatedAt })
        живойСтатусУспех(res.conflict.updatedAt)
        setIncoming(null)
        setState({
          kind: 'err',
          note: {
            текст: СЛОВА.персонажаУбрали,
            детали: подробностиЗаписи(1, res.статус, res.error),
          },
        })
        return
      }

      /*
       * Отказ после собственной записи — не чужое действие.
       *
       * Связь рвётся уже после того, как запрос до сервера дошёл, и тогда он
       * отвечает «в пати уже другое состояние», хотя менялась база ровно на ту,
       * которую просили. Сверяем отданное с лежащим: если там наше — запись
       * состоялась, а потерялся только ответ. Метку берём с сервера и
       * говорим об этом прямо: человек должен знать, что отправка потребовала
       * второй попытки, а не молчать.
       */
      const отданное = посланное.current
      if (res.conflict && отданное && одноИТоЖе(res.conflict, отданное.db)) {
        updateSession({ lastSyncedAt: res.conflict.updatedAt })
        if (одноИТоЖе(current, отданное.db)) {
          replaceDb({ ...current, updatedAt: res.conflict.updatedAt })
          setНеудач(0)
          setЖдатьДо(0)
          setState({
            kind: 'ok',
            note: приПотерянномОтвете(подробностиЗаписи(1, res.статус)),
          })
        }
        return
      }

      if (res.conflict) {
        setIncoming(res.conflict)
        setState({
          kind: 'err',
          note: {
            /*
             * Кто и когда — под значком. Надпись про то, что человек должен
             * сделать (выбрать версию), а не про то, кто именно нажал раньше.
             */
            текст: СЛОВА.вПаТИИзменилось,
            детали: `${деталиЗапроса({
              адрес: живое.apiUrl,
              вид: 'запись базы',
              код: res.статус,
              меткаСервера: res.conflict.updatedAt,
              меткаСвоя: живое.lastSyncedAt,
              текстСервера: res.error,
            })}\nВ пати правил: ${ктоПравил(res.conflict)}`,
          },
        })
        return
      }
      /*
       * Любой отказ сервера, кроме конфликта, — повод отступить.
       *
       * Раньше пауза росла только при обрыве связи, а отказ сервера повторялся
       * через те же полторы секунды. С исчерпанным лимитом GitHub это
       * превращалось в лавину: каждый повтор тратил остаток лимита и не давал
       * ему восстановиться, а человек видел мигающую надпись.
       *
       * Конфликт сюда не попадает: там выбирает человек, и до его выбора
       * повторять нечего. Обрыв тоже: он и так считается неудачей.
       */
      setНеудач((n) => n + 1)

      if (res.статус === 429) {
        setЖдатьДо(срокПослеЛимита(res.retryAfter))
        setState({
          kind: 'err',
          note: приЛимите(подробностиЗаписи(1, res.статус, res.error)),
        })
        return
      }

      /*
       * Последняя развилка: обрыв связи это или отказ.
       *
       * Разница в том, теряет человек правку или нет. Обрыв — не теряет: она
       * лежит в браузере и уйдёт сама, и надпись обязана это сказать, иначе
       * человек решит худшее и начнёт переписывать всё. Отказ — теряет: сервер
       * не взял правку, и надо сказать, что она не сохранена.
       */
      setState({
        kind: 'err',
        note:
          res.статус === 0
            ? приОбрыве(
                деталиЗапроса({
                  адрес: живое.apiUrl,
                  вид: 'запись базы',
                  попыток: 1,
                  меткаСвоя: живое.lastSyncedAt,
                  текстСервера: res.error,
                }),
              )
            : приОтказе(res.error, res.статус, живое.apiUrl),
      })
    } finally {
      сохраняется.current = false
    }
    посланное.current = null
  }, [свойCharId, сообщитьВкладкам])

  /*
   * Автосохранение.
   *
   * Пауза собирает несколько правок подряд в одну отправку: иначе набор
   * уровня и заточки дал бы десяток записей в репозиторий и десяток
   * коммитов на одну минуту работы.
   *
   * Пока открыта форма правки, ждать незачем — правки в базе ещё нет, и
   * отправлять нечего. Сама форма поставит её, когда нажмут «Сохранить».
   *
   * Пока ждёт выбора при конфликте, сохранять нельзя: человек ещё не решил,
   * чью версию оставить. Всё остальное решает таймер.
   *
   * Смену надписи в зависимостях нет намеренно. Эффект ставит «Сохраняю…»,
   * запись меняет надпись на «Связь оборвалась…» или на успех — и раньше
   * каждое такое изменение перезапускало эффект, ставило новый таймер поверх
   * старого. Теперь надпись может меняться сколько угодно: таймер один, и
   * планируется он только по настоящим поводам — правке, метке, неудаче.
   */
  useEffect(() => {
    if (формаОткрыта) return
    /*
     * Сохраняем только настоящую правку.
     *
     * Заглушка не в счёт: её метка своя, свежая, и без проверки приложение
     * решило бы, что человек правил, и отправило пустоту поверх настоящей
     * базы. Пустая метка сессии тоже не повод молчать: правка человека
     * настоящая, и молчание оставило бы её в браузере навсегда.
     */
    if (!естьНесохранённое()) return
    if (incoming) return

    const таймер = setTimeout(() => {
      /*
       * Проверка именно здесь, а не в теле эффекта.
       *
       * Тело эффекта тоже перезапускается, пока запись идёт, и проверка в нём
       * гасила бы всё до конца: ссылка ещё занята, эффект уходит, а переменяться
       * ей уже не на что — правка зависла бы до перезагрузки. Здесь проверка
       * просто снимает лишний таймер, а следующая попытка всё равно
       * запланируется по счётчику неудач.
       */
      if (сохраняется.current) return
      setState({ kind: 'busy', note: { текст: СЛОВА.сохраняю } })
      void сохранить()
    }, откатСохранения(неудач, ждатьДо))
    return () => clearTimeout(таймер)
  }, [db.updatedAt, session.lastSyncedAt, формаОткрыта, сохранить, incoming, неудач, ждатьДо])

  /**
   * Обновление само, пока вкладка открыта.
   *
   * Каждые семь секунд спрашиваем только лёгкую мету: имя, версию базы и
   * число персонажей. Полную базу тянем лишь тогда, когда версия изменилась.
   * Ответ сервер берёт из семисекундного снимка, а GitHub — условным
   * запросом, поэтому 304 не расходует основной лимит.
   *
   * Пауза растёт при неудачах: 7 → 14 → 28 → 56 секунд и не больше минуты.
   * Иначе оборванная связь превращалась бы в запрос каждые семь секунд.
   *
   * Скрытая вкладка не ходит совсем: проверка идёт при возвращении. Форма и
   * несохранённые правки тоже ставят опрос на паузу — серверную версию в этот
   * момент принимать нельзя, а мета всё равно ни на что не влияет.
   */
  useEffect(() => {
    let таймер: ReturnType<typeof setTimeout> | null = null
    let таймерПервого: ReturnType<typeof setTimeout> | null = null
    let остановлено = false

    const занято = () => формаОткрыта || естьНесохранённое()
    const можно = () =>
      document.visibilityState === 'visible' &&
      (typeof navigator === 'undefined' || navigator.onLine !== false) &&
      !занято() &&
      Date.now() >= ждатьДо

    const пауза = () => {
      const обычная = неудачПроверки.current === 0
        ? ПАУЗА_ПРОВЕРКИ_МС
        : Math.min(
            ПАУЗА_ПРОВЕРКИ_МС * 2 ** неудачПроверки.current,
            ПРЕДЕЛ_ПАУЗЫ_ПРОВЕРКИ_МС,
          )
      return Math.max(обычная, ждатьДо - Date.now(), 0)
    }

    const запланировать = (мс: number) => {
      if (остановлено) return
      if (таймер) clearTimeout(таймер)
      таймер = setTimeout(async () => {
        if (!можно()) {
          запланировать(пауза())
          return
        }
        await проверитьМету()
        if (!остановлено) запланировать(пауза())
      }, мс)
    }

    const прочитатьПервыйРаз = () => {
      setState({ kind: 'busy', note: { текст: СЛОВА.загружаю } })
      void загрузить(false)
    }

    /*
     * База этой пати ещё не прочитана — вход был без сети, и на экране пусто.
     * Ждать следующей проверки нельзя: человек смотрит на пустую пати и
     * думает, что она стёрта. Тянем сразу и говорим об этом надписью.
     *
     * Старая копия без признака «грязная» тоже требует немедленного чтения:
     * правкой она не считается, а расписание на сервере может быть свежее.
     *
     * Если известен срок лимита, «Загружаю…» на полчаса выглядело бы как
     * зависшее приложение. Поэтому ждём молча и говорим только перед попыткой.
     */
    const надо_прочитать = !базаПрочитана() || (!естьНесохранённое() && !session.lastSyncedAt)
    if (надо_прочитать && !формаОткрыта) {
      const ждать = Math.max(0, ждатьДо - Date.now())
      if (ждать === 0) прочитатьПервыйРаз()
      else таймерПервого = setTimeout(прочитатьПервыйРаз, ждать)
    }

    запланировать(надо_прочитать ? ПАУЗА_ПРОВЕРКИ_МС : 0)

    const приВидимости = () => {
      if (document.visibilityState !== 'visible') {
        if (таймер) {
          clearTimeout(таймер)
          таймер = null
        }
        return
      }
      запланировать(0)
    }

    const приФокусе = () => {
      if (document.visibilityState !== 'visible') return
      запланировать(0)
    }

    const приСети = () => {
      неудачПроверки.current = 0
      запланировать(0)
    }

    const безСети = () => {
      живойСтатусОбрыв('Браузер сообщил, что сети нет')
      if (таймер) {
        clearTimeout(таймер)
        таймер = null
      }
    }

    window.addEventListener('focus', приФокусе)
    document.addEventListener('visibilitychange', приВидимости)
    window.addEventListener('online', приСети)
    window.addEventListener('offline', безСети)
    return () => {
      остановлено = true
      if (таймер) clearTimeout(таймер)
      if (таймерПервого) clearTimeout(таймерПервого)
      window.removeEventListener('focus', приФокусе)
      document.removeEventListener('visibilitychange', приВидимости)
      window.removeEventListener('online', приСети)
      window.removeEventListener('offline', безСети)
    }
  }, [загрузить, проверитьМету, формаОткрыта, ждатьДо, session.lastSyncedAt])

  /*
   * Тело для отправки готовим заранее.
   *
   * Сжатие большой базы асинхронное, а на pagehide ждать его уже нельзя:
   * браузер выгрузит страницу раньше. Поэтому после каждой правки, пока
   * человек ещё работает, собираем тело в фоне — тогда при уходе остаётся
   * только отправить готовое.
   */
  useEffect(() => {
    if (формаОткрыта) return
    if (!естьНесохранённое()) return
    void prepareDbUpload(db, session.lastSyncedAt)
  }, [db, формаОткрыта, session.lastSyncedAt])

  /*
   * Уход со страницы.
   *
   * Мобильный браузер выгружает вкладку, не дожидаясь паузы автосохранения:
   * человек выбрал предмет, свернул приложение — и правка осталась только в
   * памяти, а на сервер не ушла. Обычный запрос в этот момент обрывается
   * вместе со страницей, поэтому отправляем короткий keepalive-запрос.
   *
   * Не ждём состояния «сейчас сохраняется»: именно зависшая отправка и
   * обрывается при уходе. Если она всё-таки дошла, повтор с той же меткой
   * сервер примет как свою же запись.
   */
  useEffect(() => {
    const отправитьПриУходе = () => {
      if (!естьНесохранённое()) return
      const живое = getSession()
      if (!живое) return

      /*
       * visibilitychange и pagehide приходят почти одновременно. Второй
       * запрос с тем же телом ничего не улучшит, а на телефоне ещё и
       * отнимает канал у первого.
       */
      if (Date.now() - уходОтправлен.current < 5000) return
      уходОтправлен.current = Date.now()

      const current = getDb()
      void saveDbKeepalive(живое.apiUrl, живое.token, current, живое.lastSyncedAt).then(
        (res) => {
          if (!res.ok) return
          /*
           * Пока запрос летел, человек мог вернуться и продолжить править.
           * Тогда метку не двигаем: следующее автосохранение отправит уже
           * новую версию.
           */
          const теперь = getDb()
          if (!одноИТоЖе(теперь, current)) return
          replaceDb({ ...теперь, updatedAt: res.value.updatedAt })
          updateSession({ lastSyncedAt: res.value.updatedAt })
          сообщитьВкладкам(res.value.updatedAt)
        },
      )
    }

    const приСкрытии = () => {
      if (document.visibilityState === 'hidden') отправитьПриУходе()
    }
    const приВыгрузке = () => отправитьПриУходе()

    document.addEventListener('visibilitychange', приСкрытии)
    window.addEventListener('pagehide', приВыгрузке)
    return () => {
      document.removeEventListener('visibilitychange', приСкрытии)
      window.removeEventListener('pagehide', приВыгрузке)
    }
  }, [сообщитьВкладкам])

  /*
   * Сообщение в разметке идёт раньше кнопки, а на экране оказывается слева от
   * неё: так полоса остаётся одной строкой и шапка не прыгает вниз каждый раз,
   * когда что-то сохранилось. Порядок задаёт не порядок в разметке, а
   * order в стилях, — но и в разметке сообщение впереди, чтобы тот, кто
   * читает код, видел то же, что видит человек.
   *
   * Кнопки выбора при конфликте — отдельная строка внизу: они зовут человека
   * что-то сделать, и он не должен выбирать их вслепую, не прочитав надпись.
   */
  return (
    <div className="sync">
      <div className="sync-feed">
        {state.kind === 'busy' && (
          <SyncMessage вид="идёт" сообщение={state.note} onОткрытие={запомнитьОткрытие} />
        )}
        {state.kind === 'ok' && (
          <SyncMessage вид="сделано" сообщение={state.note} onОткрытие={запомнитьОткрытие} />
        )}
        {state.kind === 'err' && (
          <SyncMessage вид="ошибка" сообщение={state.note} onОткрытие={запомнитьОткрытие} />
        )}

        {incoming && (
          <div className="sync-actions">
            <button
              className="btn primary tiny"
              onClick={() => {
                replaceDb(incoming)
                updateSession({ lastSyncedAt: incoming.updatedAt })
                setIncoming(null)
                setState({ kind: 'idle' })
              }}
            >
              Взять версию из пати
            </button>
            <button
              className="btn tiny"
              onClick={() => {
                /*
                 * Оставить своё — значит записать своё поверх того, что в пати.
                 *
                 * Раньше кнопка просто закрывала выбор, и это было ловушкой:
                 * метка оставалась прежней, автосохранение через паузу уходило с
                 * ней снова и снова, и то же самое сообщение возвращалось к
                 * человеку по кругу. Теперь метка становится свежей, правка
                 * действительно уходит поверх чужой, а токен персонажа на
                 * ответе о недостатке прав подставит в неё своего
                 * персонажа, как и раньше.
                 */
                const серверная = incoming
                setIncoming(null)
                setState({ kind: 'busy', note: { текст: СЛОВА.сохраняю } })
                updateSession({ lastSyncedAt: серверная.updatedAt })
                void сохранить()
              }}
            >
              Оставить мою
            </button>
          </div>
        )}
      </div>

      <div className="sync-main">
        <PartyMenu />
      </div>
    </div>
  )
}