import type { Pa } from '@/types'
import { paDateRu, paLeft, paUrgency, paUntil } from '@/lib/pa'

/**
 * Платёжный аккаунт в шапке персонажа: сколько дней осталось.
 *
 * Отдельной строкой под профессией, а не ещё одной плашкой в ряду метаданных:
 * там запас по ширине кончился на профессии и счётчике слотов, и ещё одна
 * плашка выдавила бы счётчик за карточку. Отдельной строкой она и видна
 * отдельно от «снаряжение занято», к чему относиться не хочется.
 *
 * Ничего не показывает, если ПА не заполнено: пустая плашка «ПА» без срока
 * только занимала бы место и выглядела бы как забытое значение.
 */
export function PaChip({ pa }: { pa?: Pa }) {
  const осталось = paLeft(pa)
  if (осталось === null || !pa) return null

  /*
   * Имена классов написаны словами, а не собираются из состояния: состояний
   * ровно три и они не добавятся, а класс, собранный в шаблоне, не виден
   * ни глазом в разметке, ни проверке стилей.
   */
  const срочность = paUrgency(осталось)
  const класс = срочность === 'over' ? 'chip pa over' : срочность === 'soon' ? 'chip pa soon' : 'chip pa'
  const подпись = срочность === 'over' ? 'ПА истёк' : `ПА ${осталось} дн.`

  return (
    <span
      className={класс}
      title={`Куплен ${paDateRu(pa.from)} на ${pa.days} дн., действует до ${paDateRu(paUntil(pa))}`}
    >
      {подпись}
    </span>
  )
}