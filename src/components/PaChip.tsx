import type { Pa } from '@/types'
import { paDateRu, paLeft, paUrgency, paUntil } from '@/lib/pa'

/**
 * Премиум аккаунт в шапке персонажа: сколько дней осталось.
 *
 * Стоит слева от кнопок действий, а не в ряду плашек с профессией: там
 * профессия, уровень и счётчик слотов, и запас по ширине кончается на
 * профессии — ещё одна плашка выдавила бы счётчик за карточку. Справа от
 * шапки перед кнопками для него место есть, и рядом с кнопками он читается
 * как «это можно исправить здесь», а не как ещё одно свойство снаряжения.
 *
 * Ничего не показывает, если премиум не заполнен: пустая плашка занимала бы
 * место и выглядела бы как забытое значение.
 */
export function PaChip({ pa }: { pa?: Pa }) {
  const осталось = paLeft(pa)
  if (осталось === null || !pa) return null

  /*
   * Имена классов написаны словами, а не собираются из состояния: состояний
   * ровно два и они не добавятся, а класс, собранный в шаблоне, не виден ни
   * глазом в разметке, ни проверке стилей.
   */
  const срочность = paUrgency(осталось)
  const класс = срочность === 'low' ? 'chip pa low' : 'chip pa'
  const подпись = осталось <= 0 ? 'Премиум истёк' : `Премиум ${осталось} дн.`

  return (
    <span
      className={класс}
      title={`Куплен ${paDateRu(pa.from)} на ${pa.days} дн., действует до ${paDateRu(paUntil(pa))}`}
    >
      {подпись}
    </span>
  )
}