import { useState } from 'react'
import type { Pa } from '@/types'
import { paDateRu, paLeft, paUrgency, paUntil } from '@/lib/pa'

/**
 * Премиум аккаунт в шапке персонажа: сколько дней осталось.
 *
 * Стоит в ряду плашек с профессией, уровнем и слотами. По нажатию плашка
 * переключается с остатка на дату окончания и обратно: «осталось 12 дней» —
 * это ответ на «сколько ещё», а «до 12.11.2026» — на «когда продлевать».
 * Обе цифры выводятся из одной записи, и держать ради второй отдельную
 * плашку значит занимать место в и без того тесной строке.
 *
 * Незаполненный премиум виден красным вопросом, а не пропадает: молчаливое
 * отсутствие читается как «всё в порядке», а вопрос — как «не сказано».
 */
export function PaChip({ pa }: { pa?: Pa }) {
  const [дата, setДата] = useState(false)
  const осталось = paLeft(pa)

  /*
   * Не заполнено — тоже показывается, красным и со знаком вопроса.
   *
   * Раньше плашка просто исчезала, и строка пати выглядела одинаково у того,
   * кто премиум купил и не покупал. Молчаливое отсутствие читается как «всё
   * в порядке», а вопрос — как «не сказано», и это разные вещи.
   */
  if (осталось === null || !pa) {
    return (
      <span className="chip pa low" title="Премиум аккаунт не заполнен: не указаны дата покупки и срок">
        Премиум ?
      </span>
    )
  }

  /*
   * Имена классов написаны словами, а не собираются из состояния: состояний
   * ровно два и они не добавятся, а класс, собранный в шаблоне, не виден ни
   * глазом в разметке, ни проверке стилей.
   */
  const срочность = paUrgency(осталось)
  const класс = `chip pa${срочность === 'low' ? ' low' : ''}`
  const конец = paUntil(pa)
  const подпись = дата
    ? осталось <= 0
      ? `истёк ${paDateRu(конец)}`
      : `до ${paDateRu(конец)}`
    : осталось <= 0
      ? 'Премиум истёк'
      : `Премиум ${осталось} дн.`

  return (
    <button
      type="button"
      className={класс}
      aria-pressed={дата}
      title={`${дата ? 'Показать остаток дней' : 'Показать дату окончания'}. Куплен ${paDateRu(pa.from)} на ${pa.days} дн., действует до ${paDateRu(конец)}`}
      onClick={() => setДата((v) => !v)}
    >
      {подпись}
    </button>
  )
}
