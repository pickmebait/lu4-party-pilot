import { useEffect, useState } from 'react'
import type { РодСообщения, Сообщение } from '@/lib/syncMessages'
import { IconInfo } from './Icons'

/**
 * Плашка сообщения о синхронизации.
 *
 * На виду короткая надпись: что произошло и что человеку с этим делать.
 * Рядом значок ⓘ, по нажатию на который раскрывается всё устройство — адрес,
 * код ответа, метки версий, ответ сервера.
 *
 * Разделено это потому, что надпись живёт в шапке и висит на виду всё время,
 * пока идёт работа, а подробности нужны совсем в другой момент: когда правка
 * не дошла и надо разбираться. Раньше всё это было одной строкой, и строка
 * получалась длинной, нечитаемой и одинаковой для обоих случаев — подходящей
 * ни для работы, ни для разбора.
 */
export function SyncMessage({
  вид,
  сообщение,
  onОткрытие,
}: {
  вид: РодСообщения
  сообщение: Сообщение
  /** Сообщить, открыты ли подробности: пока открыты, надпись не убирать. */
  onОткрытие?: (открыто: boolean) => void
}) {
  const [открыто, setОткрыто] = useState(false)

  /*
   * Закрываем подробности на новом сообщении.
   *
   * Без этого человек открыл подробности на одной неудаче, правил дальше, и
   * значок остался нажатым на следующем сообщении, которое ничего общего с
   * предыдущим не имеет. Читать надо то, что под значком именно сейчас.
   */
  useEffect(() => setОткрыто(false), [сообщение])

  useEffect(() => onОткрытие?.(открыто), [открыто, onОткрытие])

  const класс = вид === 'сделано' ? 'ok' : вид === 'ошибка' ? 'err' : ''
  const естьПодробности = Boolean(сообщение.детали)

  return (
    <div className="sync-note">
      <div className={`sync-msg ${класс}`.trim()}>
        <span className="sync-text">{сообщение.текст}</span>
        {естьПодробности && (
          <button
            type="button"
            className={`sync-info${открыто ? ' on' : ''}`}
            aria-expanded={открыто}
            aria-label={открыто ? 'Скрыть подробности' : 'Показать подробности'}
            title={открыто ? 'Скрыть подробности' : 'Подробности'}
            onClick={() => setОткрыто((v) => !v)}
          >
            <IconInfo size={12} />
          </button>
        )}
      </div>

      {естьПодробности && открыто && (
        <pre className="sync-details">{сообщение.детали}</pre>
      )}
    </div>
  )
}
