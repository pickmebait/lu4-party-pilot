import type { ДействияПерсонажа } from '@/lib/useCharActions'
import type { Char } from '@/types'
import { ConfirmModal } from './ConfirmModal'
import { ContactsModal } from './ContactsModal'

/**
 * Окна, которые открываются из карточки и строки персонажа.
 *
 * Форма правки стоит на своём месте в шапке, а контакты и подтверждения
 * удаления — это отдельные окна поверх раздела. Их разметка и тексты одни
 * и те же у обоих видов, поэтому живут здесь, а не дублируются в каждом.
 */
export function CharDialogs({
  char,
  правый,
  действия,
  onCloseContacts,
}: {
  char: Char
  правый: boolean
  действия: ДействияПерсонажа
  /** Дополнительное действие при закрытии контактов у строки. */
  onCloseContacts?: () => void
}) {
  return (
    <>
      {действия.contactsOpen && (
        <ContactsModal
          char={char}
          правый={правый}
          onClose={() => {
            действия.закрытьКонтакты()
            onCloseContacts?.()
          }}
        />
      )}

      {действия.confirmDelete && (
        <ConfirmModal
          заголовок={`Удалить «${char.name || 'персонажа'}»?`}
          текст="Вместе с персонажем пропадёт его снаряжение, отсутствия и контакты. Восстановить это нельзя — придётся собирать заново."
          кнопка="Удалить"
          onConfirm={действия.удалить}
          onCancel={действия.закрытьУдаление}
        />
      )}

      {действия.убираемыйСаб && (
        <ConfirmModal
          заголовок={`Удалить саб-класс${действия.убираемыйСаб.cls ? ` «${действия.убираемыйСаб.cls}»` : ''}?`}
          текст="Вместе с саб-классом пропадёт его снаряжение. Основная профессия и остальные сабы не пострадают."
          кнопка="Удалить саб"
          onConfirm={действия.удалитьСаб}
          onCancel={действия.закрытьУдалениеСаба}
        />
      )}
    </>
  )
}
