import { APP_NAME } from '@/lib/brand'

/**
 * Название приложения с пометкой стадии.
 *
 * Имя стоит в шапке и на экране входа. Пометка «pre-alpha» нужна там же:
 * человек должен видеть, что приложение ещё не готово, до того как начнёт
 * заводить пати. Отдельным компонентом — потому что две копии разметки
 * разъедутся так же незаметно, как когда-то разъехались подписи под именем.
 */
export function AppTitle() {
  return (
    <h1>
      {APP_NAME}
      <span className="stage" title="Ранняя версия: приложение ещё в разработке">
        pre-alpha
      </span>
    </h1>
  )
}
