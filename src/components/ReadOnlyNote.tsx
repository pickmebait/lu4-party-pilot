/**
 * Плашки «здесь только просмотр».
 *
 * Токен персонажа даёт право править ровно одного персонажа: казна,
 * цели, комплекты и расписание у пати общие, и править их нельзя.
 * Кнопок в этих разделах просто нет, и без плашки выглядит так, будто
 * раздел сломан — плашка объясняет, почему ничего не нажимается.
 *
 * Для расписания плашка своя: общее там только одно — прайм и выходные, а
 * отсутствие лежит внутри персонажа и своё отметить можно. Одна и та же
 * формулировка была бы там полуправдой и мешала бы нажать то, что доступно.
 */

export function ReadOnlyNote({ имя }: { имя: string }) {
  return (
    <p className="readonly-note">
      <b>Только просмотр.</b> Токен персонажа правит только {имя ? `«${имя}»` : 'свой персонаж'};
      этот раздел общий для всей пати. Правки вносит тот, у кого мастер-токен.
    </p>
  )
}

/**
 * Расписание: прайм и выходные — мастерские, отсутствие — своё.
 *
 * Сказано прямо, что можно: плашка, которая только запрещает, заставила бы
 * искать, где же тут всё-таки что-то нажать.
 */
export function ScheduleNote({ имя }: { имя: string }) {
  return (
    <p className="readonly-note">
      <b>Прайм и выходные ставит мастер.</b> Отсутствие отмечаешь себе:
      {' '}
      {имя ? `«${имя}»` : 'свой персонаж'} — выдели дни и нажми «Отметить».
    </p>
  )
}