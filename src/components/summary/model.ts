import type { EventKind } from '@/lib/l2events'

/**
 * Режимы сводки.
 *
 * «Общая» — это не период, а другой экран: штаб пати. Поэтому ключ режима
 * строкой, а не числом дней: иначе пришлось бы объяснять, почему ноль дней
 * значит «всё время», а не «сейчас».
 */
export type Режим = 'общая' | 30 | 90 | 0

/** Событие на оси прайма: минута от местной полуночи дня начала окна. */
export interface СобытиеОси {
  id: string
  kind: EventKind
  минута: number
  /** Короткое имя для подписи над осью. */
  name: string
  /** Время начала на часах пользователя. */
  время: string
  title: string
}

export const РЕЖИМЫ: { key: Режим; label: string }[] = [
  { key: 'общая', label: 'Общая' },
  { key: 30, label: 'За 30 дней' },
  { key: 90, label: 'За 90 дней' },
  { key: 0, label: 'За все время' },
]
